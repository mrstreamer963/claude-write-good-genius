// WebWorker: держит симуляцию (bevy_ecs -> WASM) и крутит фиксированный тик.
//
// Модель времени (§11 concept.md): dt тика постоянный, детерминизм не зависит от
// скорости. Множитель (0/1/5/10) = сколько сим-тиков в реальную секунду. Пауза = 0.
// Постройка теперь через чертежи: игрок тянет рамку, коты строят по тикам.
// Карту шлём при росте её версии (правки игрока + завершённые постройки).

import init, { Sim } from "./wasm/sp_sim.js";
import wasmUrl from "./wasm/sp_sim_bg.wasm?url";

const BASE_TPS = 6; // сим-тиков в секунду на ×1
const SIM_DT_MS = 1000 / BASE_TPS;
const MAX_STEPS_PER_FRAME = 2000;
// Автосохранение (§12.45) — по двум часам сразу, что наступит раньше.
//
// Тики меряют потерю в игровом времени и не зависят от скорости. Но на паузе
// они не идут вовсе, а игрок при этом размечает стройку, шлёт приказы и
// заказывает сделки — то есть меняет ровно то, что лежит в снимке. Поэтому
// вторые часы настенные.
//
// В §11 это не дыра: снимок снимается по `&World` и мир не трогает, поэтому
// момент фотографирования ни на что в симуляции повлиять не может. Настенное
// время решает «когда», а не «что».
const AUTOSAVE_EVERY = 120; // сим-тиков (20 с на ×1)
const AUTOSAVE_EVERY_MS = 20000; // и не реже этого по реальным часам

// Команды, которые мир не меняют: после них сохранять нечего.
const READ_ONLY = new Set(["setSpeed", "save", "trace", "setBuildTile"]);

let sim = null;
let speed = 1; // 0 (пауза) | 1 | 5 | 10
let acc = 0;
let last = 0;
let lastMapVersion = -1;
// Какой тайл игрок держит в руке. Нужен только маске правила доступа (§12.111):
// она зависит и от карты, и от чертежей, а те меняются между кадрами, поэтому
// считается каждым кадром заново. -1 = игрок не строит, считать нечего.
let maskTile = -1;
// Рамка, которую игрок тянет прямо сейчас; нулевая ширина = рамки нет. Внутри
// неё правило считается с накоплением, как при самой разметке: иначе превью
// обещало бы девять полок из мазка три на три, а разметилось бы восемь.
let maskRect = [0, 0, 0, 0];
// Текст рулсета нужен и после старта: из него собирается и новая партия, и
// загруженная — правил в снимке нет и быть не должно (§12.45).
let yamlText = null;
let sinceSave = 0;
let lastSaveAt = 0;
// Менялся ли мир с последнего снимка. Без этого вкладка, забытая на паузе,
// переписывала бы одно и то же каждые двадцать секунд до конца времён.
let dirty = false;

function announce() {
  lastMapVersion = sim.map_version();
  sinceSave = 0;
  lastSaveAt = performance.now();
  dirty = false;
  postMessage({ type: "ready", meta: sim.map_meta(), map: sim.base_map() });
}

async function boot() {
  await init(wasmUrl);
  yamlText = await (await fetch("/rulesets/core.yaml")).text();
  sim = new Sim(yamlText);
  announce();
  last = performance.now();
  loop();
}

function loop() {
  const now = performance.now();
  let dt = now - last;
  last = now;
  if (dt > 250) dt = 250;

  if (sim && speed > 0) {
    acc += dt * speed;
    let steps = 0;
    while (acc >= SIM_DT_MS && steps < MAX_STEPS_PER_FRAME) {
      sim.tick();
      acc -= SIM_DT_MS;
      steps++;
    }
    sinceSave += steps;
    if (steps > 0) dirty = true;
  } else {
    acc = 0;
  }

  // Снимок кладёт в localStorage главный поток: у воркера его нет вовсе.
  // Проверка снаружи ветки скорости — иначе на паузе она не выполнялась бы
  // никогда, а размеченное игроком терялось бы целиком.
  if (
    sim &&
    dirty &&
    (sinceSave >= AUTOSAVE_EVERY || now - lastSaveAt >= AUTOSAVE_EVERY_MS)
  ) {
    sinceSave = 0;
    lastSaveAt = now;
    dirty = false;
    postMessage({ type: "saved", json: sim.save(), auto: true });
  }

  if (sim) {
    const v = sim.map_version();
    if (v !== lastMapVersion) {
      postMessage({ type: "map", map: sim.base_map() });
      lastMapVersion = v;
    }
    // Маска едет вместе со снимком: она про тот же кадр. Пустая (тайл правилу
    // не подчиняется) — не едет вовсе, и рендер не красит ничего.
    const mask = maskTile >= 0 ? sim.buildable(maskTile, ...maskRect) : null;
    postMessage({
      type: "snapshot",
      snap: sim.snapshot(),
      mask: mask && mask.length ? mask : null,
    });
  }
  setTimeout(loop, 16);
}

onmessage = (e) => {
  const m = e.data;
  // Любая команда, кроме читающих, делает мир несохранённым — в том числе на
  // паузе, где тиков нет, а разметка есть.
  if (!READ_ONLY.has(m.type)) dirty = true;
  if (m.type === "setSpeed") {
    speed = m.speed;
  } else if (m.type === "setBuildTile") {
    // Инструмент в руке игрока — состояние вида, и живёт оно здесь: ядру он не
    // нужен ни для чего, кроме ответа «где этот тайл поставить можно».
    maskTile = m.tile;
    maskRect = m.rect ?? [0, 0, 0, 0];
  } else if (m.type === "build" && sim) {
    // Один жест игрока = одна рамка = один вызов. Ластик не сносит мгновенно:
    // сначала снимает чертежи в рамке, и только если снимать было нечего —
    // планирует снос, который выполняют коты (см. `plan_demolish_rect` в ядре).
    if (m.tile >= 0) sim.add_blueprint_rect(m.x, m.y, m.w, m.h, m.tile);
    else sim.plan_demolish_rect(m.x, m.y, m.w, m.h);
  } else if (m.type === "store" && sim) {
    // Разметка уборки: кота не выбираем — как и чертёж, задачу возьмёт любой
    // свободный. Повторный жест по помеченному снимает пометку.
    sim.mark_to_store_rect(m.x, m.y, m.w, m.h);
  } else if (m.type === "setAutoTidy" && sim) {
    sim.set_auto_tidy(m.on);
  } else if (m.type === "setAutoRest" && sim) {
    // Второй порог усталости: бросает ли кот работу, когда бодрость на исходе
    // (см. `set_auto_rest` в ядре, §12.33). Выключение никого не будит.
    sim.set_auto_rest(m.on);
  } else if (m.type === "move" && sim) {
    sim.set_target(m.id, m.x, m.y);
  } else if (m.type === "launch" && sim) {
    // **Узел заменяет выбор отряда** (§12.61): состав живёт на клетке рации, и
    // кнопка адресуется узлом, а не списком котов. С двумя узлами иначе не
    // сказать, чей отряд идёт. Состав, не подходящий заказу, ядро отклоняет
    // само — второй проверки в JS быть не должно.
    sim.launch_node(m.mission, m.x, m.y);
  } else if (m.type === "setAutoRaid" && sim) {
    // Правило, а не заявка (§12.67): команда пишет заказ на клетку узла, а в
    // поле отряд отправляет ядро — каждым тиком, пока отряд готов. Отсюда и
    // отсутствие пары «отменить»: `-1` и есть снятие, как ноль у порога.
    sim.set_auto_raid(m.mission, m.x, m.y);
  } else if (m.type === "setAutoRaidOn" && sim) {
    // Пауза, а не снятие (§12.77): заказ остаётся на узле, но отряд по нему не
    // уходит. Так рутину прерывают на разовое дело — разгрести привезённое, —
    // не выбирая потом тот же заказ второй раз.
    sim.set_auto_raid_on(m.x, m.y, m.on);
  } else if (m.type === "cancelMission" && sim) {
    // По заказу: вылазок теперь идёт столько, сколько узлов связи (§12.59), а
    // порядок сущностей в ядре недетерминирован — по номеру отзывался бы то
    // один отряд, то другой. Двух вылазок по одному заказу не бывает.
    sim.cancel_mission(m.mission);
  } else if (m.type === "research" && sim) {
    // Тема — разметка работы: кота не выбираем, за неё сядет ближайший, кому
    // хватает «Науки» (см. `start_research` в ядре, §12.26). Платит склад.
    sim.start_research(m.topic);
  } else if (m.type === "cancelResearch" && sim) {
    sim.cancel_research(m.topic);
  } else if (m.type === "craft" && sim) {
    // Заказ — разметка работы со счётчиком штук: кота не выбираем, к верстаку
    // встанет ближайший свободный (см. `start_craft` в ядре, §12.30). Склад
    // платит за каждую штуку отдельно, поэтому пустой склад заявку не отменяет —
    // заказ ждёт материала.
    sim.start_craft(m.recipe, m.count);
  } else if (m.type === "setStock" && sim) {
    // Порог — **правило, а не заказ** (§12.64): команда пишет число, а заказы
    // заводит и снимает ядро каждым тиком. Отсюда и отсутствие пары «отменить»:
    // ноль и есть отмена.
    sim.set_stock(m.recipe, m.min);
  } else if (m.type === "cancelCraft" && sim) {
    // **По клетке** (§12.96): заказов на один рецепт бывает несколько, и рецепт
    // их больше не различает, — а ячейка различает полностью. Довод против
    // номера строки прежний: порядок сущностей в ядре недетерминирован, и
    // закрывшийся сосед сдвинул бы номера под курсором игрока.
    sim.cancel_craft(m.x, m.y);
  } else if (m.type === "teach" && sim) {
    // Обучение адресно: игрок решает судьбу конкретного кота, а не размечает
    // работу базе (см. `teach` в ядре, §12.18).
    sim.teach(m.id, m.skill);
  } else if (m.type === "unteach" && sim) {
    // Снять с учёбы: с §12.84 обучение — приписка, и без своей команды отменить
    // её можно было только приказом «иди туда», то есть побочным действием.
    sim.unteach(m.id);
  } else if (m.type === "enlist" && sim) {
    // Зачисление в отряд узла — адресно, как приписка связиста (§12.61): это
    // конфигурация, которая переживает вылазку, а не разовый выбор перед уходом.
    sim.enlist(m.id, m.x, m.y);
  } else if (m.type === "dismiss" && sim) {
    // Вычёркивание мира не трогает: ушедшего держит `Squad`, а не состав узла.
    sim.dismiss(m.id);
  } else if (m.type === "postRelay" && sim) {
    // Приписка связиста к узлу — адресно, как обучение (§12.60): игрок решает
    // судьбу конкретного кота. Это **конфигурация**, а не разовая посадка: за
    // рацию его сажает раздатчик и возвращает после голода и сна.
    sim.post_relay(m.id, m.x, m.y);
  } else if (m.type === "unpostRelay" && sim) {
    // Отмена снимает и текущее дежурство: иначе связист досидел бы до конца
    // вылазки, и игрок решил бы, что кнопка не сработала.
    sim.unpost_relay(m.id);
  } else if (m.type === "trade" && sim) {
    // Сделка с внешним миром (см. `trade` в ядре, §12.44). Курс фиксируется
    // здесь и сейчас, покупка платится сразу, а товар едет `lead` тиков.
    // Команды отмены нет намеренно: деньги ушли, как уходят образцы за тему.
    sim.trade(m.faction, m.item, m.count, m.buying);
  } else if (m.type === "setSale" && sim) {
    // Порог автопродажи — **правило, а не сделка** (§12.87): команда пишет
    // число, а заявки подаёт ядро каждым тиком, пока есть излишек. Ноль и есть
    // снятие, как у порога производства. Адресат — та же пара «фракция +
    // предмет», по которой продают руками: у продажи есть сторона, и выбирает
    // её игрок, а не «кто в этот тик даёт больше».
    sim.set_sale(m.faction, m.item, m.keep);
  } else if (m.type === "setSalvage" && sim) {
    // Второй адресат **того же** правила (§12.115): пишется в тот же слот, что
    // и порог сбыта, поэтому «разбирать сверх N» стирает «продавать сверх K»
    // вместе с покупателем. Два правила на один излишек спорили бы за один и
    // тот же предмет, и кто победит, решал бы порядок вызовов в ядре.
    sim.set_salvage_rule(m.item, m.keep);
  } else if (m.type === "setFavorite" && sim) {
    // Избранное — закладка, а не правило (§12.100): она поднимает строку наверх
    // окна «Склад» и больше ничего не делает. Ворот у неё нет вовсе, поэтому
    // закрепить можно и то, чем не торгует никто.
    sim.set_favorite(m.item, m.on);
  } else if (m.type === "setTicker" && sim) {
    // Тикер — вторая закладка и другой вопрос (§12.100): строка уезжает лентой
    // на главный экран, и там по ней торгуют в один клик. Сторона поэтому
    // обязательна и проверяется прайсом — теми же воротами, что у `set_sale`.
    sim.set_ticker(m.item, m.faction, m.on);
  } else if (m.type === "hire" && sim) {
    // Известность открывает кандидата, платит склад (см. `hire` в ядре, §12.24).
    sim.hire(m.recruit);
  } else if (m.type === "save" && sim) {
    // Один запрос, два адресата: `toSlot` — это уход со вкладки (пишем в
    // хранилище), без него — кнопка «Сохранить в файл».
    if (m.toSlot) {
      sinceSave = 0;
      lastSaveAt = performance.now();
      dirty = false;
    }
    postMessage({ type: "saved", json: sim.save(), auto: !!m.toSlot });
  } else if (m.type === "load" && yamlText) {
    // Снимок собирается в мир из **того же** рулсета: правил в нём нет (§12.45).
    // Отказ — это чужая версия формата или чужой рулсет, и он именно отказ:
    // молча загруженная чужая партия была бы тихо другим миром.
    try {
      sim = Sim.load(yamlText, m.json);
      announce();
    } catch (err) {
      postMessage({
        type: "loadFailed",
        message: String((err && err.message) || err),
      });
    }
  } else if (m.type === "newGame" && yamlText) {
    sim = new Sim(yamlText);
    announce();
  } else if (m.type === "trace" && sim) {
    postMessage({ type: "traced", text: sim.trace() });
  }
};

boot().catch((err) =>
  postMessage({ type: "error", message: String((err && err.stack) || err) }),
);
