import { defineConfig } from 'vite';

// Рулсеты лежат в общей папке assets/ (вне web/) и раздаются как статика:
//   assets/rulesets/core.yaml  ->  http://localhost:5173/rulesets/core.yaml
export default defineConfig(({ command, isPreview }) => ({
  root: '.',
  publicDir: '../assets',
  // Dev работает от корня, а GitHub Pages публикует project site
  // под именем репозитория.
  //
  // `isPreview` тут обязателен: у `vite preview` команда — `serve`, то есть по
  // одному `command` он раздавал бы собранный `dist` от корня, а внутри HTML
  // стоят абсолютные `/cats-of-base/...`. Получался 404 на главном чанке —
  // причём похожий на поломку деплоя, хотя ломался только сам просмотр.
  base: command === 'build' || isPreview ? '/cats-of-base/' : '/',
  // Порт можно занять снаружи (PORT): 5173 бывает занят соседним запуском, а
  // адрес превью должен совпадать с тем, что вправду слушает Vite.
  server: { port: Number(process.env.PORT) || 5173 },
  worker: { format: 'es' },
  // PixiJS поднимается через `await app.init(...)` на верхнем уровне модуля, и
  // это не случайность: инициализация асинхронна, а весь модуль ниже опирается
  // на готовый `app`. Целевой набор Vite по умолчанию (`modules` = es2020 и
  // браузеры 2020 года) top-level await не умеет, поэтому dev-сервер собирался,
  // а продакшн-сборка падала. es2022 — первый уровень, где он есть.
  build: {
    target: 'es2022',
    rollupOptions: {
      output: {
        // Весь PixiJS — одним отдельным чанком, и это не про размер, а про
        // работоспособность продакшн-сборки.
        //
        // `main.js` поднимает Pixi через `await app.init(...)` на верхнем
        // уровне модуля, то есть входной чанк остаётся «вычисляющимся», пока
        // init не вернётся. А init внутри делает
        // `await import('./gl/WebGLRenderer.mjs')` — и Rollup по умолчанию
        // складывает общий код Pixi во **входной** чанк, отчего ленивый чанк
        // рендерера начинает зависеть от него. Замыкается кольцо: вход ждёт
        // init, init ждёт чанк рендерера, чанк ждёт, когда довычислится вход.
        // Файл при этом отдаётся с 200, промис просто никогда не разрешается —
        // ни ошибки в консоли, ни канваса на странице.
        //
        // ⚠️ Dev-сервер этого не показывает **никогда**: там модули не склеены,
        // Pixi вычисляется до вызова init, и кольца не возникает. Ловится
        // только продакшн-сборкой (`npm run build` + `npm run preview`),
        // поэтому правку вида проверять и на ней, а не только на `make dev`.
        //
        // Отдельный чанк разрывает кольцо: и рендерер, и окружение (`browserAll`)
        // уезжают туда же, где лежит остальной Pixi, и их динамические импорты
        // становятся локальными — без сети и без ожидания входного чанка.
        manualChunks: (id) =>
          id.includes('node_modules/pixi.js') ? 'pixi' : undefined,
      },
    },
  },
}));
