/// Предмет. Порядок записей `items:` — индекс, который лежит в кучах, в лапах
/// и в ценах тайлов и уходит в снапшот (§12.21).
#[derive(Debug, Deserialize, Clone, Serialize)]
pub(crate) struct ItemDef {
    pub(crate) id: String,
    #[serde(default)]
    pub(crate) label: String,
    pub(crate) color: String,
    /// Сколько силы предмет добавляет отряду, если надет (§12.29). Больше нуля =
    /// это снаряжение. Свойство предмета, а не отдельная сущность: та же схема,
    /// по которой `capacity` делает тайл складом, — вещь значит что-то сверх
    /// цвета, оставаясь обычным предметом в кучах, в лапах и на складе.
    #[serde(default)]
    pub(crate) force: i32,
    /// Сколько заживления за тик добавляет израсходованная аптечка (§12.47).
    /// Больше нуля = это аптечка. Тот же переключатель-свойство, что `force` и
    /// `nutrition`: лечение остаётся работой медика, а предмет только ускоряет.
    #[serde(default)]
    pub(crate) mends: i32,
    /// Сколько сытости даёт одна съеденная штука (§12.36). Больше нуля = это
    /// еда, и голодный кот придёт к куче с ней сам. Тот же
    /// переключатель-свойство, что и `force`: кухни как отдельной сущности нет.
    #[serde(default)]
    pub(crate) nutrition: i32,
}

