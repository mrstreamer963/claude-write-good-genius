//! Рулсет (YAML) — data-driven контент в стиле OpenXcom Extended.
//!
//! Порядок записей `tiles:` — это индекс палитры: он уходит в рендер, приходит
//! обратно в командах постройки и лежит в клетках карты. Переставить записи в
//! рулсете = переназначить смысл всех уже записанных индексов.

use std::collections::BTreeMap;

use serde::{Deserialize, Serialize};

#[derive(Debug, Deserialize)]
pub(crate) struct Ruleset {
    pub(crate) grid: GridDef,
    #[serde(default)]
    pub(crate) items: Vec<ItemDef>,
    #[serde(default)]
    pub(crate) tiles: Vec<TileDef>,
    #[serde(default)]
    pub(crate) build: Vec<BuildRect>,
    #[serde(default)]
    pub(crate) stock: Vec<StockDef>,
    #[serde(default)]
    pub(crate) units: Vec<UnitDef>,
    #[serde(default)]
    pub(crate) skills: Vec<SkillDef>,
    #[serde(default)]
    pub(crate) stats: Vec<StatDef>,
    #[serde(default)]
    pub(crate) perks: Vec<PerkDef>,
    #[serde(default)]
    pub(crate) factions: Vec<FactionDef>,
    #[serde(default)]
    pub(crate) missions: Vec<MissionDef>,
    #[serde(default)]
    pub(crate) recruits: Vec<RecruitDef>,
    #[serde(default)]
    pub(crate) research: Vec<ResearchDef>,
    #[serde(default)]
    pub(crate) recipes: Vec<RecipeDef>,
    #[serde(default)]
    pub(crate) timeline: Vec<EventDef>,
    #[serde(default)]
    pub(crate) goals: Vec<GoalDef>,
    /// Сколько лома кот уносит за одну ходку. Ноль = без предела (правило
    /// выключено), как `cost: 0` у тайла. Перк «Носильщик» удваивает (§12.17).
    #[serde(default)]
    pub(crate) carry: i32,
    /// Сколько тиков в сутках (§12.4, §12.46) — **подача, а не механика**.
    /// Ядро о календаре не знает и ни одна система это число не читает: оно
    /// уходит в `meta` и разворачивается в «день 12» на стороне вида. Второй
    /// сущности времени не заводится (§12.28), тик остаётся единственными
    /// часами мира. Ноль = календаря нет, вид покажет сырой тик.
    #[serde(default)]
    pub(crate) day: u64,
    /// Шаблон снаряжения: `id` предметов, которые кот носит (§4.2, §12.29).
    /// Один на всех — редактор шаблонов это интерфейс поверх выбора, которого
    /// на POC нет. Пусто = снаряжения в мире нет.
    #[serde(default)]
    pub(crate) loadout: Vec<String>,
    #[serde(default)]
    pub(crate) energy: EnergyDef,
    #[serde(default)]
    pub(crate) food: FoodDef,
    #[serde(default)]
    pub(crate) health: HealthDef,
}

/// Здоровье (§12.37). `max: 0` — механика выключена: коты не ранятся и лечиться
/// не ходят. Так живут тесты чужих механик, как и с выключенным голодом.
///
/// Отдельный блок по той же причине, что и `food:`: своя шкала, свой порог и своя
/// цена. Общего с бодростью и сытостью у неё нет даже тиканья — здоровье само не
/// убывает вовсе, его роняет только вылазка.
#[derive(Debug, Deserialize, Clone, Default)]
pub(crate) struct HealthDef {
    /// Полное здоровье. Само не тратится: на базе кот не ранится ничем.
    #[serde(default)]
    pub(crate) max: i32,
    /// Ниже этого кот выбывает: бросает начатое, ложится лечиться и в отряд не
    /// берётся. Порог один — второго нет намеренно (§12.37).
    #[serde(default)]
    pub(crate) hurt: i32,
    /// Заживление за тик там, где лазарета нет, — цена базы без него. Ровно тот
    /// же `floor`, что у сна: лечиться можно где угодно, вопрос только в сроке.
    #[serde(default)]
    pub(crate) mend: i32,
}

/// Голод (§12.36). `max: 0` — механика выключена: сытости у котов нет, за едой
/// они не ходят. Так живут тесты чужих механик, как и с выключенной усталостью.
///
/// Отдельный блок, а не поля в `energy:`: у голода своя шкала, свой порог и своя
/// цена, и включать их порознь должно быть можно.
#[derive(Debug, Deserialize, Clone, Default)]
pub(crate) struct FoodDef {
    /// Полная сытость; тратится по очку за тик — и во сне тоже.
    #[serde(default)]
    pub(crate) max: i32,
    /// Ниже этого свободный кот идёт есть сам. Второго порога у голода нет
    /// намеренно: с работы кота уводит бодрость, а не голод (§12.36).
    #[serde(default)]
    pub(crate) hungry: i32,
    /// Во сколько раз быстрее горит бодрость на пустой желудок. Это вся цена
    /// голода: он стоит сил, а не жизни.
    #[serde(default)]
    pub(crate) starve: i32,
}

/// Усталость (§12.20). `max: 0` — механика выключена: бодрости у котов нет,
/// спать они не ходят. Так живут тесты чужих механик.
#[derive(Debug, Deserialize, Clone, Default)]
pub(crate) struct EnergyDef {
    /// Полная бодрость.
    #[serde(default)]
    pub(crate) max: i32,
    /// Сколько бодрости уходит за тик бодрствования (§12.70). Из него
    /// вычитается ступень «Выносливости», поэтому число обязано быть заметно
    /// больше единицы: на шкале «очко за тик» разница в ступень означала бы
    /// кратный разброс, и это ровно та причина, по которой работа считается в
    /// очках, а не в тиках (инвариант 9).
    ///
    /// Ноль = расход в единицу, как было до §12.70.
    #[serde(default)]
    pub(crate) drain: i32,
    /// Ниже этого свободный кот идёт спать сам.
    #[serde(default)]
    pub(crate) tired: i32,
    /// Ниже этого кот бросает начатое и уходит спать (§12.33). Ноль — второго
    /// порога нет: кот доработает до нуля и свалится где стоит.
    #[serde(default)]
    pub(crate) critical: i32,
    /// Восстановление там, где лежанки нет, — цена базы без зоны отдыха.
    #[serde(default)]
    pub(crate) floor: i32,
    /// Докуда высыпаются там, где лежанки нет (§12.52). Ноль — до полной.
    /// Ниже `tired` он означает, что на полу кот только отлёживается: выспаться
    /// можно лишь в кровати, и зона отдыха становится обязательной.
    #[serde(default)]
    pub(crate) floor_wake: i32,
}

#[derive(Debug, Deserialize, Clone)]
pub(crate) struct GridDef {
    pub(crate) width: i32,
    pub(crate) height: i32,
}

#[derive(Debug, Deserialize, Clone, Serialize)]
pub(crate) struct TileDef {
    pub(crate) id: String,
    #[serde(default)]
    pub(crate) label: String,
    pub(crate) color: String,
    /// Что нужно завезти, чтобы возвести тайл: `{ предмет: сколько }`; снос
    /// возвращает то же самое (§12.15, §12.21). Пусто = бесплатно.
    ///
    /// `BTreeMap`, а не `HashMap`: порядок обхода цены доходит до раздачи задач,
    /// а недетерминизм ломает и тесты, и модель времени (§11).
    #[serde(default)]
    pub(crate) cost: BTreeMap<String, i32>,
    /// Сколько лома клетка хранит. Больше нуля = это склад: коты сами свозят
    /// сюда всё, что валяется на полу (§12.16). Ноль = обычный пол.
    #[serde(default)]
    pub(crate) capacity: i32,
    /// Сколько бодрости кот восстанавливает здесь за тик. Больше нуля = лежанка,
    /// уставшие коты идут спать сюда (§12.20). Ноль = спать можно, но медленно.
    #[serde(default)]
    pub(crate) rest: i32,
    /// Докуда здесь высыпаются: на этом уровне сон кончается и начинается
    /// дремота (§12.52). Ноль = до полной. Второе число места для сна после
    /// `rest`: гнездо отличается от лежанки не только скоростью.
    #[serde(default)]
    pub(crate) wake: i32,
    /// Сколько здоровья кот восстанавливает здесь за тик. Больше нуля = койка
    /// лазарета, раненые ложатся сюда (§12.37). Близнец `rest`, и правило то же:
    /// ноль — лечиться можно, просто дольше.
    #[serde(default)]
    pub(crate) heal: i32,
    /// Шлюз: отсюда отряд уходит на вылазку и сюда же возвращается с добычей
    /// (§12.22). Четвёртое свойство той же схемы после `cost`/`capacity`/`rest`:
    /// комната значит что-то сверх цвета, а карта остаётся одним слоем.
    #[serde(default)]
    pub(crate) gate: bool,
    /// Парта: `id` навыка, которому учит клетка (§12.18). Пусто — не учит.
    /// Пятое свойство той же схемы: обучение — это работа, у которой есть
    /// место, а не отдельный экран.
    #[serde(default)]
    pub(crate) teaches: String,
    /// Лаборатория: здесь идёт работа над темой исследования (§12.26).
    #[serde(default)]
    pub(crate) lab: bool,
    /// Мастерская: здесь идёт работа над заказом (§12.30). Седьмое свойство той
    /// же схемы — комната значит что-то сверх цвета, а карта остаётся слоем.
    #[serde(default)]
    pub(crate) shop: bool,
    /// Стеллаж и всё, что заставлено доверху: пройти клетку можно, **остаться
    /// на ней нельзя** (§12.35). Восьмое свойство той же схемы — комната значит
    /// что-то сверх цвета, а карта остаётся одним слоем.
    #[serde(default)]
    pub(crate) solid: bool,
    /// Торговый пост: без него база не торгует с внешним миром (§12.44).
    /// Девятое свойство той же схемы — и **первое, за которым никто не
    /// работает**: это лицензия, а не рабочее место. Сделку заключает игрок, а
    /// товар едет к шлюзу, поэтому сажать сюда кота не за чем.
    #[serde(default)]
    pub(crate) trade: bool,
    /// Сколько штук влезает в **один контейнер** этого поста (§12.90). Ноль —
    /// без предела.
    ///
    /// Второе число у той же клетки, как `comms` при `relay` и `wake` при
    /// `rest`: первое говорит, что это за место, второе — насколько оно велико.
    /// Без него пост ограничивал бы **число** сделок, но не объём, и одна
    /// автопродажа увозила бы через единственную ячейку хоть пятьсот штук —
    /// то есть второй пост становился бы не нужен.
    #[serde(default)]
    pub(crate) lot: i32,
    /// Узел связи: держит одну вылазку (§12.59). Десятое свойство той же схемы
    /// и **вторая лицензия** после торгового поста — сам по себе узел только
    /// считается, сколько узлов, столько отрядов база выводит разом.
    #[serde(default)]
    pub(crate) relay: bool,
    /// Сколько силы даёт отряду **полное дежурство** на этом узле (§12.60).
    ///
    /// Второе число у той же клетки, как `wake` при `rest`: первое говорит, что
    /// это за место, второе — насколько оно хорошо. Ноль значит «дежурить тут
    /// незачем», и раздатчик кота сюда не зовёт: гонять его к рации, от которой
    /// нет пользы, — это отнятое котовремя без всякой отдачи.
    #[serde(default)]
    pub(crate) comms: i32,
    /// Технология, которая открывает постройку этого тайла (§12.27). Пусто —
    /// доступен с первого тика. Это вторые ворота прогрессии после известности:
    /// та открывает вылазки и котов, эта — саму базу.
    #[serde(default)]
    pub(crate) tech: String,
}

/// Тема исследования. Порядок записей `research:` — индекс, который уходит в
/// интерфейс и приходит обратно в команде запуска, как у миссий.
///
/// Кого посадить за тему, рулсет не описывает: исполнителя берёт симуляция —
/// но только из тех, кому хватает «Науки» (§12.26).
#[derive(Debug, Deserialize, Clone, Serialize)]
pub(crate) struct ResearchDef {
    /// Он же имя технологии на выходе: у темы и результата одно имя.
    pub(crate) id: String,
    #[serde(default)]
    pub(crate) label: String,
    /// Уровень «Науки», ниже которого за тему не берутся. Это допуск (§12.18):
    /// без навыка нельзя вовсе, а не медленно. Ноль — возьмётся любой кот.
    #[serde(default)]
    pub(crate) level: i32,
    /// Очки работы, как у чертежа: `WORK_RATE` плюс уровень исполнителя за тик.
    #[serde(default)]
    pub(crate) work: i32,
    /// Чем платим: `{ предмет: сколько }` со склада — образцы с вылазок и
    /// детали. `BTreeMap` по той же причине, что и цена тайла (§12.21).
    #[serde(default)]
    pub(crate) cost: BTreeMap<String, i32>,
    /// Технологии, без которых темы не существует: дерево из §4.3.
    #[serde(default)]
    pub(crate) requires: Vec<String>,
}

/// Рецепт: что мастерская делает из чего (§12.30). Порядок записей `recipes:` —
/// индекс, который уходит в интерфейс и приходит обратно в команде заказа.
///
/// Кого поставить к верстаку, рулсет не описывает: исполнителя берёт симуляция,
/// и **допуска по навыку здесь нет** — рецепт открывает технология, а «Ремесло»
/// только ускоряет работу.
#[derive(Debug, Deserialize, Clone, Serialize)]
pub(crate) struct RecipeDef {
    pub(crate) id: String,
    #[serde(default)]
    pub(crate) label: String,
    /// Очки работы на одну штуку, как у тайла (120 = 12 тиков новичку).
    #[serde(default)]
    pub(crate) work: i32,
    /// Чем платим за штуку: `{ предмет: сколько }` со склада. Списывается в
    /// момент, когда за штуку берутся, а не при заказе (§12.30).
    #[serde(default)]
    pub(crate) cost: BTreeMap<String, i32>,
    /// Что выходит: `{ предмет: сколько }`. Ложится кучей под ноги мастеру.
    #[serde(default)]
    pub(crate) gives: BTreeMap<String, i32>,
    /// Технологии, без которых рецепта не существует, — те же ворота, что и у
    /// тайла (§12.27).
    #[serde(default)]
    pub(crate) requires: Vec<String>,
}

/// Событие таймлайна: дата, к которой база либо готова, либо нет (§12.28).
///
/// Записка (§4.6) — это и есть список таких записей: даты известны заранее,
/// детали «повреждены» и проступают ближе к сроку. Что именно скрыто, решает
/// ядро (`reveal`), а не интерфейс, — иначе «повреждённые данные» это просто
/// непоказанный текст, лежащий в JS.
#[derive(Debug, Deserialize, Clone, Serialize)]
pub(crate) struct EventDef {
    pub(crate) id: String,
    #[serde(default)]
    pub(crate) label: String,
    /// Тик, на котором событие происходит. Дата — номер тика, а не отдельный
    /// календарь: второй счётчик времени был бы вторым источником правды.
    pub(crate) at: u64,
    /// За сколько тиков до срока проступают детали. Ноль — видны сразу.
    #[serde(default)]
    pub(crate) reveal: u64,
    /// «Скелет» события: виден всегда, ещё до раскрытия.
    #[serde(default)]
    pub(crate) hint: String,
    /// Подробности: чем это грозит и что спасает. Приходят только с `reveal`.
    #[serde(default)]
    pub(crate) detail: String,
    /// Технологии, к которым база должна успеть. Пусто — событие безусловно
    /// доброе (караван просто приходит).
    #[serde(default)]
    pub(crate) requires: Vec<String>,
    /// Что придёт к шлюзу, если база готова: `{ предмет: сколько }`.
    #[serde(default)]
    pub(crate) gift: BTreeMap<String, i32>,
    /// Известность за готовность — те же ворота, что и от вылазок (§12.24).
    #[serde(default)]
    pub(crate) fame: i32,
    /// Во сколько бодрости обходится неготовность каждому коту **на базе**:
    /// ушедших мир не касается, как не касается их и усталость (§12.22).
    #[serde(default)]
    pub(crate) toll: i32,
}

/// Цель партии: то, ради чего игрок вообще здесь (§12.58).
///
/// Ярлык и подпись — **разные тексты, и путать их нельзя**: `label` называет
/// достижение и остаётся навсегда («Первая аптечка»), `hint` говорит, что надо
/// сделать, и гаснет в момент взятия («собрать аптечку в мастерской»). Один
/// текст на оба означал бы галочку «аптечка есть на базе» ровно тогда, когда
/// аптечки уже нет.
///
/// Условие задаётся **ровно одним** из полей ниже — словарь замкнут (`GoalTest`).
/// Способ достижения рулсет не описывает: игрок ищет его сам, в этом вся затея.
#[derive(Debug, Deserialize, Clone, Serialize)]
pub(crate) struct GoalDef {
    pub(crate) id: String,
    /// Название достижения: именное и в прошедшем смысле.
    #[serde(default)]
    pub(crate) label: String,
    /// Что надо сделать, инфинитивом. Гаснет, когда цель взята.
    #[serde(default)]
    pub(crate) hint: String,
    /// Скрытая: не видна, пока не взята, в счёт не идёт, финал не держит
    /// (§12.58). Для целей, которых нельзя требовать, — «вернуть кота из плена».
    #[serde(default)]
    pub(crate) hidden: bool,

    // --- Условия-состояния: каков мир прямо сейчас. Расходуемы.
    /// `id` тайла, который должен быть построен.
    #[serde(default)]
    pub(crate) tile: Option<String>,
    /// Сколько клеток такого тайла; ноль или нет — одна.
    #[serde(default)]
    pub(crate) count: i32,
    /// `{ предмет: сколько }` **на складе** — том, которым платят (§12.53).
    #[serde(default)]
    pub(crate) stored: BTreeMap<String, i32>,
    /// `id` изученной технологии.
    #[serde(default)]
    pub(crate) tech: Option<String>,
    /// Сколько котов у базы, считая ушедших и пленных.
    #[serde(default)]
    pub(crate) cats: i32,

    // --- Условия-журналы: что случилось хоть раз. Не расходуемы.
    /// `id` вылазки, которую надо завершить успешно.
    #[serde(default)]
    pub(crate) raid: Option<String>,
    /// `id` рецепта, по которому надо сделать штуку. Именно сделать: «предмет
    /// есть на базе» засчитал бы покупку и добычу, то есть мимо смысла цели.
    #[serde(default)]
    pub(crate) craft: Option<String>,
    /// Сколько котоденег надо заработать продажей за партию.
    #[serde(default)]
    pub(crate) earned: i32,
}

/// Сколько котов уходит на вылазку: `[минимум, предел]` либо одно число, если
/// минимум и предел совпадают (§12.70).
///
/// Две формы вместо одной — ради читаемости контента: у большинства заказов
/// вилка есть, но у вылазки за своим её нет и быть не должно (`squad: 1`),
/// и писать там `[1, 1]` значило бы делать вид, что выбор есть.
#[derive(Debug, Deserialize, Clone, Serialize)]
#[serde(untagged)]
pub(crate) enum SquadSize {
    Exact(usize),
    Range([usize; 2]),
}

impl SquadSize {
    /// Минимум и предел. Одиночное число разворачивается в `[n, n]`.
    pub(crate) fn bounds(&self) -> (usize, usize) {
        match *self {
            SquadSize::Exact(n) => (n, n),
            SquadSize::Range([min, max]) => (min, max),
        }
    }
}

/// Миссия — вылазка за пределы базы. Порядок записей `missions:` — индекс,
/// который уходит в интерфейс и приходит обратно в команде запуска.
///
/// Кого послать, рулсет не описывает — это выбор игрока (§12.23).
#[derive(Debug, Deserialize, Clone, Serialize)]
pub(crate) struct MissionDef {
    pub(crate) id: String,
    #[serde(default)]
    pub(crate) label: String,
    /// Сколько котов уходит: `[минимум, предел]` (§12.70). Минимум — сколько
    /// нужно, чтобы вылазка вообще состоялась; предел — сколько бригада может
    /// увести с собой. Одним числом это писалось до §12.70, и оно значило
    /// «ровно столько»; такая запись по-прежнему принимается и разворачивается
    /// в `[n, n]`.
    ///
    /// Диапазон здесь потому, что уходят **все, кто готов** (§12.70): спящий,
    /// раненый и не вернувшийся остаются дома, а вылазка идёт, если оставшихся
    /// хватает на минимум. Меньший состав платит за это сроком и долей — но
    /// платит, а не ждёт.
    pub(crate) squad: SquadSize,
    /// Дорога до места и обратно, в тиках. **От состава не зависит** (§12.70):
    /// дорога — свойство места, а не отряда, и она же не даёт сроку схлопнуться
    /// в ноль на большой бригаде.
    pub(crate) travel: i32,
    /// Работа на месте, в очках — их отряд вырабатывает сообща, по очку за тик
    /// на каждую лапу (§12.70). Это та же идиома, что `BUILD_WORK` у тайла
    /// (инвариант 9), вынесенная за шлюз: на базе очки набивает один кот, в поле
    /// — отряд. Ноль = работы на месте нет, срок равен одной дороге.
    #[serde(default)]
    pub(crate) work: i32,
    /// Сложность. Сравнивается с силой отряда (по коту — 1 плюс его уровень
    /// «Вылазки»): хватило — вся добыча, не хватило — доля, вдвое меньше
    /// нужного — провал (§12.23). Ноль = вылазка удаётся всегда.
    #[serde(default)]
    pub(crate) danger: i32,
    /// Во сколько бодрости обходится вылазка каждому коту. Списывается разом
    /// при возвращении: сама вылазка не симулируется, она считается (§12.22).
    /// Провал забирает всю бодрость — коты падают у шлюза.
    #[serde(default)]
    pub(crate) toll: i32,
    /// Во сколько здоровья обходится полный провал; частичный успех ранит той же
    /// долей, какой недобрал добычи (§12.37). Ноль = с вылазки возвращаются
    /// целыми, чего бы там ни было. Это и есть цена провала, которой у вылазки
    /// не было: бодрость восстанавливается сама и бесплатно, а выбывший кот —
    /// это сотни тиков без работника.
    #[serde(default)]
    pub(crate) harm: i32,
    /// Добыча при полном успехе: `{ предмет: сколько }`. Частичный успех даёт
    /// свою долю от каждой позиции. `BTreeMap` по той же причине, что и у цены
    /// тайла, — порядок обхода должен быть детерминирован (§12.21).
    #[serde(default)]
    pub(crate) loot: BTreeMap<String, i32>,
    /// Сколько известности приносит полный успех; доля добычи — та же доля
    /// известности. Провал не приносит ничего, но и не отнимает (§12.24).
    #[serde(default)]
    pub(crate) fame: i32,
    /// Сколько известности нужно, чтобы взяться. Ворота, а не подсказка:
    /// заявку ниже порога ядро отклоняет.
    #[serde(default)]
    pub(crate) requires: i32,
    /// Чей это заказ (`id` фракции); пусто — ничей, вылазка нейтральна (§4.4).
    #[serde(default)]
    pub(crate) patron: String,
    /// Кому этот заказ поперёк; пусто — никому.
    ///
    /// Заказчик и пострадавший — **два отдельных поля, а не набор**
    /// `{фракция: сколько}` (§12.43). Набор позволил бы написать заказ, который
    /// нравится всем сразу, то есть фракции без решения — ровно то, что §12.24
    /// однажды отверг. Разными полями это невыразимо.
    #[serde(default)]
    pub(crate) against: String,
    /// На сколько успех двигает репутацию: заказчику вверх, пострадавшему вниз,
    /// **ровно настолько же**. Идёт той же долей, что и добыча, — значит провал
    /// не двигает её вовсе (§12.43).
    #[serde(default)]
    pub(crate) standing: i32,
    /// **Пол** доверия: `{ фракция: сколько }`, ниже которого заказ не дают.
    /// Известность — порог, к которому идут снизу вверх, а это порог, ниже
    /// которого падают: одна отвечает «дорос ли ты вообще», другая — «станут ли
    /// с тобой говорить именно эти». `BTreeMap` по той же причине, что у цены и
    /// добычи, — порядок обхода детерминирован (§12.21).
    #[serde(default)]
    pub(crate) needs: BTreeMap<String, i32>,
    /// Вылазка за своим (§12.40): идут не за добычей, а за котом, оставшимся в
    /// плену после провала. Тот же переключатель, что `gate` у тайла и `force`
    /// у предмета, и меняет он ровно два правила: заявку принимают, только пока
    /// есть кого спасать, а успех **возвращает пленных** — вместо добычи или
    /// вместе с ней, если рулсет её всё-таки задал.
    ///
    /// Своих пленных такая вылазка не оставляет никогда, даже провалившись:
    /// иначе неудачное спасение плодило бы второго пленника, и база уходила бы
    /// в спираль — тот же довод, по которому известность не убывает (§12.24).
    #[serde(default)]
    pub(crate) rescue: bool,
}

/// Кандидат на найм. Коты уникальны (§4.2), поэтому это не «юнит такого-то
/// типа», а конкретный кот со своей биографией: нанимается один раз и приходит
/// уже умеющим — ровно тот «навык из найма», который предсказал §12.18.
#[derive(Debug, Deserialize, Clone, Serialize)]
pub(crate) struct RecruitDef {
    pub(crate) id: String,
    #[serde(default)]
    pub(crate) label: String,
    pub(crate) sprite: String,
    /// Сколько известности нужно, чтобы он вообще откликнулся.
    #[serde(default)]
    pub(crate) requires: i32,
    /// Чем платим: `{ предмет: сколько }` со склада. Известность не тратится —
    /// она открывает, а платят предметами (§12.24).
    #[serde(default)]
    pub(crate) cost: BTreeMap<String, i32>,
    /// С каким опытом приходит: `{ навык: очки }`. Уровень выводится из опыта
    /// по порогам, второго места для него не заводится (§12.17).
    #[serde(default)]
    pub(crate) skills: BTreeMap<String, i32>,
    /// Врождённые параметры: `{ параметр: сколько }` (§12.42). Ровно то, ради
    /// чего игрок смотрит на кандидата: опыт добирается работой, а предел дан
    /// раз и навсегда. `BTreeMap` по той же причине, что и цена, — порядок
    /// обхода должен быть детерминирован (§12.21).
    #[serde(default)]
    pub(crate) stats: BTreeMap<String, i32>,
    #[serde(default)]
    pub(crate) perks: Vec<String>,
    /// Пол доверия, ниже которого кандидат не откликается (§12.43). Только
    /// **ворота**: найм репутацию не двигает — это покупка, а не поступок, и
    /// платить ею значило бы сделать её валютой, то есть ровно то, что §12.24
    /// отверг у известности.
    #[serde(default)]
    pub(crate) needs: BTreeMap<String, i32>,
}

#[derive(Debug, Deserialize, Clone)]
pub(crate) struct BuildRect {
    pub(crate) tile: String,
    /// [x, y, w, h] в тайлах
    pub(crate) rect: [i32; 4],
}

