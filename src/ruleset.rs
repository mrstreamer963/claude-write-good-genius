#[derive(Debug, Deserialize, Clone, Serialize)]
pub(crate) struct PerkDef {
    pub(crate) id: String,
    #[serde(default)]
    pub(crate) label: String,
}

/// Навык — домен работы, а не действие игрока: стройка и снос это один навык,
/// потому что и джоб у них один (§12.17).
///
/// Порядок записей `skills:` — индекс домена, как порядок `tiles:` для палитры:
/// он лежит в `Skills::xp` и уходит в снапшот. Код обращается к навыку по `id`,
/// поэтому записи можно переставлять, но не переименовывать.
#[derive(Debug, Deserialize, Clone, Serialize)]
pub(crate) struct SkillDef {
    pub(crate) id: String,
    #[serde(default)]
    pub(crate) label: String,
    /// Пороги опыта: сколько всего очков нужно на 1-й, 2-й, … уровень. Длина
    /// списка — потолок навыка, выше него опыт не копится.
    #[serde(default)]
    pub(crate) levels: Vec<i32>,
    /// До какого уровня доводит парта (§12.18). Ноль — домену не учат вовсе:
    /// так живёт «Стройка», доступная с первого тика. Обучение — вход в домен,
    /// мастерство — из домена, поэтому потолок парты ниже потолка навыка.
    #[serde(default)]
    pub(crate) taught: i32,
    /// Врождённый параметр, которым домен ограничен (§12.42): `id` записи в
    /// `stats:`. Пусто — домен не ограничен ничем, и в нём все коты дорастают
    /// до потолка: так живут «Ремесло» и «Медицина».
    #[serde(default)]
    pub(crate) stat: String,
    /// Сколько параметра нужно на 2-й, 3-й, … уровень. Список начинается со
    /// **второго** уровня намеренно: первый параметром не закрыт никогда —
    /// вход в домен это допуск, и живёт он у навыка (`taught`), а не здесь
    /// (§12.19: параметр — мягкий предел, а не запрет).
    #[serde(default)]
    pub(crate) demands: Vec<i32>,
}

/// Фракция внешнего мира (§4.4, §4.5, §12.43). Порядок записей `factions:` —
/// это индекс, который лежит в `Standing` и уходит в снапшот, как порядок
/// `items:` для предметов и `stats:` для параметров.
///
/// Что фракция делает, знает не она, а вылазка: `patron`, `against` и
/// `standing` у записи в `missions:`. Здесь только подпись, цвет и предел.
#[derive(Debug, Deserialize, Clone, Serialize)]
pub(crate) struct FactionDef {
    pub(crate) id: String,
    #[serde(default)]
    pub(crate) label: String,
    /// Цвет фишки в интерфейсе: репутаций несколько, и различать их числом одним
    /// игрок не станет.
    #[serde(default)]
    pub(crate) color: String,
    /// Предел репутации **в обе стороны**. Дно достижимо и конечно: дорога назад
    /// всегда ограничена сверху, а не углубляется с каждым заказом. Он же делает
    /// репутацию рисуемой — знаковое число без границ нечем показать полоской.
    /// Ноль = без предела.
    #[serde(default)]
    pub(crate) span: i32,
    /// Сколько тиков идёт от заказа до поставки (§12.44). У одних дольше и
    /// дешевле, у других быстро и с наценкой — второе лицо развилки §12.43.
    /// Ноль = привозят тем же тиком.
    #[serde(default)]
    pub(crate) lead: i32,
    /// Наценка на покупку в процентах: купить всегда дороже, чем продать. Это и
    /// есть та потеря, из-за которой торговля не создаёт богатства, а только
    /// меняет его состав, — и она же защита от перевозки товара по кругу между
    /// фракциями.
    #[serde(default)]
    pub(crate) spread: i32,
    /// Насколько репутация двигает курс, в процентах при полном доверии.
    /// Репутация при этом **не тратится** (§12.43): она делает цену лучше или
    /// хуже, а не оплачивает её.
    #[serde(default)]
    pub(crate) favor: i32,
    /// Сколько тиков держится одна фаза расписания. Ноль = курс не меняется.
    #[serde(default)]
    pub(crate) period: u64,
    /// Расписание базовых курсов: `{ предмет: [фаза, фаза, …] }`. Фазу выбирает
    /// **тик** — это чистая функция времени, никакого рандома (§11), и потому
    /// расписание видно вперёд: игрок планирует, а не караулит с секундомером
    /// (§12.40).
    ///
    /// Предмета в списке нет — фракция им не торгует. Отдельного флага для этого
    /// не нужно: так и выражается «Полиция берёт образцы, Синдикат — лом».
    #[serde(default)]
    pub(crate) prices: BTreeMap<String, Vec<i32>>,
}

/// Врождённый параметр кота (§12.19, §12.42). Порядок записей `stats:` — это
/// индекс, который лежит в `Stats` и уходит в снапшот, как порядок `skills:`
/// для навыков и `items:` для предметов.
///
/// Что параметр делает, знает не он, а навык: `stat` + `demands` у записи в
/// `skills:`. Здесь только подпись — как у перка.
#[derive(Debug, Deserialize, Clone, Serialize)]
pub(crate) struct StatDef {
    pub(crate) id: String,
    #[serde(default)]
    pub(crate) label: String,
    /// На каких значениях параметр даёт ступень — те же пороги, что `demands` у
    /// навыка, но для самого параметра, а не для предела домена (§12.70).
    ///
    /// Ступень нужна там, где параметр работает **прямо сейчас**, а не потолком:
    /// у «Реакции» ею режется опасность вылазки, у «Выносливости» — расход
    /// бодрости. Сырое значение 1–10 туда пускать нельзя — разброс вышел бы
    /// десятикратным, а пороги дают 0…4 и одну шкалу на все применения.
    ///
    /// Пусто — параметр ступеней не даёт, то есть ничего не делает сверх
    /// потолка. Так живут параметры, которым сегодня нечего ускорять.
    #[serde(default)]
    pub(crate) steps: Vec<i32>,
}
