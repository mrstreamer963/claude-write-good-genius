//! Дежурство на узле связи: кот сидит у рации и прибавляет силы отряду в поле
//! (§12.60).
//!
//! # Зачем это отдельная задача
//!
//! §12.59 сделал узел лицензией-слотом: сколько узлов, столько вылазок. Сам по
//! себе узел при этом ничего не делал — стоял и считался. Дежурство даёт ему
//! второй смысл и заводит **первое место, где кот на базе влияет на исход
//! вылазки**: до сих пор всё, что решало исход, уходило вместе с отрядом.
//!
//! # Место в порядке раздатчиков — предпоследнее
//!
//! `assign_relay` стоит перед `assign_nap` и после всех работ: на узел садится
//! только тот, кому ничего не досталось. Бонус берётся **из простоя**, а не
//! отнимается у стройки, — потому он и «приятный».
//!
//! **Но раз сел — сидит.** Появившийся чертёж дежурного не срывает: занятость в
//! этом проекте это набор фильтров, и `OnDuty` попадает в них наравне с
//! остальными одиннадцатью задачами (инвариант 7). Вводить для этого ничего не
//! пришлось — исключением была ровно дремота, у которой своего компонента нет и
//! быть не должно (§12.52). Отсюда и всё поведение: на загруженной базе кот
//! рано или поздно освобождается, садится к рации и держит её до конца вылазки,
//! а не отдаёт первому же появившемуся чертежу.
//!
//! # Приписка — конфигурация, а не задача
//!
//! Игрок может назначить связиста сам (`Posted`). Это **не** разовая посадка:
//! голод и сон снимают `OnDuty`, но не приписку, и раздатчик вернёт кота к
//! рации, как только тот освободится. Разовая посадка повторила бы дыру парты —
//! игрок кликнул, кот поел и больше не вернулся, — а пропажу связи видно только
//! просевшим бонусом на возвращении, то есть поздно.
//!
//! Приписанный вытесняет самосевшего: узел держит одного, как парта и лежанка.
//!
//! # Связь считается за тик, а не на возвращении
//!
//! Каждый тик, пока отряд в поле и на его узле сидит дежурный, в `Mission`
//! падает вклад — «сила узла плюс уровень связиста». На возвращении это делится
//! на длину вылазки, то есть бонус пропорционален **доле времени со связью**.
//!
//! Мерить связь одним замером нельзя ни на уходе, ни на возвращении: в первом
//! случае хватило бы посадить кота на тик, во втором бонус повис бы на том, кто
//! случайно оказался у рации в последний тик, — а это уже не решение игрока, а
//! расписание. Делить приходится потому, что иначе длинная вылазка копила бы
//! бонус просто длиной.

use bevy_ecs::prelude::*;

use crate::components::*;
use crate::map::BaseMap;
use crate::path::Reach;
use crate::skills::{SKILL_RELAY, level_of};

/// Вклад связиста в силу отряда за один тик дежурства (§12.60).
///
/// Сила самого узла (`relay` у тайла) плюс уровень «Связи» дежурного: рация
/// работает и без мастера, но мастер выжимает из неё больше. Домен здесь свой,
/// а не «Вылазка», намеренно — см. `SKILL_RELAY`.
pub(crate) fn duty_gain(
    tiles: &TileRules,
    map: &BaseMap,
    skill_rules: &SkillRules,
    skills: Option<&Skills>,
    spot: (i32, i32),
) -> i32 {
    let power = tiles.comms_of(map.tile_at(spot.0, spot.1));
    if power <= 0 {
        return 0;
    }
    let level = skill_rules
        .index_of(SKILL_RELAY)
        .map_or(0, |s| level_of(skill_rules, skills, s));
    power + level
}

/// Сколько связь прибавила к силе отряда: набежавшее за вылазку, делённое на её
/// длину (§12.60).
///
/// Зовут двое — `run_missions` на возвращении и `snapshot` для прогноза в
/// панели, — и разойтись им нельзя: это та же дисциплина, что у
/// `missions::outcome` и `trade::quote` (инвариант 14). Полное дежурство даёт
/// ровно силу узла плюс уровень связиста, половинное — половину.
pub(crate) fn relay_force(covered: i32, ticks: i32) -> i32 {
    match ticks > 0 {
        // Округление **к ближайшему**, а не отбрасывание дробной части. При
        // силе рации в единицу деление нацело давало бы ноль всю вылазку и
        // единицу в последний тик: связь, оборванная на минуте от конца, стоила
        // бы всего бонуса целиком — ровно то «всё или ничего», от которого счёт
        // за тик и уводит. С округлением цена обрыва пропорциональна настолько,
        // насколько это вообще выразимо в целых.
        true => (covered * 2 + ticks) / (2 * ticks),
        false => 0,
    }
}

/// Сажает свободного кота к рации того узла, чей отряд сейчас в поле.
///
/// **Предпоследний раздатчик** (§12.60): всё, что раздаёт работу, уже
/// отработало, и на узел садится только тот, кому ничего не досталось. Дремота
/// идёт после — она раздаёт не работу, а её отсутствие (§12.52).
///
/// Узел просит кота, **только пока его вылазка в поле**: дежурство — первая
/// задача без естественного конца, и без этого условия кот сидел бы у рации с
/// пустым эфиром до скончания партии. Оно же снимает задачу, когда отряд
/// вернулся: искать, где ещё её снять, не приходится.
///
/// Ничью решает `id` кота, как во всех раздатчиках (инвариант 9): порядок
/// обхода сущностей ECS зависит от истории вставок и недетерминирован.
#[allow(clippy::too_many_arguments)]
pub(crate) fn assign_relay(
    map: Res<BaseMap>,
    tiles: Res<TileRules>,
    mut commands: Commands,
    missions: Query<(Entity, &Mission)>,
    crew: Query<(&Squad, Option<&Away>)>,
    // Кто уже сидит: занятость держит сам `OnDuty`, отдельного реестра нет —
    // ровно как у лежанки (`Rest::spot`) и станка (`Craft::spot`).
    posted: Query<(Entity, &UnitId, &OnDuty, Option<&Posted>)>,
    free_cats: Query<
        (Entity, &UnitId, &Position, Option<&Posted>),
        (
            Without<Assignment>,
            Without<Haul>,
            Without<Rest>,
            Without<Study>,
            Without<Researching>,
            Without<Crafting>,
            Without<Equipping>,
            Without<Eating>,
            Without<Healing>,
            Without<Treating>,
            Without<Squad>,
            Without<OnDuty>,
            Without<Away>,
            Without<Path>,
        ),
    >,
) {
    // Узлы, которым сейчас нужна связь: отряд ушёл, вылазка идёт, **и дежурство
    // тут что-то даёт**. Нулевой `comms` значит «дежурить незачем», и кота сюда
    // не зовут: гонять его к рации, от которой нет пользы, — это отнятое
    // котовремя без отдачи. Тем же нулём механика выключена в синтетических
    // схемах, как выключены навыки, рынок и цели.
    let wanted: Vec<(i32, i32)> = missions
        .iter()
        .filter(|(e, _)| crew.iter().any(|(s, away)| s.0 == *e && away.is_some()))
        .map(|(_, m)| m.node)
        .filter(|&(x, y)| tiles.comms_of(map.tile_at(x, y)) > 0)
        .collect();

    // Кто сидит зря: вылазка кончилась или узел снесли. Снимаем сразу — это и
    // есть конец задачи, второго места для него заводить не надо.
    for (cat_e, _, duty, _) in &posted {
        let gone = !tiles.is_relay_node(map.tile_at(duty.spot.0, duty.spot.1));
        if !wanted.contains(&duty.spot) || gone {
            commands.entity(cat_e).remove::<OnDuty>();
        }
    }

    // Узлы, к которым приписан свободный кот. Приписка — решение игрока, и
    // держится оно не только в момент команды: самосевший уступает место, как
    // только приписанный освободился. Иначе приписка честна ровно до тех пор,
    // пока рацию не занял кто-то другой, — а игроку сказано, что она навсегда.
    let claimed: Vec<(i32, i32)> = free_cats
        .iter()
        .filter_map(|(.., post)| post.map(|p| p.spot))
        .filter(|spot| wanted.contains(spot))
        .collect();
    let mut evicted: Vec<Entity> = Vec::new();
    for (cat_e, _, duty, post) in &posted {
        let mine = post.is_some_and(|p| p.spot == duty.spot);
        if !mine && claimed.contains(&duty.spot) {
            commands.entity(cat_e).remove::<OnDuty>();
            evicted.push(cat_e);
        }
    }

    let taken: Vec<(i32, i32)> = posted
        .iter()
        .filter(|(e, _, d, _)| wanted.contains(&d.spot) && !evicted.contains(e))
        .map(|(_, _, d, _)| d.spot)
        .collect();
    let mut open: Vec<(i32, i32)> = wanted
        .iter()
        .copied()
        .filter(|spot| !taken.contains(spot))
        .collect();
    open.sort_unstable_by_key(|&(x, y)| (y, x));
    if open.is_empty() {
        return;
    }

    // Приписанные — первыми, и каждый только к своему узлу: это решение игрока,
    // а не раздача (§12.18). Дальше — все свободные подряд, по `id`.
    let mut idle: Vec<(bool, &str, Entity, (i32, i32), Option<(i32, i32)>)> = free_cats
        .iter()
        .map(|(e, id, p, post)| {
            (
                post.is_none(), // false сортируется вперёд: приписанные первыми
                id.0.as_str(),
                e,
                (p.x, p.y),
                post.map(|p| p.spot),
            )
        })
        .collect();
    idle.sort_unstable_by_key(|&(loose, id, ..)| (loose, id));

    for (_, _, cat_e, at, post) in idle {
        if open.is_empty() {
            return;
        }
        let reach = Reach::all(&map, at);
        // Приписанный идёт только на свой узел: сажать его к чужой рации значило
        // бы отменить решение игрока молча.
        let picked = match post {
            Some(spot) => open
                .iter()
                .position(|&s| s == spot && reach.dist_at(s.0, s.1).is_some()),
            None => open
                .iter()
                .enumerate()
                .filter_map(|(i, &(x, y))| reach.dist_at(x, y).map(|d| (d, i)))
                .min_by_key(|&(d, i)| (d, i))
                .map(|(_, i)| i),
        };
        let Some(i) = picked else { continue };
        let spot = open.remove(i);
        let path = reach.path_to(spot.0, spot.1).unwrap_or_default();
        commands
            .entity(cat_e)
            .insert((OnDuty { spot }, Path { steps: path }, MoveCooldown(0)));
    }
}
