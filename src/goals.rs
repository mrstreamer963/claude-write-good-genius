//! Цели партии: то, ради чего игрок вообще здесь (§12.58).
//!
//! До этого модуля PoC был песочницей без запроса: все механики работали, но
//! никто не говорил, зачем их трогать. Набор целей и есть ответ — **закрыть все
//! семь**, а способ игрок ищет сам: цель называет результат и не называет рецепт.
//!
//! # Цель — наблюдатель, а не актор
//!
//! `check_goals` стоит **последней в цепочке** и ничего не делает с миром: она
//! читает уже сложившийся тик и отмечает, что случилось. Крючков по системам
//! работы нет ни одного, и заводить их нельзя — это десять мест вместо одного,
//! и однажды одно забудут.
//!
//! # Два вида условий, и путать их нельзя
//!
//! * **Состояние** — каков мир прямо сейчас (100 лома на складе). Расходуемо.
//! * **Журнал** — что случилось хоть раз (сделал аптечку). Не расходуемо и из
//!   состояния не выводится.
//!
//! Правило выбора: **ярлык описывает поступок → условие обязано быть журнальным.**
//! Состояние на месте поступка врёт дважды. Засчитывает чужое: «аптечка есть на
//! базе» закроется покупкой на рынке или добычей с вылазки, хотя смысл цели — в
//! мастерской. И не засчитывает своё: «денег 50» не закроется у того, кто продал
//! на сотню и потратил её, хотя торговал он дважды.
//!
//! Журналов три (`Raids`, `Crafted`, `Earned`), и каждый пишется **ровно в одном
//! месте** — там, где событие происходит: `run_missions`, `work_craft`,
//! `work_hauls`. Четвёртый обязан заводиться так же.
//!
//! # Три статуса и срок
//!
//! Цель либо **обязательна** (идёт в счёт «Цели N/7» и держит финал), либо
//! **необязательна** (видна с начала, но партию не держит), либо **скрыта** (её
//! не существует, пока не взята). Срок (`before`) бывает только у
//! необязательной, и это не вкус: обязательная цель с просроченным сроком —
//! молчаливый проигрыш по времени, а скрытая не даёт к сроку целиться (§12.158).
//! Сторож на это стоит в `tests/goals.rs`.
//!
//! # Взятая цель не снимается
//!
//! `Goals` только растёт, как `Chronicle`, `Fame` и `Techs`. Потраченный лом не
//! отнимает «Кладовую»: условие расходуемо, а поступок нет. Ровно поэтому ярлык
//! цели пишется в прошедшем смысле («Первая аптечка»), а не в настоящем
//! («аптечка есть на базе»): второе превратилось бы в галочку, которая врёт.

use bevy_ecs::prelude::*;

use crate::components::*;
use crate::hauling::stored_counts;
use crate::map::BaseMap;

/// Сколько уже есть и сколько надо — для счётчика в панели («74 / 100»).
///
/// Зовут двое: `check_goals` (порог) и `snapshot` (показ), и разойтись им
/// нельзя — иначе панель покажет одно, а засчитается другое (инвариант 14, тот
/// же довод, что у `missions::outcome` и `trade::quote`).
///
/// У целей без числа возвращает `(0, 0)` либо `(1, 1)` — «нет» и «есть»: панели
/// этого хватает, чтобы не рисовать полоску там, где мерить нечего.
pub(crate) fn progress_of(tests: &[GoalTest], w: &WorldFacts) -> (i32, i32) {
    // Узкое место всей связки — тем же выражением, каким `Stored` выбирает самый
    // дальний предмет набора (§12.158). Полоска обязана показывать то, из-за
    // чего цель ещё не взята, а не среднее по условиям: среднее у цели с пятью
    // требованиями стоит на трёх четвертях, когда сделано ноль из последнего.
    tests
        .iter()
        .map(|test| one_progress(test, w))
        .min_by_key(narrowest)
        .unwrap_or((0, 0))
}

/// Ключ «насколько далеко до этого условия»: доля от нужного, а не остаток.
/// Остаток сравнил бы 900 недостающего лома с 40 недостающей репутации, хотя
/// первого набирается вдесятеро больше за то же время.
fn narrowest((have, need): &(i32, i32)) -> i32 {
    (have * 100).checked_div(*need).unwrap_or(0)
}

fn one_progress(test: &GoalTest, w: &WorldFacts) -> (i32, i32) {
    match test {
        GoalTest::Tile(tile, count) => (w.tiles_built(*tile), *count),
        // Набор мерится по самому дальнему от цели предмету: пока не хватает
        // хоть одного, цель не взята, и честнее показывать именно узкое место.
        GoalTest::Stored(need) => need
            .iter()
            .map(|&(item, n)| (w.stored(item).min(n), n))
            .min_by_key(narrowest)
            .unwrap_or((0, 0)),
        GoalTest::Tech(id) => (w.techs.knows(id) as i32, 1),
        GoalTest::Cats(n) => (w.cats, *n),
        GoalTest::Raid(def) => (w.raids.0.contains(def) as i32, 1),
        GoalTest::Craft(def) => (w.crafted.0.contains(def) as i32, 1),
        GoalTest::Earned(n) => (w.earned.0, *n),
        // Репутация бывает отрицательной, и полоска на минусе — это «уже
        // испортил», а не «ещё не начал». Наружу поэтому едет обрезанное снизу
        // нулём: счёт показывает путь к цели, а не саму шкалу.
        GoalTest::Standing(need) => need
            .iter()
            .map(|&(faction, n)| (w.standing.value_of(faction).clamp(0, n), n))
            .min_by_key(narrowest)
            .unwrap_or((0, 0)),
    }
}

/// Выполнено ли условие. Одно выражение на всё: «взято» и «сколько осталось» —
/// это один и тот же счёт, и второго быть не должно.
fn met(tests: &[GoalTest], w: &WorldFacts) -> bool {
    let (have, need) = progress_of(tests, w);
    have >= need
}

/// Срез мира, по которому считаются все условия разом.
///
/// Собирается один раз за тик и передаётся в `progress_of` — иначе снапшот,
/// которому нужны счётчики всех целей сразу, пересчитывал бы кучи по разу на
/// цель. Здесь же лежит единственное место, где цели трогают склад, и трогают
/// они его чужой функцией (`stored_counts`, §12.53).
pub(crate) struct WorldFacts<'a> {
    pub(crate) techs: &'a Techs,
    pub(crate) raids: &'a Raids,
    pub(crate) crafted: &'a Crafted,
    pub(crate) earned: &'a Earned,
    /// Репутация по фракциям (§12.43). Знаковая: у цели на неё есть и «ещё не
    /// дошёл», и «уже испортил».
    pub(crate) standing: &'a Standing,
    /// Сколько котов у базы, считая ушедших и пленных: ушедший кот твой.
    /// §12.22 («мир не касается ушедших») — про усталость и голод, а не про
    /// принадлежность.
    pub(crate) cats: i32,
    /// Складское по типам — то, чем платят (§12.24). Пол и лапы не в счёт.
    pub(crate) stored: Vec<i32>,
    /// Сколько клеток каждого тайла построено.
    pub(crate) built: Vec<i32>,
}

impl WorldFacts<'_> {
    fn stored(&self, item: usize) -> i32 {
        self.stored.get(item).copied().unwrap_or(0)
    }

    fn tiles_built(&self, tile: usize) -> i32 {
        self.built.get(tile).copied().unwrap_or(0)
    }
}

/// Сколько клеток каждого тайла построено. Пустота (`-1`) не считается ничем.
///
/// Длина, как и у `stored_counts`, растёт под встреченное, а не задаётся
/// палитрой: `TileRules` в тестовых схемах пуст, и размер по нему обнулил бы
/// счёт для всех тайлов разом. Читать — через `.get()`.
pub(crate) fn built_counts(map: &BaseMap) -> Vec<i32> {
    let mut built: Vec<i32> = Vec::new();
    for &cell in &map.cells {
        if cell >= 0 {
            let tile = cell as usize;
            if built.len() <= tile {
                built.resize(tile + 1, 0);
            }
            built[tile] += 1;
        }
    }
    built
}

/// Отмечает цели, условия которых выполнились к концу этого тика.
///
/// Порядок обхода — **порядок правил в рулсете**, а не сущностей ECS: суммы по
/// `Query` от порядка не зависят, но `Goals` обязан быть детерминирован, а обход
/// мира, поднятого из снимка, свой (§11, §12.45).
#[allow(clippy::too_many_arguments)]
pub(crate) fn check_goals(
    rules: Res<GoalRules>,
    time: Res<SimTime>,
    map: Res<BaseMap>,
    tiles: Res<TileRules>,
    techs: Res<Techs>,
    raids: Res<Raids>,
    crafted: Res<Crafted>,
    earned: Res<Earned>,
    standing: Res<Standing>,
    mut goals: ResMut<Goals>,
    stacks: Query<(&Position, &Stack)>,
    cats: Query<(), With<UnitId>>,
) {
    if rules.0.is_empty() {
        return; // целей нет — так живут тесты чужих механик
    }
    let facts = WorldFacts {
        techs: &techs,
        raids: &raids,
        crafted: &crafted,
        earned: &earned,
        standing: &standing,
        cats: cats.iter().count() as i32,
        stored: stored_counts(stacks.iter(), &map, &tiles),
        built: built_counts(&map),
    };
    for (def, rule) in rules.0.iter().enumerate() {
        // Срок проверяется **до** условия и молча (§12.158): просроченная цель
        // не отнимает ничего и никого не наказывает, она просто перестаёт
        // браться. Второго исхода у неё нет и заводить его нельзя — это был бы
        // проигрыш по времени, которого в игре не бывает.
        if rule.before.is_some_and(|last| time.tick > last) {
            continue;
        }
        if goals.taken(def).is_none() && met(&rule.tests, &facts) {
            goals.0.push(Taken { def, at: time.tick });
        }
    }
}
