/// Все клетки-шлюзы карты, в порядке обхода: он фиксирован, значит и номер
/// отряда, и очередь заявок детерминированы (§11).
///
/// С §12.152 это же список **отрядов**: гараж держит состав и слот вылазки, —
/// поэтому список нужен и фасаду, а не только счёту внутри модуля.
pub(crate) fn gate_cells(map: &BaseMap, rules: &TileRules, owners: &Owners) -> Vec<(i32, i32)> {
    slot_cells(map, rules, owners, TileRules::is_gate)
}

/// Чем кончится вылазка. Считается и на конце работы (§12.244), и каждый кадр для панели:
/// прогноз и результат обязаны быть одним и тем же выражением, иначе игрок
/// увидит одно, а получит другое.
#[derive(Clone, Copy)]
pub(crate) struct Outcome {
    pub(crate) strength: i32,
    /// Какая доля добычи достанется, в процентах (0..=100).
    pub(crate) share: i32,
    /// Провал: силы не хватило даже вполовину.
    pub(crate) failed: bool,
}

/// Правила, по которым считается исход вылазки, — одним параметром.
///
/// Свёрнуты не для красоты: у `run_missions` их четыре, и порознь система
/// упирается в предел числа параметров bevy. Тот же приём, что сборка цепочки
/// тремя группами в `schedule.rs`, и по той же причине.
#[derive(SystemParam)]
pub(crate) struct RaidRules<'w> {
    pub(crate) missions: Res<'w, MissionRules>,
    pub(crate) skills: Res<'w, SkillRules>,
    pub(crate) stats: Res<'w, StatRules>,
    pub(crate) items: Res<'w, ItemRules>,
    /// Числа перков (§12.256): «Знание троп» укорачивает дорогу отряда.
    pub(crate) perks: Res<'w, PerkRules>,
    /// Порог ранения: по нему личное дело считает **переход**, а не урон.
    /// Лежит здесь, а не шестнадцатым параметром системы, по той же причине,
    /// по которой свёрнуты остальные четыре.
    pub(crate) health: Res<'w, HealthRules>,
    /// Породы очагов: по ним считается надбавка за ступень (§12.198). Здесь же
    /// и по той же причине — система и без них у предела параметров.
    pub(crate) blights: Res<'w, BlightRules>,
    /// Какой вылазкой база осваивает возможность отряда (§12.261).
    pub(crate) abilities: Res<'w, AbilityRules>,
}

/// Параметр, которым отряд режет опасность вылазки (§12.70). Имя, а не номер:
/// порядок записей `stats:` — дело рулсета, как и у доменов навыков.
pub(crate) const STAT_GUIDE: &str = "reflex";

/// Опасность заказа, какой её встретит этот отряд (§12.70).
///
/// **Реакция не прибавляет силу, а делит опасность** — и форма здесь важнее
/// величины. Прибавка к силе линейна и одинаково полезна везде; деление
/// нелинейно: чем тяжелее заказ, тем дороже каждая снятая единица, а при
/// `danger: 0` реакция не значит ничего вовсе. Из этого **даром** получается
/// то, ради чего иначе понадобилось бы поле «какой параметр меряет заказ»:
/// «уборка мусора — справится любой» следует из самого числа опасности.
///
/// Считается по **лучшему в отряде** (`guide` — его ступень), а не по сумме и
/// не по среднему. Сумма дала бы квадратичный рост по размеру отряда: число
/// котов уже входит в силу, и в делителе оно работало бы вторым концом дроби —
/// пятеро середняков закрывали бы топовый заказ на сотку. Среднее наказывало бы
/// за то, что кота взяли с собой: реакция врождённа и не растёт (§12.42),
/// значит слабый кот стал бы постоянным налогом на свою бригаду, а «потом» не
/// наступило бы никогда. Максимум же не мешает возить новичков: они едут с
/// проводником, ничего не портят и растят «Вылазки», то есть **силу** бригады.
///
/// Делитель ограничен, поэтому пол получается **по устройству формулы**, а не
/// отдельной проверкой: ступень 0 оставляет опасность как есть, ступень 3 режет
/// её до 40%, и ниже не бывает. Нулём опасность при этом не становится никогда:
/// «удаётся всегда» — свойство заказа, а не отряда.
pub(crate) fn raid_danger(danger: i32, guide: i32) -> i32 {
    if danger <= 0 {
        return danger;
    }
    (danger * 2 / (2 + guide.max(0))).max(1)
}

/// Сколько лап заказ **и правда** уведёт: больше `squad_max` не уходит никто
/// (§12.113), и прогноз обязан считать по этому числу, а не по длине состава
/// узла.
///
/// Живёт обрезка здесь, а не в снапшоте, по доводу инварианта 14: срок и
/// опасность считает одно выражение на уход и на прогноз, и обрезка, сделанная
/// снаружи, разошлась бы с ним на первой же перекомплектованной бригаде —
/// панель обещала бы «работа 480 / 5 котов» там, где в поле выйдут четверо.
/// На уходе она не меняет ничего: состав больше предела `launch_at` не примет.
///
/// Ноль в `squad_max` — «предела нет» (синтетические схемы), лапы идут как есть.
fn capped_paws(rule: &MissionRule, paws: usize) -> usize {
    if rule.squad_max == 0 {
        paws
    } else {
        paws.min(rule.squad_max)
    }
}

/// Опасность заказа для отряда из `paws` лап (§12.113).
///
/// Обычному заказу размер отряда безразличен: он входит в исход силой. На
/// разведке (`stealth`) он входит вторым концом — **множителем на опасность**,
/// и это то же место и та же форма, что у проводника: не пятое выражение
/// поверх `share` (инвариант 14), а поправка к `danger` до `outcome`.
///
/// Вместе с `crew_force` (сила по лучшему, а не суммой) это и делает разведку
/// разведкой: второй кот силы не добавляет, а заметность добавляет. Порознь
/// они бесполезны — линейное на линейное даёт ту же долю, то есть решение,
/// которое ничего не решает.
///
/// Шанса здесь нет: «чем меньше котов, тем выше вероятность» отвергнуто в
/// §12.113 по доводу §12.23 — с броском кубика игрок не отличит «взял слишком
/// много» от «не повезло».
///
/// `extra` — надбавка за ступень очага там, куда отряд идёт (§12.198). Она
/// складывается со сложностью заказа **до** деления на проводника: заражённый
/// участок это то же место, только хуже, и опытный проводник помогает против
/// него ровно так же. Ноль = карты нет или участок чист.
pub(crate) fn crew_danger(rule: &MissionRule, extra: i32, guide: i32, paws: usize) -> i32 {
    let paws = capped_paws(rule, paws);
    let danger = raid_danger(rule.danger + extra, guide);
    if rule.stealth {
        // Пустой отряд считается за одну лапу: множитель не должен обнулять
        // опасность — «удаётся всегда» это свойство заказа, а не состава.
        danger * paws.max(1) as i32
    } else {
        danger
    }
}

/// Сила отряда против этого заказа (§12.113): сумма вкладов, а на разведке —
/// **лучший** из них.
///
/// Максимум взят той же формой и по тем же доводам, что проводник (§12.70):
/// сумма даёт квадратичный рост по размеру отряда, среднее наказывает за то,
/// что кота взяли с собой. Разница в том, что у проводника максимум режет
/// опасность, а здесь — заменяет силу целиком.
///
/// Связь в свёртку не входит и прибавляется снаружи: она копится за время
/// вылазки и принадлежит не коту, а узлу (§12.60).
pub(crate) fn crew_force(rule: &MissionRule, forces: impl Iterator<Item = i32>) -> i32 {
    if rule.stealth {
        forces.max().unwrap_or(0)
    } else {
        forces.sum()
    }
}

/// Насколько этот проводник срезает опасность, в процентах (§12.71).
///
/// Выведено **из самой `raid_danger`**, а не повторено формулой: панель обязана
/// называть следствие реакции, а не её шкалу, — и следствие это не должно уметь
/// разойтись с тем, что случится на конце работы (инвариант 14). Сто здесь —
/// произвольная база для процента, а не опасность какого-то заказа: доля,
/// которую режет проводник, от заказа не зависит.
pub(crate) fn guide_cut(guide: i32) -> i32 {
    100 - raid_danger(100, guide)
}

/// Сырое значение «Реакции» кота — только чтобы назвать проводника по имени
/// (§12.70). В арифметику исхода не входит: там работает ступень, иначе шкала
/// 1–10 перевесила бы силу отряда.
///
/// Нужно оно вот зачем: ступень грубая, и у двоих котов с реакцией 5 и 7 она
/// одна. Назвать ведущим того, у кого реакция ниже, — значит показать игроку
/// заведомо неверное объяснение, хотя механика при этом права.
pub(crate) fn guide_value(rules: &StatRules, stats: Option<&Stats>) -> i32 {
    rules
        .index_of(STAT_GUIDE)
        .map_or(0, |stat| stats.map_or(0, |s| s.value_of(stat)))
}

/// Ступень проводника у одного кота: его «Реакция» в ступенях (§12.70).
///
/// Ступень **кота**, а не отряда: отрядную берут максимумом на месте, и это
/// сделано ради `run_missions` — держать `&Stats` в списке отряда значило бы
/// держать заимствование мира до конца тика, а там же коты правятся.
pub(crate) fn guide_of(rules: &StatRules, stats: Option<&Stats>) -> i32 {
    rules
        .index_of(STAT_GUIDE)
        .map_or(0, |stat| rules.step(stat, stats))
}

/// Что в составе отряда меняет срок и добычу (§12.256): перк «Знание троп» и
/// прибор сбора образцов. Оба — свойство **отряда**, а не кота: тропы знает
/// один, а идут по ним все; образцы собирает один прибор, и второй сбор не
/// ускоряет. Потому и не складываются.
///
/// Считает его одно выражение — `crew_traits`, — и зовут его уход и прогноз
/// в панели (инвариант 14).
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub(crate) struct Crew {
    /// На сколько процентов короче дорога: лучший перк с `road` в отряде
    /// («Знание троп»). Ноль — троп не знает никто.
    pub(crate) road_cut: i32,
    /// На сколько процентов длиннее работа: прибор сбора (`collects` у
    /// предмета). Ноль — прибора нет.
    pub(crate) work_toll: i32,
    /// Возможности отряда (§12.260) — объединение `grants` по надетому, маской
    /// по палитре `abilities:`. Ими отряд проходит ворота заказа и приносит
    /// `collected`-добычу.
    pub(crate) abilities: u64,
    /// Какие возможности вешают именно приборы сбора (§12.261): их цена
    /// (`work_toll`) платится, только пока возможность в деле.
    pub(crate) toll_grants: u64,
}

impl Crew {
    /// Отряд, каким он выйдет **на этот заказ** (§12.261): возможность,
    /// ещё не освоенная базой (`after` у записи `abilities:`), в поле не
    /// работает — ни добычи, ни цены. Исключение — заказ, который её сам
    /// требует: вылазка-урок и есть то место, где база её осваивает.
    /// Ворота заказа (`covers`) и «чего не хватает» спрашивают **несомое**,
    /// а не это: прибор у Антенны есть и до методики.
    pub(crate) fn fielded(self, rule_abilities: u64, active: u64) -> Crew {
        let abilities = self.abilities & (active | rule_abilities);
        let paid = self.toll_grants == 0 || abilities & self.toll_grants != 0;
        Crew {
            abilities,
            work_toll: if paid { self.work_toll } else { 0 },
            ..self
        }
    }
}

impl Crew {
    /// Есть ли у отряда возможность `ability` (индекс палитры `abilities:`).
    pub(crate) fn has(&self, ability: usize) -> bool {
        ability < 64 && self.abilities & (1 << ability) != 0
    }

    /// Несёт ли отряд всё, что требует заказ (§12.260).
    pub(crate) fn covers(&self, need: u64) -> bool {
        self.abilities & need == need
    }
}

/// Свернуть отряд в `Crew` по перкам и надетому (§12.256). Одно выражение на
/// уход и на прогноз: разойдись они, и панель пообещала бы не тот срок.
///
/// Числа — контент (§12.256): `road` у перка и `collects` у предмета. Берётся
/// **максимум** по отряду: тропы знает лучший, прибор нужен один.
pub(crate) fn crew_traits<'a>(
    items: &ItemRules,
    perks_rules: &PerkRules,
    cats: impl IntoIterator<Item = (Option<&'a Perks>, Option<&'a Gear>)>,
) -> Crew {
    let mut crew = Crew::default();
    for (perks, gear) in cats {
        crew.road_cut = crew.road_cut.max(perks_rules.road_of(perks));
        crew.work_toll = crew.work_toll.max(items.toll_of_gear(gear));
        crew.abilities |= items.grants_of_gear(gear);
        crew.toll_grants |= items.toll_grants_of_gear(gear);
    }
    crew
}

/// Дорога отряда в тиках (§12.256): «Знание троп» срезает свой процент. Это
/// **единственное** место этой арифметики — срок, стадия и граница исхода
/// берут дорогу отсюда, а у ушедшего отряда она заморожена (`Mission::travel`).
pub(crate) fn travel(rule: &MissionRule, crew: Crew) -> i32 {
    rule.travel * (100 - crew.road_cut.clamp(0, 100)) / 100
}

/// Работа на месте в очках (§12.256): прибор сбора добавляет свой процент —
/// образцы собирают, а не подбирают. Один раз на отряд, сколько бы приборов
/// ни несли.
pub(crate) fn work(rule: &MissionRule, crew: Crew) -> i32 {
    rule.work + rule.work * crew.work_toll.max(0) / 100
}

/// Сколько штук предмета принесёт вылазка при полной доле (§12.256): предмет
/// `collected` (образец) падает только отряду с нужной возможностью —
/// «сбор образцов» вешает прибор (§12.260). Потолок задаёт заказ, а не число
/// приборов, — второй прибор добычи не удваивает.
pub(crate) fn loot_count(items: &ItemRules, crew: Crew, item: usize, count: i32) -> i32 {
    match items.collected(item) {
        Some(ability) if !crew.has(ability) => 0,
        _ => count,
    }
}

/// Сколько тиков отряд из `paws` котов пробудет в поле (§12.70).
///
/// Дорога фиксирована, работа на месте делится на лапы: та же идиома, что
/// `BUILD_WORK / WORK_RATE` на базе (инвариант 9), только очки набивает не один
/// кот, а отряд. Отсюда и смысл большого состава — сила сверх `danger` пропадает
/// (`share` упирается в 100), а лишние лапы уходят в срок.
///
/// **Скорость берётся из числа котов, а не из их силы**, и это главное здесь
/// (§12.70): считай её силой — и сильный отряд выигрывал бы разом по обоим
/// циферблатам, а «послать толпу середняков» не имело бы смысла нигде.
/// Тропы и прибор (§12.256) правят дорогу и работу, а не скорость: это свойство
/// отряда, а не лап.
///
/// Зовут это двое — `run_missions` в момент ухода и снапшот для прогноза в
/// панели, — ровно как `outcome` (инвариант 14): игрок обязан видеть тот срок,
/// который получит.
///
/// Отряда без котов не бывает, но ноль сюда всё же доходит из панели, когда
/// бригада пуста; тогда работа не делается вовсе и остаётся одна дорога.
pub(crate) fn duration(rule: &MissionRule, paws: usize, crew: Crew) -> i32 {
    let road = travel(rule, crew);
    let work = work(rule, crew);
    let paws = capped_paws(rule, paws);
    if paws == 0 || work <= 0 {
        return road;
    }
    // Округление вверх, а не вниз: недоделанное очко — это ещё один тик в поле,
    // а срок, обнулённый делением, означал бы вылазку без работы.
    let paws = paws as i32;
    road + (work + paws - 1) / paws
}

/// Стадия ушедшей вылазки (§12.168): дорога туда → работа на месте → дорога
/// назад.
///
/// Считается **тем же разложением срока, каким его сложил `duration`**, и
/// второго экземпляра этой арифметики в JS быть не должно (инвариант 14): вид
/// увидел бы «работают» там, где отряд ещё в дороге. Дорога от числа лап не
/// зависит, значит всё, что сверх неё, — работа, а путь в один конец — её
/// половина. Дорога приходит **замороженной на уходе** (`Mission::travel`):
/// у отряда с тропами она короче, и стадия по чужой дороге разошлась бы со
/// сроком (§12.256).
///
/// Своей шкалы стадия не заводит и в мир ничего не пишет: это чтение уже
/// сложившегося срока, как `outcome` — чтение уже собранного отряда. Работы на
/// месте может не быть вовсе (`work: 0`) — тогда отряд разворачивается на
/// середине дороги, и «работают» не наступает никогда.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Phase {
    /// Идут к месту.
    Travel,
    /// Работают на месте.
    Work,
    /// Возвращаются на базу.
    Back,
}

impl Phase {
    /// Тег для снимка. Слово по нему подбирает вид: ядро не занимается
    /// подписями (то же деление, что у календаря, §12.46).
    pub(crate) fn tag(self) -> &'static str {
        match self {
            Phase::Travel => "travel",
            Phase::Work => "work",
            Phase::Back => "back",
        }
    }
}

pub(crate) fn phase(travel: i32, span: i32, left: i32) -> Phase {
    let gone = span - left;
    if gone < travel / 2 {
        Phase::Travel
    } else if left > back_ticks(travel, span) {
        Phase::Work
    } else {
        Phase::Back
    }
}

/// Сколько тиков срока занимает дорога назад (§12.244): то, что остаётся от
/// срока после половины дороги и работы. Работа — это всё, что срок набрал
/// сверх дороги: `duration` складывает его ровно так, и вычитание здесь не
/// «оценка», а тот же член суммы.
///
/// Это и есть граница, на которой считается исход: `left` дошёл до этого числа
/// — отряд отработал, и с этого тика он только идёт домой. Зовут трое —
/// `phase`, `run_missions` и `comms_span`, — и второго экземпляра быть не
/// должно (инвариант 14).
pub(crate) fn back_ticks(travel: i32, span: i32) -> i32 {
    let work = (span - travel).max(0);
    (span - travel / 2 - work).max(0)
}

/// Сколько тиков вылазки связь имеет значение (§12.244): до конца работы.
/// Дорога домой в этот счёт не входит — исход уже посчитан, и эфир отряду
/// больше ничего не даёт. На это число делится набежавшая связь и в
/// `run_missions`, и в прогнозе снимка (инвариант 14).
pub(crate) fn comms_span(travel: i32, span: i32) -> i32 {
    span - back_ticks(travel, span)
}

/// Исход по силе отряда и сложности вылазки — **без броска кубика** (§12.23).
///
/// Детерминизм здесь не формальность: он единственное, что делает выбор отряда
/// читаемым. С кубиком игрок не отличил бы «выбрал слабый отряд» от «не
/// повезло», а вылазок за сеанс столько, что вероятность так и не проступит.
///
/// Хватило силы — вся добыча; не хватило — её доля; вдвое меньше нужного —
/// провал: ни добычи, ни сил. Нулевая сложность удаётся всегда, по общему
/// правилу нулей в рулсете (цена тайла, ёмкость склада, потолок бодрости).
pub(crate) fn outcome(danger: i32, strength: i32) -> Outcome {
    if danger <= 0 {
        return Outcome {
            strength,
            share: 100,
            failed: false,
        };
    }
    let failed = strength * 2 < danger;
    Outcome {
        strength,
        share: if failed {
            0
        } else {
            (strength * 100 / danger).min(100)
        },
        failed,
    }
}

/// Держит выбранный игроком отряд идущим к шлюзу.
///
/// Состав здесь не трогается: его назначил `Sim::launch` в момент заявки, и
/// заменить выбывшего некем — это выбор игрока, а не раздача работы (§12.23).
/// Система нужна ровно для того, чтобы маршрут переживал изменения карты:
/// шлюз снесли, кота выбросило из ямы, боец проснулся после истощения.
/// Тот же случай, что `retry_orders` у приказа игрока.
pub(crate) fn gather_squad(
    map: Res<BaseMap>,
    tiles: Res<TileRules>,
    mut commands: Commands,
    missions: Query<(Entity, &Mission)>,
    crew: Query<
        (Entity, &Squad, &Position, Option<&Path>, Option<&Away>),
        // Спящего не трогаем: маршрут разбудил бы его, а истощение — не повод
        // гнать кота дальше. Проснётся — эта же система его и подберёт. Идущего
        // за снаряжением — тем более: одетым он уйдёт сильнее (§12.29, §12.34).
        // Раненого — тоже: в отряд его не берут вовсе, а если ранило уже
        // назначенного, отряд ждёт, пока тот встанет (§12.23, §12.37).
        (Without<Rest>, Without<Equipping>, Without<Healing>),
    >,
) {
    if missions.is_empty() {
        return;
    }
    let map = &*map;

    for (mission_e, mission) in &missions {
        // Кто в отряде и где он. Пустой маршрут считается пройденным:
        // `move_units` снимет его только следующим тиком.
        let mut left_base = false;
        let squad: Vec<(Entity, (i32, i32), bool)> = crew
            .iter()
            .filter(|(_, s, ..)| s.0 == mission_e)
            .inspect(|(.., away)| left_base |= away.is_some())
            .map(|(e, _, p, path, _)| {
                let walking = path.is_some_and(|p| !p.steps.is_empty());
                (e, (p.x, p.y), walking)
            })
            .collect();
        // Отряд ушёл — шлюз больше не пересматривается: вернутся коты туда,
        // откуда ушли, даже если гараж успели снести.
        if left_base {
            continue;
        }

        // **Снесённый гараж распускает собирающийся отряд** (§12.152). Правило
        // то же, по которому снесённый станок уносит свой заказ (§12.96), а
        // снесённая рация — правило автовылазки (§12.67): вылазка живёт в
        // клетке, а клетки больше нет. До §12.152 здесь выбирался новый шлюз
        // (`pick_gate` по ближайшему ко всем), и это было единственным, ради
        // чего он пересматривался каждый тик; теперь дверь называет игрок, и
        // подставлять ему другую — значит отменять его решение молча.
        //
        // Ушедшего отряда это не касается: он отсеян `left_base` выше и
        // вернётся туда, откуда ушёл, даже если гараж успели снести (§12.22).
        let gate = mission.gate;
        if !tiles.is_gate(map.tile_at(gate.0, gate.1)) {
            for &(cat_e, ..) in &squad {
                commands.entity(cat_e).remove::<(Squad, Path, Stride)>();
            }
            commands.entity(mission_e).despawn();
            continue;
        }

        for &(cat_e, at, walking) in &squad {
            if walking || at == gate {
                continue;
            }
            if let Some(steps) = find_path(map, &tiles, at, gate) {
                commands.entity(cat_e).insert(Path { steps });
            }
        }
    }
}

/// Сколько на базе шлюзов — и, с §12.152, **потолок одновременных вылазок**:
/// гараж это дверь, отряд и лицензия разом. До §12.152 потолок держала рация
/// (§12.59), а шлюз подбирался автоматом; счётность при этом никуда не делась,
/// только переехала на ту клетку, которую игрок и нажимает.
///
/// Наружу едет числом (§12.53): снесённый гараж делает вылазку невозможной, и
/// молчащая кнопка «Отправить» читается как поломка.
/// Знакома ли база с фракцией (§12.214): взяла ли она хоть раз доведённый до
/// конца заказ, где эта сторона названа заказчиком или пострадавшим.
///
/// **Одно выражение на снимок и на тесты** (инвариант 14): второй его экземпляр
/// однажды покажет в шапке сторону, о которой игра ещё молчит, — или спрячет ту,
/// с которой база уже поссорилась.
///
/// Считается **из журнала**, а не из самой репутации: та знаковая и умеет
/// вернуться в ноль, а знакомство закрываться не умеет (тот же довод, что у
/// `Seen`, §12.131). Журнал пишется ровно там, где двигается репутация (§12.43),
/// значит это одно и то же событие — и нового сохраняемого флага не нужно.
pub(crate) fn faction_is_met(rules: &MissionRules, done: &Raids, faction: usize) -> bool {
    done.0.iter().any(|&def| {
        rules
            .0
            .get(def)
            .is_some_and(|m| m.patron == Some(faction) || m.against == Some(faction))
    })
}

pub(crate) fn gate_count(map: &BaseMap, tiles: &TileRules, owners: &Owners) -> usize {
    gate_cells(map, tiles, owners).len()
}

/// Есть ли на базе силы прийти за пленным — считается **до** того, как его
/// оставят (§12.40).
///
/// Плен обратим по определению: он стоит котовремени, а не кота (§12.37). Но
/// обратимость держится не на обещании, а на этой проверке: если базе некем
/// снарядить самый маленький спасательный отряд, отряд тащит раненого сам, и
/// плена не случается вовсе. Иначе провал на трёх котах запирал бы игру
/// насмерть — та самая необратимость, которой §12.10 избегает.
///
/// Считаются вылазки, доступные **прямо сейчас**: известность только растёт
/// (§12.24), но ждать её, сидя в плену, кот будет столько же, сколько никогда.
///
/// Фракционных ворот здесь нет **намеренно** (§12.43), и это не экономия. Вся
/// обратимость плена держится на том, что известность монотонна: до порога
/// база рано или поздно дорастёт, и проверка честна. Репутация умеет падать —
/// значит база, рассорившаяся со всеми, теряла бы кота навсегда. Это смерть
/// через чёрный ход, которой в игре нет (§12.37), поэтому вылазка за своим не
/// закрыта ни репутацией, ни `needs` у самого правила.
fn rescue_is_possible(rules: &MissionRules, fame: i32, on_base: usize) -> bool {
    rules
        .0
        .iter()
        .any(|r| r.rescue && r.requires <= fame && r.squad <= on_base)
}

/// Отправляет собравшийся отряд, крутит таймер и возвращает котов с добычей.
///
/// Стоит после `move_units`: кот, шагнувший на шлюз в этом тике, засчитывается
/// сразу, — и до `settle_stacks`, чтобы добыча, вывалившаяся в свежую яму,
/// съехала на пол тем же тиком (§12.15).
///
/// **Провал может оставить кота в плену** (§12.40), а вылазка с `rescue` —
/// привести пленных обратно. И то, и другое — работа с составом отряда, а не с
/// добычей, поэтому живёт здесь же: другого места, где известно, чем кончилась
/// вылазка, нет.
pub(crate) fn run_missions(
    raid_rules: RaidRules,
    factions: Res<FactionRules>,
    mut fame: ResMut<Fame>,
    mut standing: ResMut<Standing>,
    mut raids: ResMut<Raids>,
    mut blights: ResMut<Blights>,
    mut commands: Commands,
    mut missions: Query<(Entity, &mut Mission)>,
    mut crew: Query<(
        Entity,
        &Squad,
        &UnitId,
        &Position,
        Option<&Path>,
        Option<&Away>,
        Option<&Skills>,
        Option<&mut Energy>,
        Option<&Gear>,
        Option<&mut Health>,
        // Врождённое: им отряд режет опасность заказа (§12.70). Читается только
        // здесь и в прогнозе для панели — двумя вызывающими одного выражения,
        // как и сила (инвариант 14).
        Option<&Stats>,
        // Личное дело: вылазка — единственное место, где в него пишутся три
        // поля из пяти. ⚠️ **Только `Option`**: коты из ASCII-схем собираются
        // мимо `spawn_cat` и дела не имеют, а неоптиональный `&mut Record`
        // молча выкинул бы их из запроса — то есть сломал бы вылазки целиком.
        Option<&mut Record>,
        // Перки: «Знание троп» укорачивает дорогу всему отряду (§12.256).
        Option<&Perks>,
    )>,
    // Весь личный состав базы: по нему считается, есть ли кому прийти за
    // пленным. **Ушедшие сюда входят** (§12.59): кот в поле — твой кот, он
    // вернётся и сходит за товарищем, — тот же довод, что у `WorldFacts::cats`
    // в целях. Фильтр `Without<Away>` стоял здесь, пока вылазка была одна; с
    // несколькими узлами связи он превращался в бесплатную страховку — «отправь
    // второй отряд, и первый никого не потеряет», — потому что второй отряд не
    // попадал в счёт и проверка занижала силы базы.
    roster: Query<(), With<UnitId>>,
    // Пленные — те, за кем идёт вылазка с `rescue`. Только сущности: позицию
    // им ставит `Commands`, иначе этот запрос конфликтовал бы с `crew` за
    // `Position` и bevy уронил бы систему на старте.
    captives: Query<Entity, With<Captive>>,
    // Дежурные на узлах связи (§12.60). Только те, кто **дошёл**: идущий к рации
    // ещё не держит связь, и засчитывать ему дорогу значило бы платить за
    // намерение. Позиция сюда не нужна — `assign_relay` ведёт кота маршрутом, и
    // «дошёл» это снятый `Path`.
    duty: Query<(Entity, &OnDuty, Option<&Skills>), Without<Path>>,
    map: Res<BaseMap>,
    tiles: Res<TileRules>,
    mut stacks: Query<(Entity, &Position, &mut Stack)>,
) {
    let RaidRules {
        missions: rules,
        skills: skill_rules,
        stats: stat_rules,
        items,
        perks: perk_rules,
        health: hurts,
        blights: blight_rules,
        abilities: ability_rules,
    } = raid_rules;
    let raid = skill_rules.index_of(SKILL_RAID);
    let comms = skill_rules.index_of(SKILL_RELAY);
    // Пленные, взятые **в этом же тике**: `Captive` вешает `Commands`, то есть
    // запрос `captives` увидит их только следующим тиком, а вернуться разом
    // может не один отряд (§12.59). Без этого счётчика два провала подряд
    // оставили бы двоих там, где база тянет только одного.
    let mut lost_this_tick = 0usize;
    // **Связь общая** (§12.152): дежурная рация кроет все идущие вылазки разом,
    // и слагаемое за тик у всех отрядов одно. До §12.152 она была именной —
    // дежурный сидел у рации **своего** отряда (§12.60), потому что рация и
    // держала слот; с переездом слота на гараж этой привязки не стало, и
    // считать её заново было бы вторым реестром без владельца.
    //
    // Считается **один раз за тик**, до цикла по миссиям: внутри него то же
    // выражение размножилось бы по числу отрядов (инвариант 14).
    let duty_total: i32 = duty
        .iter()
        .map(|(_, on_duty, skills)| duty_gain(&tiles, &map, &skill_rules, skills, on_duty.spot))
        .sum();
    // Есть ли кому платить опытом: домен «Связь» растёт от дежурства, но только
    // пока в поле кто-то есть — пустой эфир это не работа (§12.17, §12.60).
    let mut anyone_away = false;
    for (mission_e, mut mission) in &mut missions {
        let Some(rule) = rules.0.get(mission.def) else {
            continue;
        };
        let gate = mission.gate;

        let squad: Vec<(Entity, (i32, i32), bool, bool, i32, i32)> = crew
            .iter()
            .filter(|(_, s, ..)| s.0 == mission_e)
            .map(|(e, _, _, p, path, away, skills, _, gear, _, stats, ..)| {
                let walking = path.is_some_and(|p| !p.steps.is_empty());
                // Вклад кота в силу отряда: сам он стоит единицу, навык —
                // сверху, надетое — ещё сверху. Нулевой навык поэтому не значит
                // «бесполезен», а снаряжение — второе слагаемое, которое растёт
                // не от навыка и не упирается в его потолок (§12.29).
                let force = 1
                    + raid.map_or(0, |s| level_of(&skill_rules, skills, s))
                    + items.force_of_gear(gear);
                (
                    e,
                    (p.x, p.y),
                    walking,
                    away.is_some(),
                    force,
                    guide_of(&stat_rules, stats),
                )
            })
            .collect();

        // Отряд в поле. База о нём ничего не знает: ни усталости, ни маршрутов —
        // вылазка считается разом на конце работы (§12.22, §12.244), а не
        // симулируется; домой отряд несёт только долю добычи.
        if squad.iter().any(|&(.., away, _, _)| away) {
            // Опыт капает за тик в поле, как и на любой другой работе (§12.17):
            // начисляет его `train_skills` в конце цепочки, здесь только маркер.
            if let Some(skill) = raid {
                for &(cat_e, ..) in &squad {
                    commands.entity(cat_e).insert(Worked(skill));
                }
            }
            // Связь копится **за каждый тик**, пока где-то на базе сидит
            // дежурный (§12.60, §12.152). Одним замером её мерить нельзя: на
            // уходе хватило бы посадить кота на тик, а на возвращении бонус
            // повис бы на том, кто случайно оказался у рации в последний тик, —
            // это уже не решение игрока, а расписание.
            // Отряд, который уже отработал, только идёт домой (§12.244): эфир
            // ему больше ничего не даёт, и связь за эти тики не копится —
            // иначе дежурство после дела поднимало бы уже посчитанный исход.
            if mission.verdict.is_none() {
                anyone_away = true;
                mission.covered += duty_total;
            }

            mission.left -= 1;

            // Возвращение (§12.244): исход посчитан на конце работы, домой отряд
            // несёт только добычу и (если шли за своим) пленных. Ниже — только
            // то, что случается на шлюзе.
            if mission.left <= 0 {
                let Some(verdict) = mission.verdict else {
                    // Срок без дороги назад не бывает короче работы (`back_ticks`
                    // не больше `span`), поэтому сюда не попасть; на всякий
                    // случай отряд вернётся ни с чем, а не повиснет в поле.
                    commands.entity(mission_e).despawn();
                    for &(cat_e, ..) in &squad {
                        commands.entity(cat_e).remove::<(Away, Squad)>();
                    }
                    continue;
                };
                // Успешное спасение возвращает **всех**, кого нашли: делить
                // своих на «этого забрали, а за тем сходите ещё раз» — это не
                // сложность, а вторая ходка за тем же самым. Частичный успех
                // тоже возвращает: доля считается в добыче, а кот либо дома,
                // либо нет (§12.40).
                if rule.rescue && !verdict.failed {
                    for cat_e in &captives {
                        commands
                            .entity(cat_e)
                            .remove::<(Away, Captive)>()
                            .insert(Position {
                                x: gate.0,
                                y: gate.1,
                            });
                    }
                }
                for &(cat_e, ..) in &squad {
                    commands.entity(cat_e).remove::<(Away, Squad)>();
                }
                // Добыча ложится кучей на шлюз — ровно как возврат от сноса
                // ложится под ноги сносильщику. Развозит её обычная уборка
                // (§12.16). Доля — та, что посчитана на месте.
                // Образцы — только отряду, который нёс прибор (§12.256): его
                // возможность «сбор образцов» (§12.260) заморожена на уходе, потому что провал ломает снаряжение раньше,
                // чем отряд доберётся домой.
                let crew = Crew {
                    road_cut: 0,
                    work_toll: mission.toll,
                    abilities: mission.abilities,
                    toll_grants: 0,
                };
                for &(item, count) in &rule.loot {
                    let got = loot_count(&items, crew, item, count) * verdict.share / 100;
                    if got > 0 {
                        spill(&mut commands, &mut stacks, gate, item, got);
                    }
                }
                commands.entity(mission_e).despawn();
                continue;
            }

            // Ещё идут туда или работают — либо уже отработали и идут домой.
            if mission.verdict.is_some()
                || phase(mission.travel, mission.span, mission.left) != Phase::Back
            {
                continue;
            }

            // Конец работы (§12.244): исход считается **здесь**, а не на
            // возвращении. Очаг гаснет, известность и репутация двигаются, раны
            // и плен случаются в тот тик, когда отряд закончил дело, — иначе
            // зачищенный участок горел бы на карте всю дорогу домой.
            //
            // Сила берётся по составу **сейчас**: за дорогу и работу навык
            // вырос, и отнимать этот рост у самой вылазки было бы странно.
            // Связь входит сюда же, в **ту же** силу, а не пятым слагаемым
            // исхода: инвариант 14 держит `outcome` одним выражением на прогноз
            // и на результат. Делится она на срок **до конца работы**, потому
            // что дальше не копится.
            let force: i32 = crew_force(rule, squad.iter().map(|&(.., f, _)| f))
                + relay_force(mission.covered, comms_span(mission.travel, mission.span));
            // Опасность — та, какую встретил этот отряд: проводник режет её
            // делением (§12.70), а разведка умножает на число лап (§12.113).
            // Считается тем же выражением, что и в прогнозе для панели: игрок
            // обязан получить то, что ему показали.
            let guide = squad.iter().map(|&(.., g)| g).max().unwrap_or(0);
            // Надбавка за очаг там, куда ходили (§12.198). Цель заморожена в
            // момент заявки, а ступень берётся **сейчас**: отряд встретил то,
            // что успело вырасти за дорогу, — в этом и цена промедления.
            let extra = stage_danger(&blight_rules, mission.site.and_then(|s| blights.at(s)));
            let out = outcome(crew_danger(rule, extra, guide, squad.len()), force);

            // Кто из отряда остался там (§12.40). Выбор — **первый по `id`**, и
            // это намеренно ничего не значит: причины плена игра не называет.
            // Ни здоровье, ни навык сюда не входят — «оставили того, кому
            // досталось больше» рассказывало бы, что своих раненых бросают, а
            // это не про боевых котов. Что известно игроку — то и решает:
            // провал вылазки, дальше подробности за кадром. `id` здесь ровно
            // за детерминизмом (§11): порядок сущностей в ECS зависит от
            // истории вставок, а «кого оставили» игрок увидит и запомнит.
            //
            // Своя же вылазка за пленным пленных не оставляет никогда, иначе
            // неудачное спасение плодит второго пленника и база уходит в
            // спираль. И некому идти — тоже не оставляет: см. `rescue_is_possible`.
            //
            // **Зачистка очага — второе такое исключение** (§12.198): очаг это
            // биологическая угроза от природы, у неё нет ни воли, ни лагеря, и
            // брать в плен там некому. Провал зачистки стоит добычи и здоровья,
            // но кот возвращается всегда. Отдельного поля у правила нет и не
            // нужно: `cleanses` уже говорит, с чем отряд имел дело.
            //
            // Считается это **личным составом за вычетом пленных и минус один
            // за нового** (§12.59), а не «кто сейчас дома»: иначе число зависело
            // бы от того, сколько отрядов случайно в поле, и второй отряд
            // страховал бы первый от потери.
            let on_base = roster
                .iter()
                .count()
                .saturating_sub(captives.iter().count() + lost_this_tick + 1);
            let captive = if out.failed
                && !rule.rescue
                && rule.cleanses.is_none()
                && rescue_is_possible(&rules, fame.0, on_base)
            {
                crew.iter()
                    .filter(|(_, s, ..)| s.0 == mission_e)
                    .map(|(e, _, id, ..)| (id.0.as_str(), e))
                    .min()
                    .map(|(_, e)| e)
            } else {
                None
            };
            if captive.is_some() {
                lost_this_tick += 1;
            }

            for &(cat_e, ..) in &squad {
                let taken_captive = Some(cat_e) == captive;
                // Пленный остаётся в поле: `Away` при нём, из отряда он выбыл
                // здесь же — домой идут без него, и на возвращении его уже нет
                // в составе.
                if taken_captive {
                    commands.entity(cat_e).remove::<Squad>().insert(Captive);
                }
                // Плата за вылазку — котовремя: та же валюта, в которой
                // измеряется и сама отправка отряда. Провал забирает всё, и
                // коты валятся у шлюза — `collapse_exhausted` подберёт их.
                //
                // Раны считаются **той же долей**, что и добыча: полный успех не
                // царапает никого, полсилы стоят половины `harm`, провал — всего
                // (§12.37). Отдельной формулы для урона нет намеренно: две
                // арифметики исхода разошлись бы, а прогноз в панели показывал
                // бы игроку не то, что случится (§12.23).
                if let Ok((.., energy, _, health, _, record, _)) = crew.get_mut(cat_e) {
                    if let Some(mut energy) = energy {
                        let toll = if out.failed { energy.0 } else { rule.toll };
                        energy.0 = (energy.0 - toll).max(0);
                    }
                    // Личное дело помнит не урон, а **выход из строя**: сколько
                    // раз вылазка довела кота до порога ранения. Царапина, после
                    // которой он продолжил работать, — не то, о чём игрок
                    // рассказывает про своего кота.
                    let mut crossed = false;
                    if let Some(mut health) = health {
                        // Раны у всех одни — те, что посчитал исход. Пленному
                        // сверх этого не достаётся ничего: плен — это место, а
                        // не наказание, и добивать оставленного там кота ядру
                        // незачем (§12.40).
                        let before = health.0;
                        health.0 = (health.0 - rule.harm * (100 - out.share) / 100).max(0);
                        let hurt = hurts.hurt;
                        crossed = before > hurt && health.0 <= hurt;
                    }
                    // Три поля дела из пяти — здесь, соседними строками с самими
                    // событиями, как и журнал `Raids` ниже. Вылазка засчитывается
                    // и провальная: «сходил» — это про кота, а не про добычу.
                    if let Some(mut record) = record {
                        record.note_raid(mission.def);
                        if crossed {
                            record.wounds += 1;
                        }
                        if taken_captive {
                            record.captures += 1;
                        }
                    }
                }
                // Провал ломает снаряжение: до него он стоил только бодрости, а
                // она восстанавливается бесплатно — то есть заведомо провальная
                // вылазка была способом качать «Вылазку» за одно лишь время
                // (§12.29). Успех не изнашивает: износ за каждый выход
                // превратил бы петлю «добыча → сила» в оброк. Комплект наберётся
                // заново, как только на складе снова будет из чего.
                // Личная вещь провалом не ломается (§12.256): анализатор Антенны
                // другого пути в мир не имеет, и его потеря заперла бы образцы
                // навсегда.
                if out.failed
                    && let Ok((.., gear, _, _, _, _)) = crew.get(cat_e)
                {
                    let kept: Vec<usize> = gear
                        .map(|g| g.0.iter().copied().filter(|&i| items.personal(i)).collect())
                        .unwrap_or_default();
                    match kept.is_empty() {
                        true => commands.entity(cat_e).remove::<Gear>(),
                        false => commands.entity(cat_e).insert(Gear(kept)),
                    };
                }
            }
            // Известность идёт той же долей, что и добыча: слухи расходятся по
            // сделанному, а не по задуманному. Провал не приносит ничего — но и
            // не отнимает: ворота, которые закрываются, читаются как поломка
            // (§12.24).
            fame.0 += rule.fame * out.share / 100;
            // Журнал совершённого (§12.58). Пишется **здесь и только здесь**:
            // это единственный момент, когда вылазка засчитана, — как деньги за
            // продажу считает только `work_hauls`. Провал в журнал не идёт:
            // «сходил и вернулся ни с чем» — не поступок, за который дают цель.
            if !out.failed && !raids.0.contains(&mission.def) {
                raids.0.push(mission.def);
            }
            // Зачистка снимает очаг **целиком на полном успехе, а на неполном
            // сбивает ступень** (§12.206). Провал не двигает ничего.
            //
            // Новой арифметики здесь нет: читается та же `out.share`, которой
            // меряются добыча, известность, раны и репутация (инвариант 14), —
            // просто у очага она читается ступенью, а не долей. Гриндом это не
            // становится ровно потому, что очаг растёт, пока раненый отлёживается:
            // отряд, сбивающий ступень медленнее, чем она возвращается, не
            // выигрывает никогда — это гонка, а не терпение. Отсюда и то, что
            // ступень сбивает **любой** неполный успех: доля уже назвала, чего
            // отряд стоит, и второй порог поверх неё был бы четвёртым числом там,
            // где хватает трёх.
            //
            // Породу сверяем **на месте**: пока отряд шёл, очаг могли зачистить
            // с соседнего гаража, а на освободившийся участок могло сесть
            // что-то другое. Снять чужой очаг «за компанию» значило бы отдать
            // игроку работу, которой он не делал.
            if let (Some(kind), Some(site)) = (rule.cleanses, mission.site)
                && !out.failed
                && blights.at(site).is_some_and(|b| b.def == kind)
            {
                if out.share >= 100 {
                    blights.clear(site);
                } else {
                    blights.knock(site);
                }
            }
            // Репутация расходится **по сделанному** — тем же выражением, что и
            // добыча с известностью (§12.43). Отсюда её главное свойство: у
            // провала доля нулевая, значит провал не двигает репутацию вовсе.
            // Сорванный налёт на Синдикат Синдикат не разозлил — базе просто
            // нечего ему предъявить, и наказания поверх наказания не выходит
            // (§12.23 уже забрал добычу, силы, снаряжение и кота).
            //
            // Заказчику вверх, пострадавшему вниз, и **ровно настолько же**:
            // это и делает нейтралитет нулевым, а не бесплатным. Две зеркальные
            // вылазки, взятые по очереди, оставляют базу там же, где нашли.
            let moved = rule.standing * out.share / 100;
            if let Some(f) = rule.patron {
                standing.add(f, moved, factions.span_of(f));
            }
            if let Some(f) = rule.against {
                standing.add(f, -moved, factions.span_of(f));
            }
            // Домой отряд несёт долю — по ней возвращение положит добычу.
            mission.verdict = Some(Verdict {
                share: out.share,
                failed: out.failed,
            });
            continue;
        }

        // Уходим, когда все, кого взяли, стоят на шлюзе: пустой отряд здесь —
        // это «ещё идут», а не «недобрали».
        //
        // **Кого взяли, решено в момент клика** (§12.70): спящего, раненого и не
        // вернувшегося `launch_at` в отряд не записал вовсе, и ждать их некому.
        // Ждут ровно тех, кто уже в `Squad`, — они идут ногами, и это видимая
        // игроку беготня, а не простой.
        // Минимум вилки здесь больше не спрашивается (§12.113): недокомплект
        // разрешён и уже оплачен — долей добычи и сроком. Ждать некого, если
        // все, кого взяли, дошли.
        let ready = !squad.is_empty()
            && squad
                .iter()
                .all(|&(_, at, walking, ..)| at == gate && !walking);
        if ready {
            // Срок замерзает здесь и больше не пересчитывается (§12.70) — как
            // курс сделки замерзает в момент заказа (§12.44). Считается он по
            // числу ушедших лап: тем же выражением, каким панель показала
            // прогноз до нажатия.
            // Тропы и прибор (§12.256) замерзают вместе со сроком: состав ушёл,
            // и дорога с добычей теперь его, а не того, кто остался дома.
            let traits = crew_traits(
                &items,
                &perk_rules,
                crew.iter()
                    .filter(|(_, s, ..)| s.0 == mission_e)
                    .map(|(.., gear, _, _, _, perks)| (perks, gear)),
            );
            // Неосвоенная возможность в поле не работает (§12.261) — и
            // замерзает уже урезанной, как дорога.
            let traits = traits.fielded(rule.abilities, ability_rules.active(&raids));
            mission.span = duration(rule, squad.len(), traits);
            mission.travel = travel(rule, traits);
            mission.toll = traits.work_toll;
            mission.abilities = traits.abilities;
            mission.left = mission.span;
            for &(cat_e, ..) in &squad {
                commands.entity(cat_e).insert(Away);
            }
        }
    }

    // Опыт дежурным — **один раз за тик и на всех** (§12.152). Он не свойство
    // конкретной вылазки: связист держит эфир, а не отряд, — поэтому и стоит
    // здесь, за циклом, а не внутри него, где начислялся бы по разу на каждую
    // идущую вылазку. Пустой эфир работой не считается: некому помогать —
    // нечему и расти (§12.17).
    if anyone_away && let Some(skill) = comms {
        for (cat_e, ..) in &duty {
            commands.entity(cat_e).insert(Worked(skill));
        }
    }
}
