/// Все клетки-шлюзы карты, в порядке обхода: он фиксирован, значит выбор
/// шлюза детерминирован (§11).
fn gate_cells<'a>(map: &'a BaseMap, rules: &'a TileRules) -> impl Iterator<Item = (i32, i32)> + 'a {
    (0..map.height)
        .flat_map(move |y| (0..map.width).map(move |x| (x, y)))
        .filter(move |&(x, y)| rules.is_gate(map.tile_at(x, y)))
}

/// Чем кончится вылазка. Считается и на возвращении, и каждый кадр для панели:
/// прогноз и результат обязаны быть одним и тем же выражением, иначе игрок
/// увидит одно, а получит другое.
#[derive(Clone, Copy)]
pub(crate) struct Outcome {
    pub(crate) strength: i32,
    /// Какая доля добычи достанется, в процентах (0..=100).
    pub(crate) share: i32,
    /// Провал: силы не хватило даже вполовину.
    pub(crate) failed: bool,
}

/// Правила, по которым считается исход вылазки, — одним параметром.
///
/// Свёрнуты не для красоты: у `run_missions` их четыре, и порознь система
/// упирается в предел числа параметров bevy. Тот же приём, что сборка цепочки
/// тремя группами в `schedule.rs`, и по той же причине.
#[derive(SystemParam)]
pub(crate) struct RaidRules<'w> {
    pub(crate) missions: Res<'w, MissionRules>,
    pub(crate) skills: Res<'w, SkillRules>,
    pub(crate) stats: Res<'w, StatRules>,
    pub(crate) items: Res<'w, ItemRules>,
}

/// Параметр, которым отряд режет опасность вылазки (§12.70). Имя, а не номер:
/// порядок записей `stats:` — дело рулсета, как и у доменов навыков.
pub(crate) const STAT_GUIDE: &str = "reflex";

/// Опасность заказа, какой её встретит этот отряд (§12.70).
///
/// **Реакция не прибавляет силу, а делит опасность** — и форма здесь важнее
/// величины. Прибавка к силе линейна и одинаково полезна везде; деление
/// нелинейно: чем тяжелее заказ, тем дороже каждая снятая единица, а при
/// `danger: 0` реакция не значит ничего вовсе. Из этого **даром** получается
/// то, ради чего иначе понадобилось бы поле «какой параметр меряет заказ»:
/// «уборка мусора — справится любой» следует из самого числа опасности.
///
/// Считается по **лучшему в отряде** (`guide` — его ступень), а не по сумме и
/// не по среднему. Сумма дала бы квадратичный рост по размеру отряда: число
/// котов уже входит в силу, и в делителе оно работало бы вторым концом дроби —
/// пятеро середняков закрывали бы топовый заказ на сотку. Среднее наказывало бы
/// за то, что кота взяли с собой: реакция врождённа и не растёт (§12.42),
/// значит слабый кот стал бы постоянным налогом на свою бригаду, а «потом» не
/// наступило бы никогда. Максимум же не мешает возить новичков: они едут с
/// проводником, ничего не портят и растят «Вылазки», то есть **силу** бригады.
///
/// Делитель ограничен, поэтому пол получается **по устройству формулы**, а не
/// отдельной проверкой: ступень 0 оставляет опасность как есть, ступень 3 режет
/// её до 40%, и ниже не бывает. Нулём опасность при этом не становится никогда:
/// «удаётся всегда» — свойство заказа, а не отряда.
pub(crate) fn raid_danger(danger: i32, guide: i32) -> i32 {
    if danger <= 0 {
        return danger;
    }
    (danger * 2 / (2 + guide.max(0))).max(1)
}

/// Опасность заказа для отряда из `paws` лап (§12.113).
///
/// Обычному заказу размер отряда безразличен: он входит в исход силой. На
/// разведке (`stealth`) он входит вторым концом — **множителем на опасность**,
/// и это то же место и та же форма, что у проводника: не пятое выражение
/// поверх `share` (инвариант 14), а поправка к `danger` до `outcome`.
///
/// Вместе с `crew_force` (сила по лучшему, а не суммой) это и делает разведку
/// разведкой: второй кот силы не добавляет, а заметность добавляет. Порознь
/// они бесполезны — линейное на линейное даёт ту же долю, то есть решение,
/// которое ничего не решает.
///
/// Шанса здесь нет: «чем меньше котов, тем выше вероятность» отвергнуто в
/// §12.113 по доводу §12.23 — с броском кубика игрок не отличит «взял слишком
/// много» от «не повезло».
pub(crate) fn crew_danger(rule: &MissionRule, guide: i32, paws: usize) -> i32 {
    let danger = raid_danger(rule.danger, guide);
    if rule.stealth {
        // Пустой отряд считается за одну лапу: множитель не должен обнулять
        // опасность — «удаётся всегда» это свойство заказа, а не состава.
        danger * paws.max(1) as i32
    } else {
        danger
    }
}

/// Сила отряда против этого заказа (§12.113): сумма вкладов, а на разведке —
/// **лучший** из них.
///
/// Максимум взят той же формой и по тем же доводам, что проводник (§12.70):
/// сумма даёт квадратичный рост по размеру отряда, среднее наказывает за то,
/// что кота взяли с собой. Разница в том, что у проводника максимум режет
/// опасность, а здесь — заменяет силу целиком.
///
/// Связь в свёртку не входит и прибавляется снаружи: она копится за время
/// вылазки и принадлежит не коту, а узлу (§12.60).
pub(crate) fn crew_force(rule: &MissionRule, forces: impl Iterator<Item = i32>) -> i32 {
    if rule.stealth {
        forces.max().unwrap_or(0)
    } else {
        forces.sum()
    }
}

/// Насколько этот проводник срезает опасность, в процентах (§12.71).
///
/// Выведено **из самой `raid_danger`**, а не повторено формулой: панель обязана
/// называть следствие реакции, а не её шкалу, — и следствие это не должно уметь
/// разойтись с тем, что случится на возвращении (инвариант 14). Сто здесь —
/// произвольная база для процента, а не опасность какого-то заказа: доля,
/// которую режет проводник, от заказа не зависит.
pub(crate) fn guide_cut(guide: i32) -> i32 {
    100 - raid_danger(100, guide)
}

/// Сырое значение «Реакции» кота — только чтобы назвать проводника по имени
/// (§12.70). В арифметику исхода не входит: там работает ступень, иначе шкала
/// 1–10 перевесила бы силу отряда.
///
/// Нужно оно вот зачем: ступень грубая, и у двоих котов с реакцией 5 и 7 она
/// одна. Назвать ведущим того, у кого реакция ниже, — значит показать игроку
/// заведомо неверное объяснение, хотя механика при этом права.
pub(crate) fn guide_value(rules: &StatRules, stats: Option<&Stats>) -> i32 {
    rules
        .index_of(STAT_GUIDE)
        .map_or(0, |stat| stats.map_or(0, |s| s.value_of(stat)))
}

/// Ступень проводника у одного кота: его «Реакция» в ступенях (§12.70).
///
/// Ступень **кота**, а не отряда: отрядную берут максимумом на месте, и это
/// сделано ради `run_missions` — держать `&Stats` в списке отряда значило бы
/// держать заимствование мира до конца тика, а там же коты правятся.
pub(crate) fn guide_of(rules: &StatRules, stats: Option<&Stats>) -> i32 {
    rules
        .index_of(STAT_GUIDE)
        .map_or(0, |stat| rules.step(stat, stats))
}

/// Сколько тиков отряд из `paws` котов пробудет в поле (§12.70).
///
/// Дорога фиксирована, работа на месте делится на лапы: та же идиома, что
/// `BUILD_WORK / WORK_RATE` на базе (инвариант 9), только очки набивает не один
/// кот, а отряд. Отсюда и смысл большого состава — сила сверх `danger` пропадает
/// (`share` упирается в 100), а лишние лапы уходят в срок.
///
/// **Скорость берётся из числа котов, а не из их силы**, и это главное здесь
/// (§12.70): считай её силой — и сильный отряд выигрывал бы разом по обоим
/// циферблатам, а «послать толпу середняков» не имело бы смысла нигде.
///
/// Зовут это двое — `run_missions` в момент ухода и снапшот для прогноза в
/// панели, — ровно как `outcome` (инвариант 14): игрок обязан видеть тот срок,
/// который получит.
///
/// Отряда без котов не бывает, но ноль сюда всё же доходит из панели, когда
/// бригада пуста; тогда работа не делается вовсе и остаётся одна дорога.
pub(crate) fn duration(rule: &MissionRule, paws: usize) -> i32 {
    if paws == 0 || rule.work <= 0 {
        return rule.travel;
    }
    // Округление вверх, а не вниз: недоделанное очко — это ещё один тик в поле,
    // а срок, обнулённый делением, означал бы вылазку без работы.
    let paws = paws as i32;
    rule.travel + (rule.work + paws - 1) / paws
}

/// Исход по силе отряда и сложности вылазки — **без броска кубика** (§12.23).
///
/// Детерминизм здесь не формальность: он единственное, что делает выбор отряда
/// читаемым. С кубиком игрок не отличил бы «выбрал слабый отряд» от «не
/// повезло», а вылазок за сеанс столько, что вероятность так и не проступит.
///
/// Хватило силы — вся добыча; не хватило — её доля; вдвое меньше нужного —
/// провал: ни добычи, ни сил. Нулевая сложность удаётся всегда, по общему
/// правилу нулей в рулсете (цена тайла, ёмкость склада, потолок бодрости).
pub(crate) fn outcome(danger: i32, strength: i32) -> Outcome {
    if danger <= 0 {
        return Outcome {
            strength,
            share: 100,
            failed: false,
        };
    }
    let failed = strength * 2 < danger;
    Outcome {
        strength,
        share: if failed {
            0
        } else {
            (strength * 100 / danger).min(100)
        },
        failed,
    }
}

/// Держит выбранный игроком отряд идущим к шлюзу.
///
/// Состав здесь не трогается: его назначил `Sim::launch` в момент заявки, и
/// заменить выбывшего некем — это выбор игрока, а не раздача работы (§12.23).
/// Система нужна ровно для того, чтобы маршрут переживал изменения карты:
/// шлюз снесли, кота выбросило из ямы, боец проснулся после истощения.
/// Тот же случай, что `retry_orders` у приказа игрока.
pub(crate) fn gather_squad(
    map: Res<BaseMap>,
    tiles: Res<TileRules>,
    mut commands: Commands,
    mut missions: Query<(Entity, &mut Mission)>,
    crew: Query<
        (Entity, &Squad, &Position, Option<&Path>, Option<&Away>),
        // Спящего не трогаем: маршрут разбудил бы его, а истощение — не повод
        // гнать кота дальше. Проснётся — эта же система его и подберёт. Идущего
        // за снаряжением — тем более: одетым он уйдёт сильнее (§12.29, §12.34).
        // Раненого — тоже: в отряд его не берут вовсе, а если ранило уже
        // назначенного, отряд ждёт, пока тот встанет (§12.23, §12.37).
        (Without<Rest>, Without<Equipping>, Without<Healing>),
    >,
) {
    if missions.is_empty() {
        return;
    }
    let map = &*map;

    for (mission_e, mut mission) in &mut missions {
        // Кто в отряде и где он. Пустой маршрут считается пройденным:
        // `move_units` снимет его только следующим тиком.
        let mut left_base = false;
        let squad: Vec<(Entity, (i32, i32), bool)> = crew
            .iter()
            .filter(|(_, s, ..)| s.0 == mission_e)
            .inspect(|(.., away)| left_base |= away.is_some())
            .map(|(e, _, p, path, _)| {
                let walking = path.is_some_and(|p| !p.steps.is_empty());
                (e, (p.x, p.y), walking)
            })
            .collect();
        // Отряд ушёл — шлюз больше не пересматривается: вернутся коты туда,
        // откуда ушли, даже если гараж успели снести.
        if left_base {
            continue;
        }

        // Шлюз мог уйти под ластиком, пока отряд собирался, — выбираем заново.
        if mission
            .gate
            .is_some_and(|(x, y)| !tiles.is_gate(map.tile_at(x, y)))
        {
            mission.gate = None;
        }
        if mission.gate.is_none() {
            let at: Vec<(i32, i32)> = squad.iter().map(|&(_, at, _)| at).collect();
            mission.gate = pick_gate(map, &tiles, &at);
        }
        let Some(gate) = mission.gate else {
            continue; // шлюза нет или до него не добраться всем разом
        };

        for &(cat_e, at, walking) in &squad {
            if walking || at == gate {
                continue;
            }
            if let Some(steps) = find_path(map, &tiles, at, gate) {
                commands.entity(cat_e).insert(Path { steps });
            }
        }
    }
}

/// Сколько на базе шлюзов — ровно те клетки, среди которых выбирает
/// `pick_gate`. Наружу едет числом (§12.53): снесённый гараж делает вылазку
/// невозможной, и молчащая кнопка «Отправить» читается как поломка.
pub(crate) fn gate_count(map: &BaseMap, tiles: &TileRules) -> usize {
    gate_cells(map, tiles).count()
}

/// Шлюз, к которому отряду суммарно ближе всего идти.
///
/// Клетки, до которых дойдут не все, отбрасываются: состав фиксирован, и шлюз,
/// отрезанный от одного из бойцов, значит вылазку, которая никогда не тронется.
/// Ничьи разрешает порядок обхода карты, то есть детерминированно.
pub(crate) fn pick_gate(map: &BaseMap, tiles: &TileRules, at: &[(i32, i32)]) -> Option<(i32, i32)> {
    let reaches: Vec<Reach> = at.iter().map(|&p| Reach::all(map, tiles, p)).collect();
    gate_cells(map, tiles)
        .filter_map(|(x, y)| {
            let mut total = 0;
            for r in &reaches {
                total += r.dist_at(x, y)?;
            }
            Some((total, (x, y)))
        })
        .min_by_key(|&(total, _)| total)
        .map(|(_, cell)| cell)
}

/// Есть ли на базе силы прийти за пленным — считается **до** того, как его
/// оставят (§12.40).
///
/// Плен обратим по определению: он стоит котовремени, а не кота (§12.37). Но
/// обратимость держится не на обещании, а на этой проверке: если базе некем
/// снарядить самый маленький спасательный отряд, отряд тащит раненого сам, и
/// плена не случается вовсе. Иначе провал на трёх котах запирал бы игру
/// насмерть — та самая необратимость, которой §12.10 избегает.
///
/// Считаются вылазки, доступные **прямо сейчас**: известность только растёт
/// (§12.24), но ждать её, сидя в плену, кот будет столько же, сколько никогда.
///
/// Фракционных ворот здесь нет **намеренно** (§12.43), и это не экономия. Вся
/// обратимость плена держится на том, что известность монотонна: до порога
/// база рано или поздно дорастёт, и проверка честна. Репутация умеет падать —
/// значит база, рассорившаяся со всеми, теряла бы кота навсегда. Это смерть
/// через чёрный ход, которой в игре нет (§12.37), поэтому вылазка за своим не
/// закрыта ни репутацией, ни `needs` у самого правила.
fn rescue_is_possible(rules: &MissionRules, fame: i32, on_base: usize) -> bool {
    rules
        .0
        .iter()
        .any(|r| r.rescue && r.requires <= fame && r.squad <= on_base)
}

/// Отправляет собравшийся отряд, крутит таймер и возвращает котов с добычей.
///
/// Стоит после `move_units`: кот, шагнувший на шлюз в этом тике, засчитывается
/// сразу, — и до `settle_stacks`, чтобы добыча, вывалившаяся в свежую яму,
/// съехала на пол тем же тиком (§12.15).
///
/// **Провал может оставить кота в плену** (§12.40), а вылазка с `rescue` —
/// привести пленных обратно. И то, и другое — работа с составом отряда, а не с
/// добычей, поэтому живёт здесь же: другого места, где известно, чем кончилась
/// вылазка, нет.
pub(crate) fn run_missions(
    raid_rules: RaidRules,
    factions: Res<FactionRules>,
    mut fame: ResMut<Fame>,
    mut standing: ResMut<Standing>,
    mut raids: ResMut<Raids>,
    mut commands: Commands,
    mut missions: Query<(Entity, &mut Mission)>,
    mut crew: Query<(
        Entity,
        &Squad,
        &UnitId,
        &Position,
        Option<&Path>,
        Option<&Away>,
        Option<&Skills>,
        Option<&mut Energy>,
        Option<&Gear>,
        Option<&mut Health>,
        // Врождённое: им отряд режет опасность заказа (§12.70). Читается только
        // здесь и в прогнозе для панели — двумя вызывающими одного выражения,
        // как и сила (инвариант 14).
        Option<&Stats>,
    )>,
    // Весь личный состав базы: по нему считается, есть ли кому прийти за
    // пленным. **Ушедшие сюда входят** (§12.59): кот в поле — твой кот, он
    // вернётся и сходит за товарищем, — тот же довод, что у `WorldFacts::cats`
    // в целях. Фильтр `Without<Away>` стоял здесь, пока вылазка была одна; с
    // несколькими узлами связи он превращался в бесплатную страховку — «отправь
    // второй отряд, и первый никого не потеряет», — потому что второй отряд не
    // попадал в счёт и проверка занижала силы базы.
    roster: Query<(), With<UnitId>>,
    // Пленные — те, за кем идёт вылазка с `rescue`. Только сущности: позицию
    // им ставит `Commands`, иначе этот запрос конфликтовал бы с `crew` за
    // `Position` и bevy уронил бы систему на старте.
    captives: Query<Entity, With<Captive>>,
    // Дежурные на узлах связи (§12.60). Только те, кто **дошёл**: идущий к рации
    // ещё не держит связь, и засчитывать ему дорогу значило бы платить за
    // намерение. Позиция сюда не нужна — `assign_relay` ведёт кота маршрутом, и
    // «дошёл» это снятый `Path`.
    duty: Query<(Entity, &OnDuty, Option<&Skills>), Without<Path>>,
    map: Res<BaseMap>,
    tiles: Res<TileRules>,
    mut stacks: Query<(Entity, &Position, &mut Stack)>,
) {
    let RaidRules {
        missions: rules,
        skills: skill_rules,
        stats: stat_rules,
        items,
    } = raid_rules;
    let raid = skill_rules.index_of(SKILL_RAID);
    let comms = skill_rules.index_of(SKILL_RELAY);
    // Пленные, взятые **в этом же тике**: `Captive` вешает `Commands`, то есть
    // запрос `captives` увидит их только следующим тиком, а вернуться разом
    // может не один отряд (§12.59). Без этого счётчика два провала подряд
    // оставили бы двоих там, где база тянет только одного.
    let mut lost_this_tick = 0usize;
    for (mission_e, mut mission) in &mut missions {
        let Some(rule) = rules.0.get(mission.def) else {
            continue;
        };
        let Some(gate) = mission.gate else {
            continue; // шлюз ещё не выбран
        };

        let squad: Vec<(Entity, (i32, i32), bool, bool, i32, i32)> = crew
            .iter()
            .filter(|(_, s, ..)| s.0 == mission_e)
            .map(|(e, _, _, p, path, away, skills, _, gear, _, stats)| {
                let walking = path.is_some_and(|p| !p.steps.is_empty());
                // Вклад кота в силу отряда: сам он стоит единицу, навык —
                // сверху, надетое — ещё сверху. Нулевой навык поэтому не значит
                // «бесполезен», а снаряжение — второе слагаемое, которое растёт
                // не от навыка и не упирается в его потолок (§12.29).
                let force = 1
                    + raid.map_or(0, |s| level_of(&skill_rules, skills, s))
                    + items.force_of_gear(gear);
                (
                    e,
                    (p.x, p.y),
                    walking,
                    away.is_some(),
                    force,
                    guide_of(&stat_rules, stats),
                )
            })
            .collect();

        // Отряд в поле. База о нём ничего не знает: ни усталости, ни маршрутов —
        // вылазка считается разом по возвращении, а не симулируется (§12.22).
        if squad.iter().any(|&(.., away, _, _)| away) {
            // Опыт капает за тик в поле, как и на любой другой работе (§12.17):
            // начисляет его `train_skills` в конце цепочки, здесь только маркер.
            if let Some(skill) = raid {
                for &(cat_e, ..) in &squad {
                    commands.entity(cat_e).insert(Worked(skill));
                }
            }
            // Связь копится **за каждый тик**, пока на узле сидит дежурный
            // (§12.60). Одним замером её мерить нельзя: на уходе хватило бы
            // посадить кота на тик, а на возвращении бонус повис бы на том, кто
            // случайно оказался у рации в последний тик, — это уже не решение
            // игрока, а расписание. Дежурному тоже капает опыт: домен «Связь»
            // растёт от работы, как и все остальные (§12.17).
            for (cat_e, on_duty, skills) in &duty {
                if on_duty.spot != mission.node {
                    continue;
                }
                mission.covered += duty_gain(&tiles, &map, &skill_rules, skills, on_duty.spot);
                if let Some(skill) = comms {
                    commands.entity(cat_e).insert(Worked(skill));
                }
            }

            mission.left -= 1;
            if mission.left > 0 {
                continue;
            }

            // Исход считаем по силе **на возвращении**: за вылазку навык вырос,
            // и отнимать этот рост у самой вылазки было бы странно. Связь входит
            // сюда же, в **ту же** силу, а не пятым слагаемым исхода: инвариант
            // 14 держит `outcome` одним выражением на прогноз и на результат.
            let force: i32 = crew_force(rule, squad.iter().map(|&(.., f, _)| f))
                + relay_force(mission.covered, mission.span);
            // Опасность — та, какую встретил этот отряд: проводник режет её
            // делением (§12.70), а разведка умножает на число лап (§12.113).
            // Считается тем же выражением, что и в прогнозе для панели: игрок
            // обязан получить то, что ему показали.
            let guide = squad.iter().map(|&(.., g)| g).max().unwrap_or(0);
            let out = outcome(crew_danger(rule, guide, squad.len()), force);

            // Кто из отряда остался там (§12.40). Выбор — **первый по `id`**, и
            // это намеренно ничего не значит: причины плена игра не называет.
            // Ни здоровье, ни навык сюда не входят — «оставили того, кому
            // досталось больше» рассказывало бы, что своих раненых бросают, а
            // это не про боевых котов. Что известно игроку — то и решает:
            // провал вылазки, дальше подробности за кадром. `id` здесь ровно
            // за детерминизмом (§11): порядок сущностей в ECS зависит от
            // истории вставок, а «кого оставили» игрок увидит и запомнит.
            //
            // Своя же вылазка за пленным пленных не оставляет никогда, иначе
            // неудачное спасение плодит второго пленника и база уходит в
            // спираль. И некому идти — тоже не оставляет: см. `rescue_is_possible`.
            //
            // Считается это **личным составом за вычетом пленных и минус один
            // за нового** (§12.59), а не «кто сейчас дома»: иначе число зависело
            // бы от того, сколько отрядов случайно в поле, и второй отряд
            // страховал бы первый от потери.
            let on_base = roster
                .iter()
                .count()
                .saturating_sub(captives.iter().count() + lost_this_tick + 1);
            let captive =
                if out.failed && !rule.rescue && rescue_is_possible(&rules, fame.0, on_base) {
                    crew.iter()
                        .filter(|(_, s, ..)| s.0 == mission_e)
                        .map(|(e, _, id, ..)| (id.0.as_str(), e))
                        .min()
                        .map(|(_, e)| e)
                } else {
                    None
                };
            if captive.is_some() {
                lost_this_tick += 1;
            }

            // Успешное спасение возвращает **всех**, кого нашли: делить своих
            // на «этого забрали, а за тем сходите ещё раз» — это не сложность,
            // а вторая ходка за тем же самым. Частичный успех тоже возвращает:
            // доля считается в добыче, а кот либо дома, либо нет (§12.40).
            if rule.rescue && !out.failed {
                for cat_e in &captives {
                    commands
                        .entity(cat_e)
                        .remove::<(Away, Captive)>()
                        .insert(Position {
                            x: gate.0,
                            y: gate.1,
                        });
                }
            }

            for &(cat_e, ..) in &squad {
                // Пленный остаётся в поле: `Away` при нём, отряда больше нет —
                // миссия сейчас исчезнет, и ссылка на неё повисла бы.
                match Some(cat_e) == captive {
                    true => {
                        commands.entity(cat_e).remove::<Squad>().insert(Captive);
                    }
                    false => {
                        commands.entity(cat_e).remove::<(Away, Squad)>();
                    }
                }
                // Плата за вылазку — котовремя: та же валюта, в которой
                // измеряется и сама отправка отряда. Провал забирает всё, и
                // коты валятся у шлюза — `collapse_exhausted` подберёт их.
                //
                // Раны считаются **той же долей**, что и добыча: полный успех не
                // царапает никого, полсилы стоят половины `harm`, провал — всего
                // (§12.37). Отдельной формулы для урона нет намеренно: две
                // арифметики исхода разошлись бы, а прогноз в панели показывал
                // бы игроку не то, что случится (§12.23).
                if let Ok((.., energy, _, health, _)) = crew.get_mut(cat_e) {
                    if let Some(mut energy) = energy {
                        let toll = if out.failed { energy.0 } else { rule.toll };
                        energy.0 = (energy.0 - toll).max(0);
                    }
                    if let Some(mut health) = health {
                        // Раны у всех одни — те, что посчитал исход. Пленному
                        // сверх этого не достаётся ничего: плен — это место, а
                        // не наказание, и добивать оставленного там кота ядру
                        // незачем (§12.40).
                        health.0 = (health.0 - rule.harm * (100 - out.share) / 100).max(0);
                    }
                }
                // Провал ломает снаряжение: до него он стоил только бодрости, а
                // она восстанавливается бесплатно — то есть заведомо провальная
                // вылазка была способом качать «Вылазку» за одно лишь время
                // (§12.29). Успех не изнашивает: износ за каждый выход
                // превратил бы петлю «добыча → сила» в оброк. Комплект наберётся
                // заново, как только на складе снова будет из чего.
                if out.failed {
                    commands.entity(cat_e).remove::<Gear>();
                }
            }
            // Добыча ложится кучей на шлюз — ровно как возврат от сноса ложится
            // под ноги сносильщику. Развозит её обычная уборка (§12.16).
            for &(item, count) in &rule.loot {
                let got = count * out.share / 100;
                if got > 0 {
                    spill(&mut commands, &mut stacks, gate, item, got);
                }
            }
            // Известность идёт той же долей, что и добыча: слухи расходятся по
            // сделанному, а не по задуманному. Провал не приносит ничего — но и
            // не отнимает: ворота, которые закрываются, читаются как поломка
            // (§12.24).
            fame.0 += rule.fame * out.share / 100;
            // Журнал совершённого (§12.58). Пишется **здесь и только здесь**:
            // это единственный момент, когда вылазка засчитана, — как деньги за
            // продажу считает только `work_hauls`. Провал в журнал не идёт:
            // «сходил и вернулся ни с чем» — не поступок, за который дают цель.
            if !out.failed && !raids.0.contains(&mission.def) {
                raids.0.push(mission.def);
            }
            // Репутация расходится **по сделанному** — тем же выражением, что и
            // добыча с известностью (§12.43). Отсюда её главное свойство: у
            // провала доля нулевая, значит провал не двигает репутацию вовсе.
            // Сорванный налёт на Синдикат Синдикат не разозлил — базе просто
            // нечего ему предъявить, и наказания поверх наказания не выходит
            // (§12.23 уже забрал добычу, силы, снаряжение и кота).
            //
            // Заказчику вверх, пострадавшему вниз, и **ровно настолько же**:
            // это и делает нейтралитет нулевым, а не бесплатным. Две зеркальные
            // вылазки, взятые по очереди, оставляют базу там же, где нашли.
            let moved = rule.standing * out.share / 100;
            if let Some(f) = rule.patron {
                standing.add(f, moved, factions.span_of(f));
            }
            if let Some(f) = rule.against {
                standing.add(f, -moved, factions.span_of(f));
            }
            commands.entity(mission_e).despawn();
            continue;
        }

        // Уходим, когда все, кого взяли, стоят на шлюзе: пустой отряд здесь —
        // это «ещё идут», а не «недобрали».
        //
        // **Кого взяли, решено в момент клика** (§12.70): спящего, раненого и не
        // вернувшегося `launch_at` в отряд не записал вовсе, и ждать их некому.
        // Ждут ровно тех, кто уже в `Squad`, — они идут ногами, и это видимая
        // игроку беготня, а не простой.
        // Минимум вилки здесь больше не спрашивается (§12.113): недокомплект
        // разрешён и уже оплачен — долей добычи и сроком. Ждать некого, если
        // все, кого взяли, дошли.
        let ready = !squad.is_empty()
            && squad
                .iter()
                .all(|&(_, at, walking, ..)| at == gate && !walking);
        if ready {
            // Срок замерзает здесь и больше не пересчитывается (§12.70) — как
            // курс сделки замерзает в момент заказа (§12.44). Считается он по
            // числу ушедших лап: тем же выражением, каким панель показала
            // прогноз до нажатия.
            mission.span = duration(rule, squad.len());
            mission.left = mission.span;
            for &(cat_e, ..) in &squad {
                commands.entity(cat_e).insert(Away);
            }
        }
    }
}
