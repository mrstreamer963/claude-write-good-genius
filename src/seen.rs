//! Знакомство с предметом: что база уже видела своими глазами (§12.131).
//!
//! Модуль крошечный намеренно. Шкала-ворота обычно обходится без системы —
//! у `Fame`, `Techs` и `Standing` их нет и не было никогда (§12.43): нужна
//! сущность-владелец или тик, а у них только арифметика в момент события.
//! Здесь событие размазано по всему миру — предмет «побывал на базе» может
//! приехать добычей, подарком, покупкой, выйти из рецепта или лечь стартовой
//! кучей, — и крючок в каждом из этих мест был бы шестью местами вместо
//! одного, где однажды забудут седьмое.
//!
//! Поэтому наблюдатель. Место у него — **цепочка**, рядом с `check_goals`, а
//! не фасад рядом с `note_news`: тот живёт в фасаде потому, что читает
//! **ворота** (`raid_is_open`, `topic_is_open`), а второй их экземпляр в
//! системе разошёлся бы с первым (инвариант 14). Здесь ворот нет — есть
//! чистый запрос по миру, ровно как у цели партии.

use bevy_ecs::prelude::*;

use crate::components::{Carrying, Gear, Seen, Stack};

/// Отметить всё, что сейчас есть в мире базы.
///
/// Мир не меняет: наблюдатель, как `check_goals`. Трёх запросов хватает на все
/// входы — добыча вылазки, подарок таймлайна, покупка, выход рецепта и темы,
/// стартовый склад **все** ложатся кучей (`Stack`) и живут там минимум до
/// конца тика, а `Carrying` ловит то, что кот подхватил с пола, не донеся.
///
/// `Gear` в списке не ради полноты входа, а ради **старых снимков**: формат до
/// §12.131 шкалы не вёз, и надетый комбинезон иначе оказался бы «невиданным»
/// у базы, которая в нём ходит.
pub(crate) fn note_seen(
    mut seen: ResMut<Seen>,
    stacks: Query<&Stack>,
    paws: Query<&Carrying>,
    worn: Query<&Gear>,
) {
    for stack in &stacks {
        if stack.count > 0 {
            seen.mark(stack.item);
        }
    }
    for load in &paws {
        if load.count > 0 {
            seen.mark(load.item);
        }
    }
    for gear in &worn {
        for &item in &gear.0 {
            seen.mark(item);
        }
    }
}
