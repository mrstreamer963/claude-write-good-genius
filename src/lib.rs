//! SP / Эсперы — ядро симуляции.
//!
//! bevy_ecs-мир крутится в WebWorker (WASM), контент грузится из YAML-рулсета
//! (стиль OpenXcom Extended). Наружу торчит один тип — `Sim` (модуль `sim`):
//! это и есть весь API для воркера.
//!
//! Раскладка по модулям:
//!   * `ruleset`    — YAML-контент → структуры (serde);
//!   * `map`        — тайловая карта: проходимость и версия;
//!   * `path`       — BFS: дерево кратчайших путей и маршруты;
//!   * `components` — компоненты ECS и ресурсы мира (данные без поведения);
//!   * `schedule`   — цепочка систем одного тика; новая система добавляется только сюда;
//!   * `jobs`       — чертежи: раздача котам и работа над ними;
//!   * `hauling`    — перенос лома: доставка на площадку и возврат при сносе;
//!   * `movement`   — шаги по маршруту, повтор приказов, выход из пустоты;
//!   * `demolition` — порядок сноса (волна от берега вглубь);
//!   * `needs`      — усталость и отдых: кот сам уходит спать;
//!   * `skills`     — навыки: рост от работы, скорость работы;
//!   * `snapshot`   — DTO наружу (worker → main);
//!   * `sim`        — `#[wasm_bindgen]`-фасад.
//!
//! Сквозные инварианты, которые ломаются незаметно:
//!   * **Проходимость** — ходить можно только по построенному полу (индекс тайла >= 0);
//!     пустые клетки (-1) непроходимы, путь ищется BFS по 4-связной сетке. Но
//!     проходимость *стартовой* клетки не требуется — на этом держится выход кота
//!     из ямы.
//!   * **Детерминизм** — фиксированный тик, фиксированный порядок `DIRS`, никакого
//!     рандома и wall-clock внутри систем (§11 concept.md).
//!   * **Версия карты** — единственный сигнал «карта изменилась»: и гейт повторов
//!     приказов, и триггер отправки карты в рендер. Тайлы менять только через
//!     `BaseMap::set`.

