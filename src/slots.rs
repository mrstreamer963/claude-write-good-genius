//! Слот — это объект, а не клетка (§12.161).
//!
//! Счётность §12.55 («комната = слот») до §12.160 держалась на **клетках**:
//! сколько клеток с ролью, столько параллельных тем, заказов, сделок и вылазок.
//! Пока постройка была клеткой, это совпадало с намерением; с объектом-штампом
//! перестало — лаборатория из трёх клеток дала бы три темы вместо одной темы на
//! три места, то есть ровно противоположное задуманному.
//!
//! Правило одно и общее на четыре механики: **клетки роли, принадлежащие одному
//! объекту, считаются одним слотом**, а клетка, не принадлежащая никакому, —
//! слотом сама по себе. Второе не оговорка совместимости, а тот же принцип:
//! одиночная клетка и есть объект из одной клетки, и стартовая застройка,
//! выложенная рамкой, продолжает считаться ровно как считалась.
//!
//! Отсюда же и то, чем счётность перестала быть дисциплиной автора рулсета
//! (§12.160): гараж, заложенный залом 6×4 **штампом**, даёт одну вылазку, а не
//! двадцать четыре. Залом из отдельных клеток — по-прежнему двадцать четыре, и
//! это честно: игрок построил двадцать четыре гаража.

use std::collections::HashSet;

use bevy_ecs::prelude::*;

use crate::components::{Structure, StructureRules, TileRules};
use crate::map::BaseMap;

/// Кому принадлежит клетка: номер объекта или `NONE`.
///
/// Плоский массив по карте, а не `HashMap`: спрашивают его в обходах всей
/// карты, и порядок обхода обязан оставаться фиксированным (§11).
pub(crate) struct Owners {
    width: i32,
    height: i32,
    cells: Vec<i32>,
}

/// Клетка ничьих объектов — сама себе слот.
const NONE: i32 = -1;

impl Owners {
    /// Разметить карту по объектам. `list` — `(def, anchor, rot)` каждого
    /// объекта в мире; номер объекта = его место в этом списке.
    ///
    /// Список приходит параметром, а не из мира: зовут это и системы (у них
    /// `Query`), и фасад (у него `World`), а второй способ узнать, где стоят
    /// объекты, разошёлся бы с первым (инвариант 14).
    pub(crate) fn of(
        map: &BaseMap,
        rules: &StructureRules,
        list: impl Iterator<Item = (usize, (i32, i32), u8)>,
    ) -> Self {
        let mut owners = Owners {
            width: map.width,
            height: map.height,
            cells: vec![NONE; (map.width * map.height) as usize],
        };
        for (n, (def, anchor, rot)) in list.enumerate() {
            let Some(rule) = rules.0.get(def) else {
                continue;
            };
            for ((x, y), _) in rule.stamp(anchor, rot) {
                if let Some(i) = owners.index(x, y) {
                    owners.cells[i] = n as i32;
                }
            }
        }
        owners
    }

    fn index(&self, x: i32, y: i32) -> Option<usize> {
        (x >= 0 && y >= 0 && x < self.width && y < self.height)
            .then(|| (y * self.width + x) as usize)
    }

    fn at(&self, x: i32, y: i32) -> i32 {
        self.index(x, y).map_or(NONE, |i| self.cells[i])
    }
}

/// Клетки роли в порядке обхода карты, схлопнутые по объектам (§12.161).
///
/// От объекта в список попадает **первая** его клетка роли по тому же обходу,
/// остальные не попадают вовсе. Порядок фиксирован, значит и номер отряда, и
/// очередь ячеек остаются детерминированными (§11).
///
/// `role` — свойство тайла, а не отдельная палитра: одно выражение обслуживает
/// лабораторию, мастерскую, торговый пост и гараж, и пятая механика со
/// счётностью обязана прийти сюда же, а не завести свой обход.
pub(crate) fn slot_cells(
    map: &BaseMap,
    tiles: &TileRules,
    owners: &Owners,
    role: fn(&TileRules, i16) -> bool,
) -> Vec<(i32, i32)> {
    let mut seen: HashSet<i32> = HashSet::new();
    let mut out = Vec::new();
    for y in 0..map.height {
        for x in 0..map.width {
            if !role(tiles, map.tile_at(x, y)) {
                continue;
            }
            let owner = owners.at(x, y);
            if owner != NONE && !seen.insert(owner) {
                continue; // этот объект уже дал свой слот
            }
            out.push((x, y));
        }
    }
    out
}

/// Разметка по объектам для системы: тот же `Owners::of`, но берущий список из
/// запроса. Фасад строит её из `World` своим путём — выражение при этом одно.
pub(crate) fn owners_of(
    map: &BaseMap,
    rules: &StructureRules,
    placed: &Query<&Structure>,
) -> Owners {
    Owners::of(map, rules, placed.iter().map(|s| (s.def, s.anchor, s.rot)))
}
