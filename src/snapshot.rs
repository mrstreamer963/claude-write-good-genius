//! DTO наружу (worker → main), сериализуются serde-wasm-bindgen.
//!
//! Это весь контракт с рендером: `map_meta` и `base_map` уходят по требованию
//! (при росте версии карты), `snapshot` — каждый кадр целиком (§12.8a).

use serde::Serialize;

use crate::ruleset::{
    FactionDef, GoalDef, ItemDef, MissionDef, PerkDef, RecipeDef, RecruitDef, ResearchDef,
    SkillDef, StatDef, TileDef,
};

#[derive(Serialize)]
pub(crate) struct MapMeta {
    pub(crate) width: i32,
    pub(crate) height: i32,
    /// Сколько тиков в сутках (§12.46). Едет один раз, как палитры, и нужен
    /// ровно для подписи: «день 12» вместо «тик 42327». Ядро календаря не
    /// считает — это единственное место, где число вообще всплывает.
    pub(crate) day: u64,
    /// Сколько тиков висит тикер новости (§12.120). Едет здесь, а не в снимке,
    /// по тому же доводу, что и `day`: это подача, и ядро её не исполняет.
    pub(crate) news: u64,
    pub(crate) palette: Vec<TileDef>,
    /// Палитра объектов-штампов (§12.160): своя, потому что в клетках карты
    /// лежит индекс `palette`, а штамп в карту не кладётся никогда.
    pub(crate) structures: Vec<StructureSnap>,
    /// Палитра предметов: тип в снапшоте — это её индекс (§12.21).
    pub(crate) items: Vec<ItemDef>,
    /// Палитра навыков: имена и подписи уходят один раз, как палитра тайлов, —
    /// в снапшоте от навыка остаётся только номер (§12.17).
    pub(crate) skills: Vec<SkillDef>,
    /// Палитра врождённых параметров; в снапшоте у кота лежат только значения
    /// в этом порядке (§12.42). Чем параметр ограничивает домен, панель читает
    /// из самого навыка (`stat` и `demands` у записи в `skills`).
    pub(crate) stats: Vec<StatDef>,
    /// Какой из параметров делает проводника (§12.71); `-1` — ни один, механики
    /// проводника в этом рулсете нет. Едет номером по той же причине, что и
    /// сами палитры: панель обязана назвать реакцию по имени и показать её
    /// значение, а искать `reflex` строкой в JS значило бы завести второй
    /// экземпляр правила, которое живёт в `missions::STAT_GUIDE`.
    pub(crate) guide_stat: i32,
    /// Какой навык даёт силу в поле (§12.71); `-1` — такого домена в рулсете
    /// нет. Едет номером по той же причине, что и `guide_stat`: панель обязана
    /// назвать «Вылазку» её же подписью из палитры, а искать `raid` строкой в
    /// JS значило бы завести второй экземпляр правила из `skills::SKILL_RAID`.
    pub(crate) raid_skill: i32,
    /// Ярлыки тем, открывающих правила автоматики (§12.93): «сбыт», «производство»,
    /// «вылазки». Пусто — ворот нет, правило доступно сразу. Нужны виду, чтобы
    /// назвать отказ по имени темы, а не «нужна какая-то наука» (§12.53).
    pub(crate) auto_gates: AutoGateNames,
    /// Подписи перков; в снапшоте у кота лежат только их `id`.
    pub(crate) perks: Vec<PerkDef>,
    /// Палитра фракций: в снапшоте от репутации остаются только числа в этом
    /// порядке (§12.43), как у врождённых параметров кота.
    pub(crate) factions: Vec<FactionDef>,
    /// Палитра миссий: запуск ходит по индексу в этом списке (§12.22).
    pub(crate) missions: Vec<MissionDef>,
    /// Кандидаты на найм; найм ходит по индексу в этом списке (§12.24).
    pub(crate) recruits: Vec<RecruitDef>,
    /// Темы исследования; заявка ходит по индексу в этом списке (§12.26).
    pub(crate) research: Vec<ResearchDef>,
    /// Рецепты; заказ ходит по индексу в этом списке (§12.30).
    pub(crate) recipes: Vec<RecipeDef>,
    /// Палитра целей: ярлыки и подписи едут один раз, как рецепты и темы
    /// (§12.58). В снапшоте от них остаются индексы.
    pub(crate) goals: Vec<GoalDef>,
}

/// Ярлыки тем, открывающих автоматику (§12.93). Пустая строка — ворот нет.
///
/// Едет в `meta`, а не в снимке: имя темы — контент, оно за партию не меняется.
/// В снимке остаётся только «изучена ли» — три флага, как `post_free`.
#[derive(Serialize, Default)]
pub(crate) struct AutoGateNames {
    pub(crate) sales: String,
    pub(crate) crafting: String,
    pub(crate) raids: String,
}

/// Объект-штамп для вида (§12.162): силуэт **уже повёрнутый**, все четыре
/// четверти сразу.
///
/// Сетка тайлов наружу не едет вовсе, и это не экономия: поворот — правило, а
/// не данные, и посчитанный второй раз в JS он однажды нарисует рамку, которую
/// фасад отклонит (инвариант 14). Вид получает готовые смещения и рисует по
/// ним, ничего не выводя.
#[derive(Serialize, Clone)]
pub(crate) struct StructureSnap {
    pub(crate) id: String,
    pub(crate) label: String,
    /// Технология, открывающая объект; пусто — доступен сразу. Прячет закрытый
    /// объект из палитры тот же код, что прячет закрытый тайл (§12.126).
    pub(crate) tech: String,
    /// Цена всего объекта — сумма цен его клеток: `(предмет, сколько)`.
    /// Считает ядро, потому что складывать её в JS значило бы завести второе
    /// место, знающее, из чего состоит штамп.
    pub(crate) cost: Vec<(usize, i32)>,
    /// Силуэт по четвертям оборота: `shapes[rot]` — список `(dx, dy, тайл)`
    /// от левого верхнего угла занятого прямоугольника.
    pub(crate) shapes: Vec<Vec<(i32, i32, i16)>>,
}

#[derive(Serialize)]
pub(crate) struct BaseMapDto<'a> {
    pub(crate) width: i32,
    pub(crate) height: i32,
    pub(crate) cells: &'a [i16],
}

#[derive(Serialize)]
pub(crate) struct Snapshot {
    pub(crate) tick: u64,
    pub(crate) entities: Vec<EntitySnap>,
    pub(crate) blueprints: Vec<BlueprintSnap>,
    pub(crate) stacks: Vec<StackSnap>,
    /// Имущество базы по типам, в порядке палитры `items:` — **разложенное на
    /// три числа** (§12.53). Одно общее число обмануло бы: платит склад (§12.24),
    /// а кучи на полу и груз в лапах в казну ещё не попали.
    pub(crate) stock: Vec<StockSnap>,
    /// Вылазки в работе — **их столько, сколько узлов связи** (§12.59).
    pub(crate) missions: Vec<MissionSnap>,
    /// Вылазки в порядке палитры: можно ли за них взяться и если нет, то почему.
    pub(crate) raids: Vec<RaidSnap>,
    /// Сколько на базе узлов связи (§12.59). Узел — лицензия, а не рабочее
    /// место, как и торговый пост (§12.44). С §12.152 лицензии на вылазку у неё
    /// больше нет — слот держит гараж, — и рация осталась чистой связью: она
    /// прибавляет отряду силы, а не разрешает ему уйти.
    pub(crate) relays: i32,
    /// Сколько на базе гаражей — и, с §12.152, **сколько отрядов у базы** и
    /// сколько вылазок разом (§12.53). Снесли все гаражи, и уйти некуда никому. Считает
    /// ядро теми же клетками, по которым считает слоты `gate_count`, — второй
    /// экземпляр этого правила в JS показал бы живую кнопку, которую фасад
    /// отклонит (инвариант 14).
    pub(crate) gates: i32,
    /// Сколько силы прибавляет связь **за тик** прямо сейчас: сумма вкладов всех
    /// дошедших дежурных (§12.60, §12.152). Считает ядро тем же `duty_gain`,
    /// каким копит `run_missions`, — сложить это в JS запрещает инвариант 14, а
    /// панель рации обязана называть цену дежурства до того, как игрок посадит
    /// туда кота.
    pub(crate) comms_now: i32,
    /// Узлы связи поимённо: клетка, состав и занятость (§12.61). Счёт выше
    /// остаётся, потому что это разные вопросы — «сколько вылазок можно» и «кто
    /// откуда идёт».
    ///
    /// Ворот «свободен ли хоть один узел» здесь нет намеренно. Они были — рядом
    /// со счётом и по тому же правилу «считает ядро» (§12.26), — но с §12.61
    /// вопрос стал поузловым: отряд приписан к клетке, кнопка адресуется узлом,
    /// и спрашивают теперь «занят ли **этот**» (`NodeSnap::busy`). Глобальный
    /// ответ на это не отвечает, и заводить его обратно незачем.
    pub(crate) nodes: Vec<NodeSnap>,
    /// Парты по доменам, в порядке палитры навыков (§12.84). Нужны панели ровно
    /// для одного: сказать словом, **почему** кнопка «Учить» отказала, — иначе
    /// молчащая кнопка читается как поломка (§12.53). Считает ядро, потому что
    /// «свободна» здесь значит «её не держит ничей `Study`», а это знание о
    /// занятости, которого в JS нет.
    pub(crate) desks: Vec<DeskSnap>,
    /// Известность базы: копится от вылазок, открывает вылазки и кандидатов.
    pub(crate) fame: i32,
    /// Репутация по фракциям, в порядке палитры из `map_meta` (§12.43). В
    /// отличие от известности бывает отрицательной: она не копится, а
    /// распределяется.
    pub(crate) standing: Vec<i32>,
    /// Котоденьги (§12.44). Единственная величина, которая и копится, и
    /// тратится: это счёт, а не ворота.
    pub(crate) money: i32,
    /// Сделка в работе; список, а не одна запись, — но фасад пускает по одной
    /// за раз, как вылазку, тему и заказ (§12.44).
    pub(crate) deals: Vec<DealSnap>,
    /// Курсы всех фракций по всем предметам, которыми они торгуют.
    pub(crate) prices: Vec<PriceSnap>,
    /// Действующие правила автопродажи, по одному на предмет (§12.88).
    pub(crate) sales: Vec<SaleSnap>,
    /// Избранные предметы: их строки стоят наверху окна «Склад» (§12.100).
    /// Индексы палитры, отсортированные, — порядок держит ядро.
    pub(crate) favorites: Vec<usize>,
    /// Тикеры: что вынесено лентой на главный экран и с кем по нему торгуют
    /// в один клик (§12.100). Отдельным списком от `favorites`, потому что это
    /// другой вопрос и у него есть сторона.
    pub(crate) tickers: Vec<TickerSnap>,
    /// Сколько на базе торговых постов (§12.55). Пост остался лицензией, а не
    /// рабочим местом (§12.44), — но лицензия счётная: сделок идёт столько,
    /// сколько постов, и второй пост это первая причина его строить.
    pub(crate) posts: i32,
    /// Свободен ли хоть один пост прямо сейчас. Отдельно от счёта, потому что
    /// это **ворота**, и считать их обязано ядро (§12.26): «сделок меньше, чем
    /// постов» второй раз в JS однажды разойдётся с `trade`.
    pub(crate) post_free: bool,
    /// Сколько влезает в контейнер той ячейки, которую займёт следующая заявка
    /// (§12.90); ноль — предела нет. Кнопка сделки берёт отсюда свой размер:
    /// «Shift — полный контейнер» обязано значить то же число, которое примет
    /// фасад, иначе Shift начнёт молча отклоняться.
    pub(crate) post_lot: i32,
    /// Кандидаты в порядке палитры из `map_meta`.
    pub(crate) recruits: Vec<RecruitSnap>,
    /// Тема в работе; список, а не одна запись, — но фасад пока пускает по
    /// одной за раз, как и вылазку (§12.26).
    pub(crate) research: Vec<ResearchSnap>,
    /// Темы в порядке палитры: можно ли взяться и если нет, то почему.
    pub(crate) topics: Vec<TopicSnap>,
    /// Заказ в работе; список, а не одна запись, — но фасад пускает по одному
    /// за раз, как вылазку и тему (§12.30).
    pub(crate) crafting: Vec<CraftSnap>,
    /// Рецепты в порядке палитры: можно ли заказать и если нет, то почему.
    pub(crate) recipes: Vec<RecipeSnap>,
    /// Пороги автопроизводства в порядке палитры рецептов: сколько штук держать
    /// на базе, ноль — правила нет (§12.65). Едет целиком, а не «сколько
    /// осталось»: правило игрок задал сам, и видеть он должен своё число.
    pub(crate) stocking: Vec<i32>,
    /// Сколько на базе мастерских (§12.55). Станок — слот заказа, и заказов
    /// идёт столько же; счёт нужен панели, чтобы отличить «мастерской нет» от
    /// «все станки заняты» — молчащая кнопка читается как поломка (§4.4).
    pub(crate) shops: i32,
    /// Открыта ли автоматика такого рода — то есть изучена ли технология её
    /// ворот (§12.93). Считает ядро: ворота названы в рулсете, а второй их
    /// экземпляр в JS однажды покажет живую строку, которую фасад отклонит
    /// (§12.26). Ярлыки самих тем едут в `meta`: имя — контент, оно уезжает
    /// один раз.
    pub(crate) auto_sales: bool,
    pub(crate) auto_crafting: bool,
    pub(crate) auto_raids: bool,
    /// Убирают ли коты лом с пола без разметки (§12.16). До §12.96 вид держал
    /// это своим зеркалом тумблера, и после загрузки партии зеркало врало:
    /// ресурс в снимке сохраняется, а переменная в JS начиналась заново с
    /// «включено». Пока от флага зависела только подсветка кнопки, цена была
    /// косметической; с §12.96 от него зависит, есть ли у кучи кнопка «на
    /// склад» вообще, — то есть доступность механики.
    pub(crate) auto_tidy: bool,
    /// Изученные технологии. Только растут и только открывают (§12.24, §12.26).
    pub(crate) techs: Vec<String>,
    /// Записка: даты мира и то, что о них известно **сейчас** (§12.28).
    pub(crate) notes: Vec<NoteSnap>,
    /// Цели партии: что закрыто, что нет и сколько осталось (§12.58).
    pub(crate) goals: Vec<GoalSnap>,
    /// Сколько целей идёт в счёт «Цели 3/7». Скрытые не входят, поэтому длина
    /// `goals` знаменателем быть не может: взятая скрытая её раздувает.
    pub(crate) goals_required: usize,
    /// Лента новостей: что открылось и что закрылось, от старого к новому
    /// (§12.120). Едет целиком — она ограничена (`NEWS_MAX`), — а возраст
    /// новости считает вид, по `tick` выше и `news` из `meta`.
    pub(crate) news: Vec<NewsSnap>,
}

/// Одна новость об открытии или закрытии (§12.120).
///
/// Вид назван словом, а не числом: три реестра — это три разных экрана, и
/// перепутать их местами в JS по индексу проще, чем кажется (тот же довод, по
/// которому §12.93 развёл три флага автоматики по именованным полям).
#[derive(Serialize)]
pub(crate) struct NewsSnap {
    /// `raid` · `recruit` · `topic` · `recipe` — какой палитре принадлежит `def`.
    pub(crate) kind: &'static str,
    /// Индекс записи в палитре своего вида.
    pub(crate) def: usize,
    /// `true` — открылось, `false` — закрылось. Закрытие идёт наравне с
    /// открытием намеренно: заказ, который вчера был в списке, а сегодня нет,
    /// игрок помнит, и молчание об этом читается как поломка (§12.43). У темы и
    /// рецепта закрытий не бывает вовсе — технологии не забываются (§12.18).
    pub(crate) opened: bool,
    /// Тик, на котором это случилось: возраст новости вид считает **в тиках**,
    /// значит на паузе стопка не тает.
    pub(crate) at: u64,
}

/// Строка панели целей.
///
/// **Скрытая и невзятая цель сюда не попадает вовсе** — тем же приёмом, что
/// туман предзнания у записки (§12.28): что игроку знать рано, ядро не отдаёт.
/// Спрятанный в JS список вычитывается из снапшота в devtools за минуту, и тогда
/// «скрытая» — это просто необъявленная.
#[derive(Serialize)]
pub(crate) struct GoalSnap {
    /// Индекс записи в `goals:` рулсета; ярлык и подпись лежат в `meta`.
    pub(crate) def: usize,
    pub(crate) done: bool,
    /// Тик взятия — панель разворачивает его в «день 3». Ноль, пока не взята.
    pub(crate) at: u64,
    /// Счётчик «74 / 100». Считает ядро тем же выражением, что и засчитывает
    /// (`goals::progress_of`): разойдись они — панель показывала бы одно, а
    /// цель закрывалась бы по другому (инвариант 14).
    pub(crate) have: i32,
    pub(crate) need: i32,
    /// `required` · `optional` · `hidden` — что цель значит для партии (§12.158).
    /// Словом, а не флагом: статусов стало три, и два булевых поля рядом — это
    /// приглашение перепутать их местами (тот же довод, что у `NewsSnap::kind`).
    pub(crate) kind: &'static str,
    /// Последний тик, на котором цель ещё можно взять; ноль — срока нет. Дни из
    /// него считает панель (§12.46).
    pub(crate) before: u64,
    /// Срок вышел, а цель не взята. Считает ядро — тем же выражением, каким
    /// `check_goals` перестаёт её брать (инвариант 14).
    pub(crate) expired: bool,
    /// С какого тика держалось каждое условие связки, в порядке
    /// `meta.goals[def].parts` (§12.159). Пусто, пока цель не взята: до этого
    /// момента даты ещё двигаются, и показывать их как итог нечего.
    pub(crate) parts: Vec<u64>,
}

/// Строка записки: дата, скелет события и — если срок близко — подробности.
///
/// **Туман предзнания живёт здесь, а не в интерфейсе** (§4.6, §12.28): пока
/// детали не проступили, их в снапшоте просто нет. Спрятанный в JS текст — это
/// не «повреждённые данные», а непоказанный текст, и однажды он покажется.
#[derive(Serialize)]
pub(crate) struct NoteSnap {
    /// Индекс записи в `timeline:` рулсета.
    pub(crate) def: usize,
    pub(crate) label: String,
    /// Тик события и сколько до него осталось (отрицательное — уже позади).
    pub(crate) at: u64,
    pub(crate) left: i64,
    /// «Скелет» — виден всегда, ещё до раскрытия: игрок знает, что будет, но
    /// не знает, чем это грозит.
    pub(crate) hint: String,
    /// Детали проступили: `detail` и `requires` больше не пусты.
    pub(crate) revealed: bool,
    pub(crate) detail: String,
    /// Каких технологий ждёт событие; пусто до раскрытия и у безусловных.
    pub(crate) requires: Vec<String>,
    /// Успевает ли база прямо сейчас — считает ядро, как и доступность найма
    /// (§12.24). До раскрытия деталей это тоже деталь, поэтому всегда false.
    pub(crate) ready: bool,
    /// Событие уже прошло — и вот с каким исходом.
    pub(crate) done: bool,
    pub(crate) succeeded: bool,
}

/// Заказ в работе: сколько штук осталось, сколько сделано у текущей и кто занят.
///
/// Отдельное от темы DTO, потому что у заказа есть то, чего у темы нет и быть не
/// может, — **счётчик штук** (§12.30). Полоска показывает текущую штуку, а не
/// весь заказ: работа считается поштучно, и «40% от пяти» игрок прочтёт неверно.
#[derive(Serialize)]
pub(crate) struct CraftSnap {
    /// Индекс записи в палитре рецептов из `map_meta`.
    pub(crate) def: usize,
    /// Сколько штук осталось, включая ту, что в работе.
    pub(crate) left: i32,
    pub(crate) progress: i32,
    pub(crate) total: i32,
    /// Материала на станке хватает хотя бы на одну штуку: заказ работает, а не
    /// ждёт носильщика (§12.102).
    pub(crate) supplied: bool,
    /// Сколько на станок уже завезли и сколько нужно на всю партию — двумя
    /// числами, дословно `BlueprintSnap` (§12.102): панель клетки пишет
    /// «завезено 12 из 30» тем же выражением, что и у площадки. Штуки разных
    /// типов тут складываются намеренно — это полоска наполнения, а не запас.
    pub(crate) delivered: i32,
    pub(crate) need: i32,
    /// Чего заказу ещё не хватает — **по типам** (§12.128). Полоска наполнения
    /// выше складывает штуки разных типов в одно число, а это вопрос про запас:
    /// «сколько моего лома уже расписано». Считает ядро тем же `craft_missing`,
    /// каким подвоз решает, что нести: второй экземпляр вычитания в JS обещал
    /// бы не то, что уедет со склада.
    pub(crate) owed: Vec<NeedSnap>,
    /// Станок, за которым идёт работа; `-1`, пока исполнителя нет (§12.55).
    /// Мастерских на базе столько, сколько построили, и каждая — слот заказа;
    /// без координат панель клетки не отличила бы занятую от свободной. Та же
    /// причина, по которой шлюз едет в `MissionSnap`.
    pub(crate) x: i32,
    pub(crate) y: i32,
    /// Заказ ведёт правило-порог, а не игрок (§12.65). Панель предлагает у
    /// такого снять порог вместо «Отменить»: отменённый заказ правило завело бы
    /// обратно тем же тиком.
    pub(crate) auto: bool,
    /// Кто у верстака; пусто — исполнитель ещё не нашёлся.
    pub(crate) unit: String,
}

/// Можно ли заказать рецепт прямо сейчас — и если нет, то почему.
///
/// Считает ядро, а не интерфейс, по той же причине, что и у тем (§12.26).
/// `affordable` здесь — **подсказка, а не запрет**: заказ без материала ядро
/// примет, он просто будет ждать, как чертёж без лома (§12.30).
#[derive(Serialize)]
pub(crate) struct RecipeSnap {
    /// Технологии рецепта изучены: он вообще существует.
    pub(crate) unlocked: bool,
    /// И есть мастерская, в которой работать.
    pub(crate) shop: bool,
    /// Сколько штук примет заявка прямо сейчас (§12.114d, §12.129): нехватка
    /// материала — отказ, а не ожидание, и считает его ядро тем же выражением,
    /// каким режет заявку `start_craft`. С §12.129 это верно у **любого**
    /// рецепта, а не только у разбора: ждущий заказ держит станок и расписывает
    /// на себя будущий лом (§12.128).
    pub(crate) room: i32,
}

/// Тема в работе: сколько сделано и кто этим занят.
#[derive(Serialize)]
pub(crate) struct ResearchSnap {
    /// Индекс записи в палитре тем из `map_meta`.
    pub(crate) def: usize,
    pub(crate) progress: i32,
    pub(crate) total: i32,
    /// Кто сейчас за темой; пусто — исполнитель ещё не нашёлся.
    /// Сколько учёных сейчас над темой и сколько мест у её лаборатории
    /// (§12.163). Считает ядро: «сколько мест» это форма объекта, и вывести её
    /// в JS нельзя — сетка тайлов наружу не едет (§12.162).
    pub(crate) crew: i32,
    pub(crate) seats: i32,
    pub(crate) unit: String,
    /// Клетка лаборатории, в которой стоит тема (§12.132). Дословно
    /// `CraftSnap::x`/`y`: тем теперь несколько, и без координат панель клетки
    /// не отличила бы занятую лабораторию от свободной.
    pub(crate) x: i32,
    pub(crate) y: i32,
    /// Чего ещё ждёт вскрытие (§12.133): образец, который к ней везут. Пусто —
    /// тема снабжена и работает. Считает ядро (`topic_missing`) — тем же
    /// выражением, каким подвоз решает, что нести.
    pub(crate) owed: Vec<NeedSnap>,
    /// Есть ли **сейчас на базе** кот, проходящий допуск этой темы (§12.135).
    ///
    /// Отвечает на «почему тема стоит», и ответов два: некому взяться совсем
    /// (все допущенные в поле) — чинится возвращением отряда; или взяться есть
    /// кому, но все заняты другим — чинится само. Без этого поля панель писала
    /// «ждёт исполнителя» и в первом случае, то есть молчала о причине
    /// (§12.53).
    ///
    /// Считает ядро и **не тем же выражением, что ворота заявки**: заявку
    /// открывает наличие такого кота у базы вообще (иначе решение игрока
    /// отменялось бы тем, что учёный сейчас в поле), а это — наличие его здесь
    /// и сейчас. Два вопроса, два поля.
    pub(crate) home: bool,
}

/// Можно ли взяться за тему прямо сейчас — и если нет, то почему.
///
/// Считает ядро, а не интерфейс, по той же причине, что и у кандидатов
/// (§12.24): «есть ли на складе образцы» и «хватает ли кому-то „Науки“» — это
/// знание ядра, и дублировать его в JS значит однажды показать кнопку, которую
/// ядро отклонит.
#[derive(Serialize)]
pub(crate) struct TopicSnap {
    /// Технология уже изучена — второй раз тему не берут.
    pub(crate) known: bool,
    /// Предыдущие технологии на месте: тема вообще существует.
    pub(crate) unlocked: bool,
    /// На складе есть чем заплатить.
    pub(crate) affordable: bool,
    /// На базе есть кот с нужным уровнем «Науки» — это допуск (§12.18).
    pub(crate) staffed: bool,
    /// И есть лаборатория, в которой работать.
    pub(crate) lab: bool,
    /// …и хотя бы одна **свободная** (§12.132). Два поля, а не одно: «нет
    /// лаборатории» чинится стройкой, «все заняты» — окончанием чужой темы, и
    /// это два разных слова в отказе (§12.53, §12.124).
    pub(crate) lab_free: bool,
    /// Эта тема уже идёт. До §12.132 вид держал это глобальным флагом «наука
    /// занята» — тема была одна; теперь занята бывает одна строка из шести.
    pub(crate) busy: bool,
    /// Образец темы база уже видела (§12.131, §12.133) — иначе вскрывать
    /// нечего, и тема закрыта совсем: в реестре она стоит витриной (§12.137),
    /// но взяться за неё нельзя.
    pub(crate) sighted: bool,
    /// Образец **лежит на складе прямо сейчас** (§12.139) — за вычетом брони,
    /// тем же выражением, что и `affordable`.
    ///
    /// Второе поле рядом с `sighted`, а не вместо него: «никогда не видели» и
    /// «видели, но свободного нет» — это два разных отказа и два разных слова
    /// (§12.53). Считает ядро, потому что склад — то же самое число, каким
    /// платят (§12.24), и второй его экземпляр в JS показал бы живую кнопку,
    /// которую фасад отклоняет (инвариант 14).
    pub(crate) stocked: bool,
    /// Что именно надо повидать/привезти — чтобы отказ назывался предметом, а
    /// не «нужен образец» вообще (§12.53).
    pub(crate) specimen: Vec<usize>,
}

/// Сделка в работе (§12.44): что, у кого, почём и сколько ещё ждать.
///
/// Курс здесь **зафиксированный при заказе**, а не сегодняшний: панель обязана
/// показывать то, по чему на самом деле рассчитаются. Расписание к этому моменту
/// могло уйти — это и есть весь риск торговли.
#[derive(Serialize)]
pub(crate) struct DealSnap {
    pub(crate) faction: usize,
    pub(crate) item: usize,
    pub(crate) count: i32,
    pub(crate) unit: i32,
    pub(crate) buying: bool,
    /// Тиков до отгрузки. У покупки идёт с заказа, у продажи — с момента, когда
    /// контейнер набит целиком (§12.68); ноль у продажи значит «ещё набивают»,
    /// и мерить это время тиками нечем — его меряют ходки котов.
    pub(crate) left: i32,
    /// Сколько штук уже лежит в контейнере; только у продажи.
    pub(crate) delivered: i32,
    /// Ячейка торгового поста, которую сделка занимает (§12.68).
    ///
    /// Едет наружу, потому что предел торговли перестал быть невидимым
    /// счётчиком: обе сделки рисуются прямо на карте одним словарём — контур
    /// «ячейка занята», заливка «сколько уже здесь», цифра «сколько тиков», —
    /// и читаются, не открывая панель.
    pub(crate) x: i32,
    pub(crate) y: i32,
}

/// Курс фракции по предмету — то же выражение, что рассчитает заказ (§12.44).
///
/// Расписание **видно вперёд**: рядом с сегодняшней ценой едет следующая и
/// сколько тиков до смены. Без этого игрок не планирует, а караулит (§12.40).
#[derive(Serialize)]
pub(crate) struct PriceSnap {
    pub(crate) faction: usize,
    pub(crate) item: usize,
    /// Почём купить и почём продадут — уже с наценкой и поправкой на репутацию.
    pub(crate) buy: i32,
    pub(crate) sell: i32,
    /// Что будет в следующей фазе и через сколько тиков она настанет;
    /// `next_in = 0` — расписание не меняется вовсе.
    pub(crate) next_buy: i32,
    pub(crate) next_sell: i32,
    pub(crate) next_in: u64,
    /// Что было в **прошлой** фазе. Из этого вид считает стрелку `▲+1` в
    /// строке склада и в ленте тикеров (§12.100): строка отвечает «что сейчас»,
    /// и прогноз вперёд её распирает, — он остаётся в подсказке, где и живёт
    /// сегодня.
    ///
    /// Числом, а не готовой дельтой: вычесть вид умеет, а два поля вместо
    /// четырёх везли бы одно и то же дважды. Расписание — кольцо, поэтому
    /// «прошлая фаза» есть всегда, даже на первом тике партии.
    pub(crate) prev_buy: i32,
    pub(crate) prev_sell: i32,
    /// Ворота на сам товар (§12.150): известности хватает / репутации хватает.
    ///
    /// Два флага врозь, а не их «и», по тому же доводу, что у `RaidGates` и
    /// `RecruitSnap`: кнопка обязана назвать причину отказа словом (§12.53), а
    /// «нельзя» без причины игрок читает как поломку. Закрывают они только
    /// покупку — продать можно всегда.
    ///
    /// Цена у закрытой строки едет **обычная**: «почём будет» и есть ответ на
    /// «ради чего расти», и прятать её значило бы отказать без причины.
    pub(crate) unlocked: bool,
    pub(crate) welcome: bool,
}

/// Правило автопродажи по предмету: кому и сколько придерживать (§12.88).
///
/// Отдельным списком, а не полем в `PriceSnap`: правило висит на **предмете**, а
/// строк курса у одного предмета столько, сколько сторон им торгует. Пока
/// `keep` ехал там, у лома он приезжал дважды — и второе число было ложью, ведь
/// правило одно.
///
/// Едут только действующие правила: ноль — это «правила нет», и пустая строка в
/// списке значила бы то же самое вторым способом.
#[derive(Serialize)]
pub(crate) struct SaleSnap {
    pub(crate) item: usize,
    /// Куда уходит излишек: сторона — или `null`, то есть **в разбор**
    /// (§12.115). Одно поле, потому что и решение одно: два правила на один
    /// излишек спорили бы за один и тот же предмет.
    pub(crate) faction: Option<usize>,
    pub(crate) keep: i32,
}

/// Тикер: предмет, вынесенный лентой на главный экран, и сторона, с которой по
/// нему торгуют в один клик (§12.100).
///
/// Форма — `SaleSnap` без порога, и это не совпадение: у обоих ключ предмет, а
/// сторона поле, и по обоим бывает ровно одно решение (§12.88). Отдельно от
/// избранного (`favorites`), потому что вопроса два: «где эта строка в окне» и
/// «видно ли её, не открывая окна». У первого стороны нет вовсе.
#[derive(Serialize)]
pub(crate) struct TickerSnap {
    pub(crate) item: usize,
    pub(crate) faction: usize,
}

/// Можно ли взяться за вылазку прямо сейчас — и если нет, то почему.
///
/// Считает ядро по той же причине, что и доступность найма (§12.24): ворота
/// вылазки — это знание о лестнице известности и о том, есть ли ещё кого
/// спасать, а второй его экземпляр в JS однажды покажет кнопку, которую ядро
/// отклонит. Состав отряда сюда не входит: кого выбрать, знает только интерфейс.
/// Три причины отказа разведены намеренно: панель называет их словом, а
/// молчащая кнопка читается как поломка (§12.24, §12.40).
#[derive(Serialize, Default)]
pub(crate) struct RaidSnap {
    /// Известности хватает: за дело, о котором ещё не слышали, не берутся.
    pub(crate) unlocked: bool,
    /// Заказчик доверяет: репутация не ниже пола (§12.43). Отдельно от
    /// известности, потому что «не дорос» и «эти с тобой не разговаривают» —
    /// разные новости, и вторая ещё и обратима.
    pub(crate) welcome: bool,
    /// У вылазки есть цель: за своим идут, только пока есть за кем (§12.40).
    /// У обычной вылазки цель есть всегда.
    pub(crate) possible: bool,
    /// Сколько вылазка займёт у **минимального** состава (§12.71) — медленный
    /// край вилки. От узла не зависит: это свойство самого заказа, — и потому
    /// едет здесь, а не в `NodeSnap`, где срок считается для нынешних лап.
    ///
    /// Нужен, чтобы игрок видел «сколько это займёт» **до набора отряда**, где
    /// считать ещё не на кого. Быстрый край наружу не едет намеренно: панель
    /// показывает срок формулой («дорога 60 + работа 360 / 2 кота»), из которой
    /// рычаг виден и без второго числа, а гипотезу о составе, которого нет,
    /// игрок читает как обещание. Считает тот же `duration`, что и уход
    /// (инвариант 14).
    pub(crate) span_slow: i32,
}

/// То же самое для ядра: снапшот на хосте не собрать, а тестам нужны ровно эти
/// три ответа.
pub(crate) type RaidGates = RaidSnap;

/// Можно ли нанять кандидата прямо сейчас — и если нет, то почему.
