/// Куча предметов на полу; `item` — индекс палитры из `map_meta`.
#[derive(Serialize)]
pub(crate) struct StackSnap {
    pub(crate) x: i32,
    pub(crate) y: i32,
    pub(crate) item: usize,
    pub(crate) count: i32,
    /// Помечена «на склад» — за ней придёт свободный кот. При включённой
    /// автоуборке помечено всё, что лежит вне склада.
    pub(crate) marked: bool,
}

/// Сколько предмета у базы и в каком он состоянии (§12.53).
///
/// Три числа вместо одного, потому что тратить можно не всё: платит **склад**
/// (§12.24), и из складского ещё вычитается забронированное под сделку
/// (§12.50). Считает это ядро, а не панель: правило «чем можно платить» второй
/// раз в JS однажды разойдётся с `plan_spend`, и игрок увидит кнопку, которую
/// ядро отклонит (§12.26).
#[derive(Serialize)]
pub(crate) struct StockSnap {
    /// Лежит на клетках с `capacity` — это и есть казна базы.
    pub(crate) stored: i32,
    /// Валяется на полу и едет в лапах: имущество, но ещё не казна. Ноль тут
    /// значит «всё убрано», и это первая причина убираться не из аккуратности.
    pub(crate) loose: i32,
    /// Из складского обещано покупателю: базе оно больше не принадлежит.
    pub(crate) booked: i32,
}
