//! Чем кот занят — то, что игрок читает в его карточке (§12.41).
//!
//! Разбирает задачи `Busy::of` — та же функция, что решает, застрял ли кот,
//! и тот же список, что в фильтрах раздатчиков. Поэтому тесты здесь не про
//! текст (он живёт в UI), а про две вещи, в которых панель может соврать:
//! **какая** из задач показана, когда их формально две, и **дошёл ли** кот до
//! своего дела или ещё идёт.
//!
//! Снос от стройки отличает уже снапшот (у `Busy` нет чертежа), поэтому здесь
//! он и не проверяется: `job_of` возвращает то же, что `Busy`.

use super::*;

/// Тайл, которым в этих тестах занимают кота стройкой: пол схемы — уже `0`,
/// и чертёж на нём отсекается как «уже построено».
const OTHER: i32 = 2;

/// Предмет-снаряжение: индекс палитры, у которого есть `force`.
const SUIT: usize = 1;

/// Отряд поимённо — состав выбирает игрок (§12.23).
fn squad(ids: &[&str]) -> Vec<String> {
    ids.iter().map(|s| s.to_string()).collect()
}

/// Свободному коту панель не придумывает занятия. Пустой ключ — это «без дела»,
/// и он обязан отличаться от любой задачи: игрок по нему ищет, кого занять.
#[test]
fn an_idle_cat_has_no_job() {
    let mut sim = sim_from(&["#####", "#a..#", "#####"]);

    sim.tick_n(5);
    assert_eq!(sim.job_of("a"), ("", false), "делать нечего и идти некуда");
}

/// «Идёт на площадку» и «строит» — одна задача и две картинки, и различает их
/// маршрут. Без этого панель говорила бы «строит» о коте, который только вышел.
#[test]
fn a_builder_walks_first_and_works_after() {
    let mut sim = sim_from(&["########", "#a.....#", "########"]);
    sim.add_blueprint(6, 1, OTHER);

    sim.tick_n(1);
    assert_eq!(sim.job_of("a"), ("build", true), "взял чертёж и пошёл");

    sim.tick_n(9);
    assert_eq!(sim.job_of("a"), ("build", false), "дошёл и работает");
}

/// Приказ игрока — тоже занятие: кот идёт не «без дела», а туда, куда велели.
/// Невыполнимый приказ занятием не считается — это `stuck`, и подписан он
/// отдельно (§12.6).
#[test]
fn an_ordered_cat_is_walking_not_idle() {
    let mut sim = sim_from(&["#####", "#a..#", "#####"]);
    sim.set_target("a", 3, 1);

    sim.tick_n(1);
    assert_eq!(sim.job_of("a"), ("order", true), "идёт по приказу");

    sim.tick_n(20);
    assert_eq!(sim.job_of("a"), ("", false), "дошёл и снова свободен");
}

/// Сон — та же пара «идёт / делает», что у стройки, и по той же причине: кот в
/// двух шагах от лежанки ещё не спит, а панель обязана это различать (§12.33).
#[test]
fn a_tired_cat_walks_to_the_bed_then_sleeps() {
    let mut sim = sim_from(&["########", "#a.....#", "########"]);
    sim.set_needs(100, 50, 1);
    sim.set_rest(1, 2);
    sim.force_tile(6, 1, 1);
    sim.set_energy("a", 40);

    sim.tick_n(1);
    assert_eq!(sim.job_of("a"), ("rest", true), "пошёл спать");

    sim.tick_n(9);
    assert_eq!(sim.job_of("a"), ("rest", false), "дошёл и спит");
}

/// Раненый и его медик — две разные строки, а не одна: «лежит» и «лечит»
/// одинаково объясняют, почему кот не строит, но означают противоположное
/// (§12.37). Медик в пути ещё не лечит — до пациента надо дойти.
#[test]
fn a_patient_lies_and_the_medic_treats() {
    let mut sim = sim_from(&["#########", "#a.....b#", "#########"]);
    sim.set_health_rules(1000, 600, 1);
    sim.set_health("a", 100);

    sim.tick_n(1);
    assert_eq!(sim.job_of("a"), ("heal", false), "ранен и лёг где стоял");
    assert_eq!(sim.job_of("b"), ("treat", true), "медик пошёл к нему");

    sim.tick_n(20);
    assert_eq!(sim.job_of("b"), ("treat", false), "дошёл и лечит");
}

/// Задачи друг друга исключают, но одна пара всё-таки совмещается: кот в отряде
/// уходит за комплектом (§12.34). Панель обязана показать то же, что решила
/// симуляция, — иначе игрок будет ждать у шлюза кота, который на самом деле
/// пошёл одеваться.
#[test]
fn equipping_wins_over_the_gathering_squad() {
    let mut sim = sim_from(&["########", "#a....b#", "########"]);
    sim.set_gate(1, true);
    sim.force_tile(6, 1, 1);
    sim.set_force(SUIT, 1);
    sim.set_loadout(&[SUIT]);
    sim.put_item(3, 1, SUIT, 1);
    let m = sim.set_mission(1, 100, &[(0, 1)]);
    assert!(sim.launch(m, squad(&["a"])));

    sim.tick_n(1);
    assert_eq!(sim.job_of("a"), ("equip", true), "сперва за комбинезоном");

    sim.tick_n(30);
    assert_eq!(sim.job_of("a"), ("away", false), "оделся, дошёл и ушёл");
}

/// Пленный — тоже «нет на базе», и `Busy` их не различает намеренно: `away`
/// здесь про место, а не про причину. Разводит их снапшот отдельным флагом,
/// потому что «ушёл» и «остался там» — разные решения игрока (§12.40).
#[test]
fn a_captive_is_away_like_the_squad() {
    let mut sim = sim_from(&["########", "#ab...c#", "########"]);
    sim.set_gate(1, true);
    sim.force_tile(6, 1, 1);
    let doomed = sim.set_risky_mission(2, 10, 100, 0, &[]);
    sim.set_rescue_mission(2, 10, 0);
    assert!(sim.launch(doomed, squad(&["a", "b"])));

    sim.tick_n(40);
    assert!(sim.is_captive("a"), "провал оставил первого по id");
    assert_eq!(sim.job_of("a"), ("away", false), "и его нет на базе");
    assert_eq!(sim.job_of("b"), ("", false), "а вернувшийся снова свободен");
}
