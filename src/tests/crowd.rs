//! Два кота в одной клетке: пройти сквозь можно, остаться — нет (§12.32).
//!
//! Проходимость считается по тайлам, и кот в неё не входит, поэтому правило
//! касается только **остановки** и разбирается после факта (`spread_units`) —
//! тем же приёмом, что выход из ямы и сдвиг кучи из пустоты.
//!
//! Симптомом была лежанка: занятость держит `Rest` спящего, и в тот тик, когда
//! кот просыпается, место снова считается свободным — второй уходил спать под
//! первого. Поэтому тесты идут парой: сама клетка и лежанка.

use super::*;

/// Отряд поимённо — состав выбирает игрок (§12.23).
fn squad(ids: &[&str]) -> Vec<String> {
    ids.iter().map(|s| s.to_string()).collect()
}

// --- клетка -----------------------------------------------------------------

/// Два приказа в одну точку: дойдут оба, но останется там один.
#[test]
fn two_cats_do_not_stay_in_one_cell() {
    let mut sim = sim_from(&["#####", "#ab.#", "#...#", "#####"]);
    sim.set_target("a", 3, 1);
    sim.set_target("b", 3, 1);
    sim.tick_n(20);

    assert_ne!(sim.pos_of("a"), sim.pos_of("b"), "коты разошлись");
}

/// Сквозь идущего проходят: иначе коридор шириной в клетку встал бы намертво.
#[test]
fn cats_pass_through_each_other() {
    let mut sim = sim_from(&["######", "#ab..#", "######"]);
    sim.set_target("a", 4, 1);
    sim.tick_n(20);

    assert_eq!(sim.pos_of("a"), (4, 1), "прошёл сквозь соседа и дошёл");
    assert_eq!(sim.pos_of("b"), (2, 1), "а тот остался, где стоял");
}

/// Отойти некуда — стоят вместе. Это легальное состояние, как `stuck`, а не
/// ошибка: в тупике из одной клетки правило просто не применяется.
#[test]
fn with_nowhere_to_step_cats_stay_together() {
    // Тупик из трёх клеток: `c` в дальнем конце, за спиной у него `b`, и оба
    // соседа занятой клетки закрыты — стеной и другим котом.
    let mut sim = sim_from(&["#####", "#abc#", "#####"]);
    sim.set_target("a", 3, 1);
    sim.tick_n(10);

    assert_eq!(sim.pos_of("a"), (3, 1), "дошёл до дальней клетки");
    assert_eq!(sim.pos_of("c"), (3, 1), "и оба остались: отойти некуда");
}

/// Занятый делом остаётся, отходит свободный: работа весомее праздного стояния.
#[test]
fn a_working_cat_keeps_the_cell() {
    let mut sim = sim_from(&["#####", "#ab.#", "#...#", "#####"]);
    sim.set_rest(1, 1); // спит долго: проверяем занятую клетку, а не сон
    sim.force_tile(2, 1, 1); // лежанка под котом `b`
    sim.set_needs(100, 90, 1);
    sim.set_energy("b", 50); // `b` ложится спать здесь же
    sim.set_energy("a", 100);
    sim.set_target("a", 2, 1); // а `a` приходит на ту же клетку
    sim.tick_n(10);

    assert!(sim.is_resting("b"), "спящий на месте");
    assert_eq!(sim.pos_of("b"), (2, 1), "и клетку не уступил");
    assert_ne!(sim.pos_of("a"), (2, 1), "а свободный отошёл");
}

// --- лежанка ----------------------------------------------------------------

/// Тот самый баг: проснувшийся кот продолжал стоять на лежанке, место снова
/// считалось свободным, и второй ложился под него (§12.20, §12.32).
#[test]
fn a_woken_cat_does_not_block_the_bed() {
    let mut sim = sim_from(&["#####", "#ab.#", "#...#", "#####"]);
    sim.set_needs(100, 90, 1);
    sim.set_rest(1, 10);
    sim.force_tile(3, 1, 1); // одна лежанка на двоих
    sim.set_energy("a", 50);
    sim.set_energy("b", 50);

    // Первый высыпается и встаёт, второй занимает освободившееся место.
    sim.tick_n(40);
    assert_ne!(sim.pos_of("a"), sim.pos_of("b"), "на лежанке один кот");
}

/// Освободившаяся клетка не просто «не занята», а **пригодна**: проснувшийся кот
/// стоит на лежанке, но следующего уставшего это не останавливает — тот придёт,
/// ляжет, а стоящий отойдёт (§12.32).
///
/// Это и есть «закончивший работу освобождает ячейку»: отдельного шага в сторону
/// коту не нужно, место освобождается ровно тогда, когда на него кто-то
/// претендует.
#[test]
fn a_freed_bed_is_used_by_the_next_cat() {
    let mut sim = sim_from(&["#####", "#ab.#", "#...#", "#####"]);
    // Порог низкий: второй кот не должен захотеть спать раньше времени —
    // проверяем освобождение места, а не гонку двух уставших.
    sim.set_needs(100, 30, 10);
    sim.set_rest(1, 10);
    sim.force_tile(3, 1, 1); // одна лежанка
    sim.set_energy("a", 20); // спать идёт только `a`
    sim.set_energy("b", 100);

    sim.tick_n(16); // `a` дошёл, выспался и встал — стоя на лежанке
    assert_eq!(sim.pos_of("a"), (3, 1), "проснувшийся стоит на лежанке");
    assert!(!sim.is_resting("a"), "и уже не спит");

    sim.set_energy("b", 20); // теперь устал второй
    sim.tick_n(6); // дошёл и ещё спит: сон тут не мерим
    assert_eq!(sim.pos_of("b"), (3, 1), "он занял лежанку");
    assert!(sim.is_resting("b"), "и спит именно на ней");
    assert_ne!(sim.pos_of("a"), (3, 1), "а стоявший отошёл");
}

/// Лежанка по-прежнему достаётся ровно одному: `spread_units` разводит котов,
/// но не отменяет саму занятость (§12.20).
#[test]
fn the_bed_is_still_claimed_by_one() {
    let mut sim = sim_from(&["#####", "#ab.#", "#...#", "#####"]);
    sim.set_needs(100, 90, 1);
    sim.set_rest(1, 10);
    sim.force_tile(3, 1, 1);
    sim.set_energy("a", 50);
    sim.set_energy("b", 50);
    sim.tick_n(3);

    let spots = [sim.rest_spot_of("a"), sim.rest_spot_of("b")];
    let claimed = spots.iter().filter(|s| **s == Some((3, 1))).count();
    assert_eq!(claimed, 1, "лежанку застолбил ровно один");
}

// --- отряд ------------------------------------------------------------------

/// Отряд у шлюза — исключение: сбор по определению сводит котов в одну точку, и
/// `run_missions` ждёт, пока **все** встанут именно на неё (§12.22).
#[test]
fn a_squad_gathers_on_one_gate_cell() {
    let mut sim = sim_from(&["######", "#ab..#", "######"]);
    sim.set_gate(1, true);
    sim.force_tile(4, 1, 1);
    let m = sim.set_mission(2, 40, &[]);
    assert!(sim.launch(m, squad(&["a", "b"])));

    sim.tick_n(12);
    assert!(sim.is_away("a"), "отряд собрался на шлюзе и ушёл");
    assert!(sim.is_away("b"));
}

/// Куча предметов на клетке коту не мешает: она не сущность на пути, а
/// содержимое клетки (§12.21). Правило про остановку — только про котов.
#[test]
fn a_pile_does_not_block_a_cell() {
    let mut sim = sim_from(&["#####", "#a..#", "#####"]);
    sim.put_scrap(3, 1, 5);
    sim.set_auto_tidy(false); // иначе кот унесёт кучу, и проверять будет нечего
    sim.set_target("a", 3, 1);
    sim.tick_n(10);

    assert_eq!(sim.pos_of("a"), (3, 1), "кот стоит прямо на куче");
    assert_eq!(sim.scrap_at(3, 1), 5, "а куча — под ним");
}
