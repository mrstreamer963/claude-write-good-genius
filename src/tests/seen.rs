//! Знакомство с предметом (§12.131): что база видела своими глазами.
//!
//! Шкала отвечает ровно на один вопрос — есть ли у предмета строка в окне
//! «Склад» и в шапке. Проверяем два её свойства: она отмечается **тем, что
//! предмет побывал в мире**, и она **только растёт**.

use super::*;

/// Пустая палитра — пустая память: предмета, которого база не видела, для
/// склада не существует.
#[test]
fn an_item_is_unseen_until_it_touches_the_base() {
    let mut sim = sim_from(&["#####", "#a..#", "#####"]);
    sim.set_items(3);

    sim.tick_n(3);

    assert!(
        !sim.seen(1),
        "предмета в мире не было, а склад его уже показывает"
    );
    assert!(!sim.seen(2));
}

/// Куча на полу — уже встреча: считать надо мир, а не склад. Предмет, надетый
/// прямо с пола или съеденный по дороге, до склада не доходит никогда.
#[test]
fn a_pile_makes_an_item_seen() {
    let mut sim = sim_from(&["#####", "#a..#", "#####"]);
    sim.set_items(3);
    sim.put_item(2, 1, 1, 4);

    sim.tick_n(1);

    assert!(sim.seen(1), "куча пролежала тик, а база её не заметила");
    assert!(!sim.seen(2), "заодно отметился предмет, которого не было");
}

/// Главное свойство шкалы: «Ткань — 0» переживает то, что ткань кончилась.
/// Считай мы по `stored > 0` — строка пропала бы, и игрок решил бы, что
/// механика ему привиделась.
#[test]
fn a_seen_item_stays_seen_after_it_runs_out() {
    let mut sim = sim_from(&["#####", "#a..#", "#####"]);
    sim.set_items(2);
    sim.put_item(3, 1, 1, 2);
    sim.tick_n(1);
    assert!(sim.seen(1));

    sim.take_item(3, 1, 1);
    sim.tick_n(10);

    assert_eq!(sim.item_total(1), 0, "куча должна была исчезнуть");
    assert!(
        sim.seen(1),
        "предмет вывезли подчистую, и склад о нём забыл"
    );
}

/// Груз в лапах — тоже встреча: между подъёмом и сдачей предмет нигде не
/// лежит, и без этого запроса ходка делала бы его невидимым.
#[test]
fn an_item_in_paws_is_seen() {
    let mut sim = sim_from(&["#####", "#a..#", "#####"]);
    sim.set_items(2);
    let cat = sim.entity_of("a");
    sim.world
        .entity_mut(cat)
        .insert(Carrying { item: 1, count: 3 });

    sim.tick_n(1);

    assert!(sim.seen(1), "кот несёт вещь, а база её не видела");
}

/// Надетое — тоже встреча, и ради этого запроса `note_seen` смотрит на `Gear`:
/// иначе старый снимок отдал бы базу, которая ходит в комбинезонах и не знает,
/// что такое комбинезон.
#[test]
fn worn_gear_is_seen() {
    let mut sim = sim_from(&["#####", "#a..#", "#####"]);
    sim.set_items(2);
    let cat = sim.entity_of("a");
    sim.world.entity_mut(cat).insert(Gear(vec![1]));

    sim.tick_n(1);

    assert!(sim.seen(1), "кот одет в вещь, о которой база не знает");
}

/// Стартовый склад боевого рулсета виден **сразу**, без единого тика, — и
/// только он. Ткань и аптечку игрок должен встретить сам, иначе вся дуга
/// §12.131 ни о чём.
///
/// «Без единого тика» здесь не придирка: партия открывается на паузе, и первый
/// тик может не наступить ещё долго. Шапка всё это время говорила бы «ресурсы
/// не выбраны» про ресурсы, выбранные самим рулсетом.
#[test]
fn the_shipped_ruleset_starts_with_only_what_it_has() {
    let mut sim = Sim::new(include_str!("../../assets/rulesets/core.yaml")).expect("рулсет");
    // Мир по расписанию — шум для этой проверки: событие с подарком отметило бы
    // предмет, которого база ещё не добывала (§12.28).
    sim.without_timeline();

    let name = |id: &str| {
        sim.item_index(id)
            .unwrap_or_else(|| panic!("предмет `{id}`"))
    };
    let (scrap, part, ration) = (name("scrap"), name("part"), name("ration"));
    let (cloth, medkit) = (name("cloth"), name("medkit"));

    for (id, item) in [("scrap", scrap), ("part", part), ("ration", ration)] {
        assert!(
            sim.seen(item),
            "`{id}` лежит в стартовой застройке, а строки склада у него нет",
        );
    }
    for (id, item) in [("cloth", cloth), ("medkit", medkit)] {
        assert!(
            !sim.seen(item),
            "`{id}` в мире ещё не появлялся, а склад уже про него рассказал — \
             знакомство с предметом должно случаться в игре, а не в таблице",
        );
    }
}
