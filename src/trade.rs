//! Торговля с внешним миром: курс, покупка с доставкой и продажа (§12.44
//! concept.md).
//!
//! **Деньги — валюта только этого модуля.** Они входят единственным путём
//! (продажа) и уходят единственным (покупка); напечатать их нельзя. Отсюда всё
//! остальное: торговля не создаёт богатства, а меняет его состав — и всегда с
//! убытком, потому что купить дороже, чем продать. Поэтому она не обесценивает
//! ни вылазку, ни мастерскую, а решает другую задачу: превратить излишек в
//! нехватку, заплатив за это долей и временем. За найм, науку и производство
//! по-прежнему платит склад предметами (§12.24).
//!
//! Система здесь одна — `run_trade`: крутит таймеры обеих сделок, кладёт
//! купленное кучей в ячейку поста и платит за отгруженную продажу. Продажу
//! везут коты обычным подвозом, как материал на площадку (§12.16), но денег
//! она приносит не по мере сдачи, а разом по отгрузке (§12.68): контейнер
//! набирается, потом уезжает.
//!
//! **Пост — место, а не лицензия** (§12.68). Сделка занимает ячейку от клика до
//! вывоза, и предел «сделок столько, сколько постов» перестал быть невидимым
//! счётчиком: игрок видит забитый контейнер и знает, что делать. Ёмкости у
//! ячейки нет намеренно — иначе привезённое оплачивало бы найм и науку, не
//! доехав до склада (§12.24), и вывоз перестал бы быть механикой.

use bevy_ecs::prelude::*;

use crate::components::*;
use crate::hauling::spill;

/// Курс за штуку: сколько денег стоит купить или сколько дадут за продажу.
///
/// **Единственное место, где считается цена.** Её спрашивают двое — фасад в
/// момент заказа и снапшот для панели, — и развести их значит показать игроку
/// одно, а списать другое. Тот же довод и та же дисциплина, что у
/// `missions::outcome` (§12.23).
///
/// `None` — фракция этим предметом не торгует: расписание её прайса о нём
/// молчит, и отдельного флага для этого не нужно.
///
/// Фазу выбирает тик, а не бросок кубика (§11): расписание — чистая функция
/// времени, поэтому его видно вперёд. Иначе оптимальной игрой стало бы
/// ожидание пика, то есть секундомер вместо базы (§12.40).
pub(crate) fn quote(
    factions: &FactionRules,
    standing: &Standing,
    faction: usize,
    item: usize,
    tick: u64,
    buying: bool,
) -> Option<i32> {
    let rule = factions.0.get(faction)?;
    let phases = &rule.price_of(item)?.phases;
    if phases.is_empty() {
        return None;
    }
    let phase = match rule.period {
        0 => 0,
        p => (tick / p) as usize % phases.len(),
    };
    let base = phases[phase];
    // Репутация двигает курс в свою сторону, но не тратится (§12.43): у тех,
    // кто базе доверяет, покупать дешевле и продавать выгоднее.
    let favor = match rule.span {
        0 => 0,
        span => rule.favor * standing.value_of(faction) / span,
    };
    Some(match buying {
        true => base * (100 + rule.spread) / 100 * (100 - favor) / 100,
        false => base * (100 + favor) / 100,
    })
}

/// Ворота на строку прайса: пускают ли базу к этому товару (§12.150).
///
/// `None` — фракция этим предметом не торгует вовсе; это не отказ, а молчание
/// прайса, и вид такую строку не показывает нигде.
///
/// Считается **отдельно от `quote`** намеренно. `quote` отвечает «почём»,
/// ворота — «станут ли говорить»; сложи их в одно, и закрытая позиция поехала
/// бы в снимок ценой `0¤`, тогда как «почём будет» — это и есть ответ на «ради
/// чего расти». Выражение одно на фасад и на снимок, как сам `quote`
/// (инвариант 14).
///
/// Закрывают они **только покупку** — см. `PriceDef`.
pub(crate) fn offer_gates(
    factions: &FactionRules,
    fame: &Fame,
    standing: &Standing,
    faction: usize,
    item: usize,
) -> Option<OfferGates> {
    let line = factions.0.get(faction)?.price_of(item)?;
    if line.phases.is_empty() {
        return None;
    }
    Some(OfferGates {
        unlocked: fame.0 >= line.requires,
        welcome: standing.covers(&line.needs),
    })
}

/// Можно ли купить этот товар прямо сейчас — и если нет, то почему (§12.150).
///
/// Форма — `RaidGates` без третьего поля, и это не совпадение: вопросы те же
/// два, «дорос ли ты вообще» и «станет ли с тобой говорить эта сторона»
/// (§12.43). Причину кнопка обязана назвать словом (§12.53), поэтому наружу
/// едут оба флага врозь, а не их «и».
pub(crate) struct OfferGates {
    /// Известности хватает.
    pub(crate) unlocked: bool,
    /// Репутация у всех названных сторон не ниже пола.
    pub(crate) welcome: bool,
}

/// Сколько открытые продажи ещё **должны**: пары «предмет, штук», **без скидки
/// на лапы** (§12.50).
///
/// Сырая половина брони и вход для `booked`. Спрашивают её те, кто считает
/// добро базы **вместе с лапами**: ворота заявки на продажу и порог
/// автопроизводства (§12.65). Для них носильщик — это добро, которое пока на
/// базе, но базе уже не принадлежит.
pub(crate) fn owed<'a>(deals: impl Iterator<Item = &'a Deal>) -> Vec<(usize, i32)> {
    let mut out: Vec<(usize, i32)> = Vec::new();
    for deal in deals {
        if deal.buying {
            continue;
        }
        let left = deal.count - deal.delivered;
        if left <= 0 {
            continue;
        }
        match out.iter_mut().find(|(item, _)| *item == deal.item) {
            Some((_, n)) => *n += left,
            None => out.push((deal.item, left)),
        }
    }
    out
}

/// Что и сколько **забронировано под открытую продажу** (§12.50): пары
/// «предмет, штук». Сделка на POC одна, поэтому пара обычно ровно одна.
///
/// Продать можно только то, что на базе есть, — и с момента заявки товаром
/// распоряжается уже сделка, а не база: слот торговли один и не отменяется,
/// поэтому лом, съеденный стройкой, превратил бы продажу в вечно открытую и
/// убил бы торговлю целиком. Бронь нигде не хранится: она считается по самой
/// сделке, тем же приёмом, что обещания носильщиков (§12.48).
///
/// Из брони вычитается то, что уже **в лапах**: эти штуки из куч взяты, и
/// считать их дважды значило бы запирать базе лишнее.
///
/// **Отсюда граница применимости, и она узкая.** Скидка на лапы верна ровно для
/// тех, кто берёт **из куч**: подвоз, плата складом, еда, снаряжение. Кто
/// считает добро базы вместе с лапами — ворота заявки на продажу и порог
/// автопроизводства — обязан брать `owed`, иначе носильщик засчитывается дважды:
/// раз как «есть на базе», раз как «уже не обещано».
pub(crate) fn booked<'a>(
    deals: impl Iterator<Item = &'a Deal>,
    in_paws: impl Iterator<Item = (&'a Haul, &'a Carrying)>,
) -> Vec<(usize, i32)> {
    let mut out = owed(deals);
    if out.is_empty() {
        return out;
    }
    for (haul, load) in in_paws {
        if !matches!(haul.to, HaulTo::Sale(_)) {
            continue;
        }
        if let Some(slot) = out.iter_mut().find(|(item, _)| *item == load.item) {
            slot.1 -= load.count;
        }
    }
    out.retain(|&(_, n)| n > 0);
    out
}

/// Сколько предмета база вправе потратить: всё, что лежит в кучах, **минус
/// забронированное под продажу** (§12.50).
///
/// Спрашивают это все, кто снимает предметы с базы по воле игрока: подвоз на
/// площадку, плата складом (найм, наука, заказ, аптечка), снаряжение и еда.
/// Забыть спросить — значит вернуть ту самую вечно открытую сделку, ради
/// которой бронь и заводилась.
pub(crate) fn free_to_spend<'a>(
    piles: impl Iterator<Item = &'a Stack>,
    deals: impl Iterator<Item = &'a Deal>,
    in_paws: impl Iterator<Item = (&'a Haul, &'a Carrying)>,
    item: usize,
) -> i32 {
    let on_floor: i32 = piles.filter(|s| s.item == item).map(|s| s.count).sum();
    let reserved = booked(deals, in_paws)
        .iter()
        .find(|&&(i, _)| i == item)
        .map_or(0, |&(_, n)| n);
    on_floor - reserved
}

/// Сколько тиков осталось до смены фазы; `None` — курс вообще не меняется.
///
/// Уходит в панель: «видно вперёд» — это не только сама цена, но и то, сколько
/// она продержится, иначе планировать всё равно нечем.
pub(crate) fn phase_left(rule: &FactionRule, tick: u64) -> Option<u64> {
    match rule.period {
        0 => None,
        p => Some(p - tick % p),
    }
}

/// Крутит таймеры обеих сделок: выкладывает купленное в ячейку поста и
/// отгружает набитый контейнер продажи.
///
/// Стоит рядом с `run_missions` и по той же причине — **до `settle_stacks`**:
/// товар ложится кучей в ячейку, а та могла стать ямой, и съехать на пол он
/// обязан тем же тиком (§12.15).
///
/// **Здесь же начисляются деньги за продажу** (§12.68) — разом и по истечении
/// таймера. До §12.68 их капал `work_hauls` поштучно по мере сдачи; переезд не
/// заводит второго счёта, а убирает его: теперь обе сделки платят в одном
/// месте, том же, где списывается покупка. Вместе с деньгами сюда переехал и
/// журнал `Earned` (§12.58) — он пишется одной строкой рядом с самим событием.
///
/// **Асимметрия ячейки принципиальна** (§12.68): продажа освобождает её сама
/// (содержимого в мире нет — оно продано и ждёт отгрузки), покупка — только
/// после вывоза (содержимое в мире есть, но лежит не на складе, и увозит его
/// обычная уборка).
pub(crate) fn run_trade(
    mut commands: Commands,
    factions: Res<FactionRules>,
    mut money: ResMut<Money>,
    mut earned: ResMut<Earned>,
    mut deals: Query<(Entity, &mut Deal)>,
    mut stacks: Query<(Entity, &Position, &mut Stack)>,
) {
    for (deal_e, mut deal) in &mut deals {
        // Срок поставки — свойство фракции, и он один на обе стороны сделки:
        // возить одинаково далеко и туда, и обратно. Читается живьём, а не
        // фиксируется в сделке, потому что это правило, а не курс: правила из
        // рулсета за партию не меняются, а курс — меняется, и потому лежит в
        // самой сделке (§12.44).
        let lead = factions.0.get(deal.faction).map_or(0, |f| f.lead).max(1);

        if !deal.buying {
            // Контейнер ещё набивают — таймер не идёт вовсе (§12.68). Отсюда и
            // то, что состояния «срок вышел, а донесли половину» не существует.
            if deal.delivered < deal.count {
                continue;
            }
            // Набит целиком — отгрузка пошла. Ноль здесь однозначен: после
            // отсчёта сделка закрывается тем же шагом, и второй раз таймер с
            // нуля не заводится.
            if deal.left == 0 {
                deal.left = lead;
                continue;
            }
            deal.left -= 1;
            if deal.left > 0 {
                continue;
            }
            // Товар уехал, деньги пришли — **разом и по договорному курсу**.
            let total = deal.unit * deal.count;
            money.0 += total;
            // `Money` для цели «заработать продажей» не годится: он расходуем,
            // и заработавший сотню да потративший её игрок никогда бы цели не
            // закрыл (§12.58).
            earned.0 += total;
            commands.entity(deal_e).despawn();
            continue;
        }

        if deal.left > 0 {
            deal.left -= 1;
        }
        if deal.left > 0 {
            continue;
        }
        // Товар приходит **в ячейку поста**, а не на склад и не к шлюзу
        // (§12.68). Ёмкости у ячейки нет, поэтому платить им нельзя, а уборка
        // пометит кучу и увезёт её на склад сама.
        spill(&mut commands, &mut stacks, deal.cell, deal.item, deal.count);
        commands.entity(deal_e).despawn();
    }
}
