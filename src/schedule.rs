fn advance_time(mut time: ResMut<SimTime>) {
    time.tick += 1;
}

/// Цепочка систем одного тика. Вынесена отдельно, чтобы тесты гоняли ровно тот
/// же порядок, что и боевая симуляция.
///
/// Десять раздатчиков берут котов из одного пула свободных, поэтому их порядок —
/// это и есть приоритет работ (§12.15, §12.16, §12.20, §12.26, §12.30, §12.36,
/// §12.37):
///   1. `assign_heal` — ранение. Раньше всех, потому что решает не «чем кот
///      займётся», а «может ли он вообще»: выбывший обязан выпасть из пула до
///      того, как пул начнут разбирать (§12.37).
///   2. `assign_eat` — еда. Даже раньше отдыха: ходка за пайком короткая, а сон
///      длится сотни тиков, и уснувший голодным просыпается голодным же —
///      только позже и потратив вдвое больше бодрости по дороге (§12.36).
///   3. `assign_rest` — отдых. Иначе уставшего кота тут же уводит работа.
///   4. `assign_treat` — лечение. Первая из работ **над кем-то**, и раньше
///      остальных: пациент уже лежит, и каждый тик без медика — это котовремя,
///      которого база лишилась, тогда как чертёж просто ждёт (§12.37).
///   5. `assign_equip` — экипировка. До всех работ по базе: работа есть всегда,
///      и одетым отряд не уходил бы никогда (§12.34). Ходка короткая и разовая.
///   6. `assign_hauls` — подвоз на площадки. Иначе бригада разбирает уже
///      обеспеченные чертежи, а за ломом для остальных никто не идёт, и база
///      встаёт тем вернее, чем больше на ней работы.
///   7. `assign_research` — наука. Раньше стройки: за тему уже заплачено
///      образцами, а чертёж на базе есть почти всегда, и наука не двинулась бы
///      никогда. Это же и есть специализация (§12.17): учёный не строит.
///   8. `assign_craft` — производство. Там же и по той же причине: заказ игрок
///      разметил явно и поштучно, а чертежей на базе всегда больше (§12.30).
///   9. `assign_jobs` — стройка и снос.
///  10. `assign_tidy` — уборка пола. Последняя: подбирать мусор, пока стоит
///      настоящая работа, — это ровно то, чего игрок не ждёт.
///
/// Вылазки и учёба в этот порядок не входят: отряд назначает игрок в момент
/// заявки (§12.23), ученика — в момент команды (§12.18), и раздавать там нечего.
/// `gather_squad` и `study` только держат выбранных котов идущими к месту,
/// поэтому стоят рядом с раздатчиками, но пула не трогают.
///
/// `assign_equip` стоит **перед** `gather_squad` и единственный из раздатчиков
/// берёт кота даже на маршруте, если тот в отряде: сбор ещё не закончен, а
/// уходить голым, когда на складе лежит комбинезон, — это сила отряда,
/// зависящая от того, успел ли склад пополниться до нажатия кнопки (§12.34).
/// `gather_squad` его подождёт — у него `Without<Equipping>`.
///
/// `run_missions` — после `move_units`: кот, шагнувший на шлюз в этом тике,
/// засчитывается в отряд сразу. И до `settle_stacks`: добыча ложится кучей на
/// шлюз, а он к возвращению отряда может оказаться ямой.
///
/// `run_timeline` — рядом с ним и по той же причине: мир тоже дотягивается до
/// базы через шлюз, и его груз должен успеть съехать из ямы тем же тиком.
///
/// `escape_voids` — под конец: если приказ или джоб уже дали маршрут, он и
/// выводит кота из ямы, отдельный шаг не нужен. `settle_stacks` после
/// `work_jobs`: обе системы разбирают последствия только что снесённого
/// тайла — кота в яме и кучу лома в ней же. `spread_units` — там же и по той же
/// причине: он разбирает после факта то, что запретом стоило бы дороже, —
/// двух котов, оставшихся в одной клетке (§12.32). Идёт после `escape_voids`,
/// потому что кот с только что выданным маршрутом уже не «стоит».
/// `clear_solids` — сразу за ним и по той же причине: он сгоняет котов с
/// заставленных клеток (§12.35), и «стоит» для него значит ровно то же самое.
///
/// `study` — после `move_units`, по той же причине, что и `run_missions`: кот,
/// шагнувший к парте в этом тике, тикает сразу, а не со следующего. `work_equip`
/// и `work_eat` там же и потому же: дошедший до кучи одевается и ест тем же
/// тиком, а «дошёл» значит «`move_units` уже снял пустой маршрут».
///
/// `heal` — рядом со `sleep` и по той же причине: и сон, и заживление считаются
/// за прожитый тик, а не за то, что кот в нём делал. С `tire` и `hunger` порядок
/// не значим: здоровье ни на одну из них не смотрит и само по себе не тикает
/// (§12.37).
///
/// `hunger` — рядом с `tire` и в конце: обе тратят своё за прожитый тик, а не
/// за то, что кот в нём делал. Порядок между ними значим ровно в одном месте —
/// `tire` смотрит на сытость (§12.36), поэтому голод, наступивший в этом тике,
/// начинает жечь бодрость со следующего, а не задним числом.
///
/// `train_skills` замыкает цепочку: он превращает в опыт маркеры `Worked`,
/// которые за тик оставили системы работы, — и потому должен идти после любой
/// из них, включая будущие (§12.17).
///
/// Цепочка разбита на три группы **только из-за предела арности** у кортежа
/// систем: порядок ровно тот же, что и одним списком, — сперва кто за что
/// берётся, потом что из этого выходит, потом последствия прожитого тика.
pub(crate) fn build_schedule() -> Schedule {
    let mut schedule = Schedule::default();
    // Кто чем занят: раздача работы и сбор тех, кого назначил игрок.
    let assign = (
        advance_time,
        collapse_exhausted,
        assign_heal,
        assign_eat,
        assign_rest,
        assign_treat,
        assign_equip,
        gather_squad,
        assign_hauls,
        assign_research,
        assign_craft,
        assign_jobs,
        mark_loose_scrap,
        assign_tidy,
    )
        .chain();
    // Что из этого вышло: шаги и сама работа.
    let act = (
        move_units,
        work_hauls,
        work_equip,
        work_eat,
        work_jobs,
        work_research,
        work_craft,
        study,
        run_missions,
        run_timeline,
    )
        .chain();
    // Последствия прожитого тика: кто где оказался, что с ним стало и чему он
    // за это научился.
    let settle = (
        retry_orders,
        escape_voids,
        spread_units,
        clear_solids,
        settle_stacks,
        sleep,
        heal,
        tire,
        hunger,
        train_skills,
    )
        .chain();
    schedule.add_systems((assign, act, settle).chain());
    schedule
}
