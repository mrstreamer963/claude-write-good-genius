//! Цепочка систем одного тика — карта всей симуляции.
//!
//! Новая система добавляется **только сюда**: тесты гоняют ровно эту функцию,
//! поэтому расписание, собранное где-то ещё, останется непокрытым.

use bevy_ecs::prelude::*;

use crate::components::SimTime;
use crate::gear::auto_equip;
use crate::hauling::{assign_hauls, assign_tidy, mark_loose_scrap, settle_stacks, work_hauls};
use crate::jobs::{assign_jobs, work_jobs};
use crate::missions::{gather_squad, run_missions};
use crate::movement::{escape_voids, move_units, retry_orders};
use crate::needs::{assign_rest, collapse_exhausted, sleep, tire};
use crate::research::{assign_research, work_research};
use crate::skills::{study, train_skills};
use crate::timeline::run_timeline;

fn advance_time(mut time: ResMut<SimTime>) {
    time.tick += 1;
}

/// Цепочка систем одного тика. Вынесена отдельно, чтобы тесты гоняли ровно тот
/// же порядок, что и боевая симуляция.
///
/// Пять раздатчиков берут котов из одного пула свободных, поэтому их порядок —
/// это и есть приоритет работ (§12.15, §12.16, §12.20, §12.26):
///   1. `assign_rest` — отдых. Иначе уставшего кота тут же уводит работа.
///   2. `assign_hauls` — подвоз на площадки. Иначе бригада разбирает уже
///      обеспеченные чертежи, а за ломом для остальных никто не идёт, и база
///      встаёт тем вернее, чем больше на ней работы.
///   3. `assign_research` — наука. Раньше стройки: за тему уже заплачено
///      образцами, а чертёж на базе есть почти всегда, и наука не двинулась бы
///      никогда. Это же и есть специализация (§12.17): учёный не строит.
///   4. `assign_jobs` — стройка и снос.
///   5. `assign_tidy` — уборка пола. Последняя: подбирать мусор, пока стоит
///      настоящая работа, — это ровно то, чего игрок не ждёт.
///
/// Вылазки и учёба в этот порядок не входят: отряд назначает игрок в момент
/// заявки (§12.23), ученика — в момент команды (§12.18), и раздавать там нечего.
/// `gather_squad` и `study` только держат выбранных котов идущими к месту,
/// поэтому стоят рядом с раздатчиками, но пула не трогают.
///
/// `auto_equip` не входит в него тем более: экипировка — **состояние кота, а не
/// задача** (§12.29), она никого не занимает и ни у кого ничего не отнимает.
/// Стоит первой, чтобы новичок с найма и вернувшийся отряд успели одеться до
/// того, как их посчитают: сила отряда считается на возвращении, и надетое
/// входит в неё наравне с навыком.
///
/// `run_missions` — после `move_units`: кот, шагнувший на шлюз в этом тике,
/// засчитывается в отряд сразу. И до `settle_stacks`: добыча ложится кучей на
/// шлюз, а он к возвращению отряда может оказаться ямой.
///
/// `run_timeline` — рядом с ним и по той же причине: мир тоже дотягивается до
/// базы через шлюз, и его груз должен успеть съехать из ямы тем же тиком.
///
/// `escape_voids` — предпоследним: если приказ или джоб уже дали маршрут, он и
/// выводит кота из ямы, отдельный шаг не нужен. `settle_stacks` после
/// `work_jobs`: обе системы разбирают последствия только что снесённого
/// тайла — кота в яме и кучу лома в ней же.
///
/// `study` — после `move_units`, по той же причине, что и `run_missions`: кот,
/// шагнувший к парте в этом тике, тикает сразу, а не со следующего.
///
/// `train_skills` замыкает цепочку: он превращает в опыт маркеры `Worked`,
/// которые за тик оставили системы работы, — и потому должен идти после любой
/// из них, включая будущие (§12.17).
///
/// Цепочка разбита на две группы **только из-за предела арности** у кортежа
/// систем: порядок ровно тот же, что и одним списком, — сперва кто за что
/// берётся, потом что из этого выходит.
pub(crate) fn build_schedule() -> Schedule {
    let mut schedule = Schedule::default();
    // Кто чем занят: раздача работы и сбор тех, кого назначил игрок.
    let assign = (
        advance_time,
        auto_equip,
        collapse_exhausted,
        assign_rest,
        gather_squad,
        assign_hauls,
        assign_research,
        assign_jobs,
        mark_loose_scrap,
        assign_tidy,
    )
        .chain();
    // Что из этого вышло: шаги, работа, последствия и опыт.
    let act = (
        move_units,
        work_hauls,
        work_jobs,
        work_research,
        study,
        run_missions,
        run_timeline,
        retry_orders,
        escape_voids,
        settle_stacks,
        sleep,
        tire,
        train_skills,
    )
        .chain();
    schedule.add_systems((assign, act).chain());
    schedule
}
