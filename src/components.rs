//! Компоненты ECS и ресурсы мира.
//!
//! Данные без поведения: логика живёт в системах (`schedule`, `jobs`,
//! `movement`, `hauling`). Новая фича = новые компоненты здесь + отдельная
//! система там.

use bevy_ecs::prelude::*;
use serde::Serialize;
use std::collections::VecDeque;

#[derive(Component)]
pub(crate) struct Position {
    pub(crate) x: i32,
    pub(crate) y: i32,
}

#[derive(Component)]
pub(crate) struct Renderable {
    pub(crate) sprite: String,
}

#[derive(Component)]
pub(crate) struct UnitId(pub(crate) String);

/// Оставшийся маршрут. Хранится «развёрнуто»: следующий шаг — последний элемент
/// (`pop()` = следующая клетка), первый элемент — конечная цель.
#[derive(Component)]
pub(crate) struct Path {
    pub(crate) steps: Vec<(i32, i32)>,
}

/// Шаг, который кот делает прямо сейчас: «иду из своей клетки в соседнюю»
/// (§12.140).
///
/// **Кот числится в клетке, пока не дошёл.** `Position` переставляется не в
/// начале шага, а в момент прибытия, — поэтому между A и B у мира есть
/// промежуточное состояние, и вид рисует его честно, а не догадывается по
/// прошлому снимку. До §12.140 здесь стоял обратный отсчёт до следующего шага
/// (`MoveCooldown`), а позиция флипалась сразу: кот числился там, куда только
/// шёл, и нарисовать дорогу было нечем.
///
/// `left` идёт от `span` к нулю; ноль — это прибытие, и в тот же тик кот
/// трогается дальше (иначе между клетками появился бы лишний тик стояния).
/// Завал под лапами (§12.35) сидит в `span`: он не пауза после шага, а цена
/// входа в клетку.
#[derive(Component)]
pub(crate) struct Stride {
    /// Клетка, в которую кот идёт. Всегда 4-сосед его `Position`.
    pub(crate) to: (i32, i32),
    /// Сколько тиков осталось до прибытия.
    pub(crate) left: u8,
    /// Сколько тиков занимает шаг целиком — знаменатель прогресса для вида.
    pub(crate) span: u8,
}

/// Кот назначен на джоб постройки (ссылка на сущность-чертёж).
#[derive(Component)]
pub(crate) struct Assignment(pub(crate) Entity);

/// Приказ игрока «иди туда». Хранится, даже если путь сейчас не найден:
/// `retry_orders` перепроложит маршрут, как только карта изменится —
/// например, после постройки коридора.
#[derive(Component)]
pub(crate) struct Order {
    pub(crate) x: i32,
    pub(crate) y: i32,
    /// Версия карты, на которой попытка проложить маршрут **провалилась**.
    /// Проходимость зависит только от тайлов (коты друг друга не блокируют),
    /// поэтому повтор на неизменившейся карте заведомо даст тот же результат —
    /// и пропускается, чтобы не гонять BFS каждый тик.
    ///
    /// `None` — не пробовали или последняя попытка удалась. Разница
    /// существенная: маршрут теряется не только от непроходимости, но и от сна,
    /// раны и вылазки (`release_work`, `release_task`), а такому коту повтор
    /// нужен **сразу**, а не после ближайшей стройки. Отметка «пробовали» без
    /// этого различия держала кота с выполнимым приказом в `stuck` навсегда.
    pub(crate) tried_version: Option<u64>,
}

/// Чертёж — запланированная постройка тайла.
#[derive(Component)]
pub(crate) struct Blueprint {
    pub(crate) x: i32,
    pub(crate) y: i32,
    pub(crate) tile: i16,
    pub(crate) progress: i32,
    pub(crate) assignee: Option<Entity>,
    /// Что уже завезли на площадку: `(предмет, сколько)`. Пока набор не покрыл
    /// цену тайла, чертёж строителю не раздаётся — сперва носильщик (§12.15).
    ///
    /// Носильщика здесь нет намеренно (§12.48): сколько котов уже везут сюда лом,
    /// видно по ним самим — по их `Haul`, — и второе место, где это же записано,
    /// пришлось бы чистить в пяти местах, откуда задачу отбирают.
    pub(crate) delivered: Vec<(usize, i32)>,
}

/// Объект-штамп, стоящий (или строящийся) на карте (§12.160).
///
/// Сущность нужна ровно для двух вещей: **сносить целиком** и **считать
/// слотами**. Клетки при этом остаются обычными тайлами, и ни `walkable`, ни
/// зонирование, ни правило доступа о штампе не знают — поэтому инварианты 1 и 3
/// эта механика не трогает вовсе.
///
/// Чертежей у штампа **много, по одному на клетку** (§12.160): так
/// переиспользуются `assign_jobs`, `work_jobs`, `build_spot`, подвоз
/// `HaulTo::Site` и волна сноса. Атомарность нужна только на разметке — либо
/// весь штамп прошёл `may_build`, либо не поставлено ничего.
#[derive(Component)]
pub(crate) struct Structure {
    /// Индекс записи в `structures:` рулсета.
    pub(crate) def: usize,
    /// Левый верхний угол занятого прямоугольника **после поворота**.
    pub(crate) anchor: (i32, i32),
    /// Сколько четвертей оборота по часовой стрелке (0..3).
    pub(crate) rot: u8,
}

/// Куча предметов на клетке пола. Тип живёт в самой куче, поэтому на одной
/// клетке спокойно лежат разные (§12.21); сливаются только одинаковые.
#[derive(Component)]
pub(crate) struct Stack {
    pub(crate) item: usize,
    pub(crate) count: i32,
}

/// Груз в лапах: **один тип за ходку** (§12.21) — иначе лапы превращаются в
/// инвентарь, а раздатчик в планировщик маршрутов. Груз сам не падает: кот
/// держит его, пока не донесёт, и потому первым берётся за следующую доставку.
#[derive(Component)]
pub(crate) struct Carrying {
    pub(crate) item: usize,
    pub(crate) count: i32,
}

/// Пометка «эту кучу — на склад»; она же задача уборки. Без пометки куча просто
/// лежит. Вешает её автоуборка или рамка игрока (§12.16).
///
/// Носильщика пометка не держит (§12.48): кучу разбирают столько котов, на
/// сколько её хватает, а «сколько уже обещано идущим» считается по ним самим —
/// тем же приёмом, каким `assign_equip` не отправляет троих за одним
/// комбинезоном (§12.34).
#[derive(Component, Default)]
pub(crate) struct ToStore;

/// Куда кот несёт груз.
#[derive(Clone, Copy)]
pub(crate) enum HaulTo {
    /// Площадка: лом уходит в `Blueprint::delivered`.
    Site(Entity),
    /// Сделка на продажу: товар уходит с базы и превращается в деньги (§12.44).
    /// Снабжается ровно как площадка — тем же раздатчиком и теми же ходками, —
    /// но на месте не укладывается в тайл, а **исчезает из мира**. Кучей на
    /// шлюзе он при этом не становится ни на тик: иначе уборка увезла бы
    /// проданное обратно на склад.
    Sale(Entity),
    /// Мастерская: материал уходит в `Craft::delivered` (§12.102). Снабжается
    /// **ровно как площадка** — тем же раздатчиком и теми же ходками, — но
    /// берут для неё **только со склада** (§12.130), как для торгового поста:
    /// заказ есть трата запаса, и платят за него учтённым (§12.69). До §12.102
    /// материал списывался со склада мгновенно, и мастерская была единственным
    /// рабочим местом, к которому ничего не везли.
    Shop(Entity),
    /// Склад: конкретная клетка выбирается по дороге, а не при назначении —
    /// пока кот идёт, склад может заполниться. Внутри — куча-источник: на клетке
    /// лежат кучи разных типов (§12.21), а помечена была одна, и по ней же
    /// считается, сколько из кучи уже обещано идущим (§12.48). `None` у кота,
    /// которого отправили на склад уже с грузом.
    /// Лаборатория: образец уходит в `Research::delivered` (§12.133). Дословно
    /// `Shop` — тем же раздатчиком, теми же ходками и **только со склада**
    /// (§12.130): тема есть трата запаса, и платят за неё учтённым (§12.69).
    ///
    /// Четвёртый адресат, и на этом список закрыт не навсегда: новый обязан
    /// попасть **во все четыре исчерпывающих матча** — сюда, в `assign_hauls`
    /// (счёт обещанного, вместе с `assign_tidy`), в `work_hauls` и в
    /// `save.rs` (`HaulDto`).
    Lab(Entity),
    Store(Option<Entity>),
}

/// Задача переноса. Фаза отдельно не хранится — её задаёт наличие `Carrying`:
/// без груза кот идёт к куче, с грузом — к адресату.
#[derive(Component)]
pub(crate) struct Haul {
    pub(crate) to: HaulTo,
    /// За какой кучей и за каким типом кот пошёл (§12.49). `None` — кот уже с
    /// грузом либо идёт на склад: там куча-источник лежит в самом `HaulTo`.
    ///
    /// Это **наводка, а не бронь**: раздатчик по ней считает, сколько из кучи
    /// уже обещано идущим, — ровно как `assign_equip` по `Equipping::pile`
    /// (§12.34). Подъём наводку не читает: кот берёт то, что под ногами, и
    /// пропавшая куча остаётся промахом ценой ходки (§12.15).
    pub(crate) aim: Option<Aim>,
}

/// Куда кот идёт за грузом: куча и тип, который он собирается взять.
#[derive(Clone, Copy)]
pub(crate) struct Aim {
    pub(crate) pile: Entity,
    pub(crate) item: usize,
}

/// Сколько лома кот берёт за одну ходку. Компонента нет — предела нет: так
/// живут тесты механик, которым до объёма лап дела нет (§12.17).
#[derive(Component)]
pub(crate) struct Carry(pub(crate) i32);

/// Бодрость: тратится по очку за тик бодрствования, восстанавливается сном.
/// Компонента нет — кот не устаёт вовсе (§12.20).
#[derive(Component)]
pub(crate) struct Energy(pub(crate) i32);

/// Сытость: тратится по очку за тик — и во сне тоже, время идёт для всех.
/// Компонента нет — кот не голодает вовсе (§12.36).
#[derive(Component)]
pub(crate) struct Fed(pub(crate) i32);

/// Здоровье: **третья шкала, но не третий таймер** (§12.37). Сама не тикает ни
/// вверх, ни вниз: её роняет вылазка и возвращает лечение. Компонента нет — кот
/// не ранится вовсе, как не устаёт без `Energy`.
#[derive(Component)]
pub(crate) struct Health(pub(crate) i32);

/// Кот выбыл: лежит и заживает — **десятая задача общего слоя** (§12.37).
///
/// Устроена как `Rest`, и по той же причине: раненого забирает не игрок и не
/// раздатчик, а его собственное состояние. Фаза отдельно не хранится — с `Path`
/// кот идёт в лазарет, без него уже лежит.
///
/// Разница со сном одна и существенная: ранение **срывает начатое**, каким бы
/// оно ни было. Уставший доделывает (§12.20), раненый — нет: тем и отличается
/// «устал» от «не может».
#[derive(Component)]
pub(crate) struct Healing {
    /// Занятая койка: клетка, к которой кот идёт или на которой уже лежит.
    /// `None` — лёг там, где стоял: лазарета нет или до него не добраться.
    /// Занятость живёт здесь, а не отдельным claim, — ровно как у лежанки
    /// и парты (§12.20, §12.18): снимается вместе с задачей.
    pub(crate) spot: Option<(i32, i32)>,
    /// Медик, который сейчас над ним работает; `None` — заживает сам, медленно.
    /// Это тот же `assignee`, что у чертежа и темы: раненый — разметка работы,
    /// которую выставил не игрок, а мир (§12.37).
    pub(crate) medic: Option<Entity>,
    /// Сколько заживления за тик добавляет израсходованная на него аптечка
    /// (§12.47); ноль — аптечки не было. Она же и признак «уже потратили»:
    /// склад платит один раз за раненого, а не каждый тик.
    ///
    /// Перевязка держится до конца лечения, даже если медика увели: аптечку
    /// израсходовали, и отобрать прибавку значило бы отменить эту трату.
    pub(crate) kit: i32,
}

/// Кот лечит раненого (ссылка на пациента) — **одиннадцатая задача общего
/// слоя**. Как и десять остальных, обязана попасть во все фильтры «кот
/// свободен», иначе медика тихо уведёт с работы первый же чертёж.
#[derive(Component)]
pub(crate) struct Treating(pub(crate) Entity);

/// Кот отдыхает. Фаза отдельно не хранится, её задаёт наличие маршрута: с
/// `Path` кот идёт к лежанке, без — уже спит (так же устроен `Haul`, §12.15).
///
/// Это третья задача общего слоя, поэтому `Without<Rest>` обязан стоять всюду,
/// где кот считается свободным, — иначе спящего тихо перехватит работа.
#[derive(Component)]
pub(crate) struct Rest {
    /// Занятая лежанка: клетка, к которой кот идёт или на которой уже спит.
    /// `None` — кот свалился от истощения где стоял, места он не занимает
    /// (кроме случая, когда упал прямо на лежанку — это видно по позиции).
    ///
    /// Занятость лежанки живёт здесь, а не отдельным claim: она снимается
    /// вместе с задачей — просыпанием, приказом игрока, чем угодно (§12.20).
    pub(crate) spot: Option<(i32, i32)>,
}

/// Кот учится у парты: стоит и тикает, а на выходе не построенная клетка, а
/// опыт в навыке (§12.18). **Шестая задача общего слоя** — как и пять
/// остальных, обязана попасть во все фильтры «кот свободен».
#[derive(Component)]
pub(crate) struct Study {
    /// Домен, которому кот учится: он же тот, которому учит парта.
    pub(crate) skill: usize,
    /// Занятая парта: клетка, к которой кот идёт или у которой уже сидит.
    /// Занятость живёт здесь, а не отдельным claim, — ровно как у лежанки
    /// (§12.20): снимается вместе с задачей, чем бы её ни сняли.
    pub(crate) spot: (i32, i32),
}

/// Тема исследования в работе. Это **разметка работы**, как чертёж: игрок
/// выбирает, что изучать, а исполнителя берёт симуляция — но только из тех, у
/// кого хватает «Науки» (§12.16, §12.26).
#[derive(Component)]
pub(crate) struct Research {
    /// Индекс записи в `research:` рулсета.
    pub(crate) def: usize,
    /// Очки работы, как у чертежа: скорость даёт навык исполнителя (§12.17).
    pub(crate) progress: i32,
    pub(crate) assignee: Option<Entity>,
    /// Клетка лаборатории, в которой стоит тема, — **свойство темы, а не
    /// задачи** (§12.96, §12.132), поэтому `Option` тут нет и быть не должно.
    /// Дословно `Craft::cell`: занята от заявки до последнего очка работы.
    ///
    /// `release_work` и `release_task` её **не трогают**: они отбирают у темы
    /// исполнителя, а комната принадлежит самой теме, и снятая там она стоила
    /// бы теме уплаченных образцов.
    ///
    /// Она же адрес подвоза (§12.133): образец везут именно сюда.
    pub(crate) cell: (i32, i32),
    /// Что уже привезли на вскрытие: `(предмет, сколько)` — дословно
    /// `Craft::delivered` (§12.102, §12.133). Пока образец не завезён целиком,
    /// тема учёному не раздаётся: сперва носильщик (§12.15).
    ///
    /// Носильщика здесь нет намеренно, как и у заказа (§12.48): сколько котов
    /// уже везут сюда, видно по ним самим — по их `Haul`.
    ///
    /// У обычной темы список пуст всегда: она платит `cost` со склада в момент
    /// заявки, и везти ей нечего.
    pub(crate) delivered: Vec<(usize, i32)>,
}

/// Кот занят темой (ссылка на сущность-тему) — **седьмая задача общего слоя**.
#[derive(Component)]
pub(crate) struct Researching(pub(crate) Entity);

/// Заказ в мастерской. Это **разметка работы**, как чертёж и как тема, но
/// первая **повторяемая**: рецепт крутится, пока не сделано `left` штук
/// (§12.30). Очереди заказов нет — счётчик и есть весь ответ на «сколько раз».
///
/// С §12.96 заказ **живёт в ячейке станка**, дословно как сделка живёт в ячейке
/// торгового поста (§12.68): клетку выбирает ядро — первую свободную по обходу
/// карты, — и до конца работы она за заказом. Отсюда и то, что заказов на один
/// рецепт бывает несколько: три мастерских тянут пятнадцать деталей втрое
/// быстрее, а не по очереди.
#[derive(Component)]
pub(crate) struct Craft {
    /// Индекс записи в `recipes:` рулсета.
    pub(crate) def: usize,
    /// Сколько штук осталось сделать, включая ту, что в работе.
    pub(crate) left: i32,
    /// Очки работы **текущей** штуки: скорость даёт навык исполнителя (§12.17).
    pub(crate) progress: i32,
    /// Что уже завезли на станок: `(предмет, сколько)` — дословно
    /// `Blueprint::delivered` (§12.102). Пока набор не покрыл цену **одной**
    /// штуки, заказ мастеру не раздаётся: сперва носильщик (§12.15).
    ///
    /// Просит заказ материал **на всю партию сразу**, а мастер съедает цену
    /// штуки, доделав её. Иначе станок вставал бы после каждой штуки и ждал
    /// ходку — заказ на пять деталей означал бы пять пауз.
    ///
    /// Носильщика здесь нет намеренно, как и у площадки (§12.48): сколько котов
    /// уже везут сюда, видно по ним самим — по их `Haul`.
    ///
    /// До §12.102 это был `paid: bool`, а материал списывался со склада
    /// мгновенно. Отсюда и разница в отмене: списанное вернуть было нечем, а
    /// завезённое возвращается кучей на клетку станка (§12.31).
    pub(crate) delivered: Vec<(usize, i32)>,
    pub(crate) assignee: Option<Entity>,
    /// Клетка мастерской, в которой стоит заказ, — **свойство заказа, а не
    /// задачи** (§12.96), поэтому `Option` тут нет и быть не должно. Ровно
    /// `Deal::cell`: занята от заявки до последней штуки. `release_work` и
    /// `release_task` её **не трогают** — они отбирают задачу у кота, а станок
    /// принадлежит заказу; снятое там потеряло бы станок вместе с оплаченным
    /// материалом.
    pub(crate) cell: (i32, i32),
    /// Заказ завело правило-порог, а не игрок (§12.65). Признак нужен самому
    /// правилу — чтобы узнавать своё и не трогать чужое — и панели, которая
    /// вместо «Отменить» предлагает снять порог: отменённый заказ правило
    /// завело бы обратно тем же тиком, и кнопка читалась бы как поломка.
    pub(crate) auto: bool,
}

/// Кот занят заказом (ссылка на сущность-заказ) — **восьмая задача общего слоя**.
#[derive(Component)]
pub(crate) struct Crafting(pub(crate) Entity);

/// Сделка с внешним миром (§12.44) — **занимает ячейку торгового поста**
/// (§12.68), и ячеек столько, сколько постов построено.
///
/// Очереди нет намеренно: с ней задержка перестаёт быть ограничением («заказал
/// всё сразу, жду параллельно»), и решение «на что я трачу это окно» исчезает.
/// С §12.68 предел перестал быть невидимым счётчиком: ячейка занята сделкой от
/// клика до вывоза, и забитый контейнер игрок видит на карте.
///
/// **Курс зафиксирован в момент заказа** (`unit`), а не берётся заново при
/// поставке: цена обязана быть видна до клика, а показать одно и списать другое
/// запрещает та же дисциплина, что у прогноза вылазки (§12.23).
///
/// Отменить сделку нельзя, и команды для этого нет: деньги за покупку уже ушли,
/// как уходят образцы за тему и материал за штуку (§12.26, §12.30). Иначе это
/// бесплатный опцион — закупился на минимуме, передумал на максимуме.
#[derive(Component)]
pub(crate) struct Deal {
    pub(crate) faction: usize,
    pub(crate) item: usize,
    /// Сколько штук; у продажи — сколько ещё предстоит донести вместе с
    /// `delivered`.
    pub(crate) count: i32,
    /// Курс за штуку, зафиксированный при заказе.
    pub(crate) unit: i32,
    /// Покупаем (товар приедет) или продаём (товар унесут).
    pub(crate) buying: bool,
    /// Тиков до отгрузки. У покупки идёт с заказа, у продажи — **с момента,
    /// когда контейнер набит целиком** (§12.68): груз уехал, значит поехало, —
    /// ровно как таймер вылазки идёт с ухода отряда, а не с заявки (§12.22).
    /// Ноль у неполной продажи и значит «ещё набивают».
    pub(crate) left: i32,
    /// Сколько штук уже лежит в контейнере; только у продажи.
    ///
    /// Это **счётчик, а не кучи** (§12.68). Кучей содержимое быть не может
    /// дважды: уборка тут же повезла бы проданное обратно на склад (ячейка без
    /// ёмкости), а куча в мире — это то, что другие системы вправе трогать,
    /// тогда как весь смысл в том, что тронуть нельзя. Числом это выражено по
    /// построению. Будущему налёту числа хватает: «контейнер повредили» — это
    /// высыпать `delivered` кучей на ячейку (§12.31, §12.38).
    pub(crate) delivered: i32,
    /// Клетка торгового поста: сюда несут проданное и сюда же ложится
    /// купленное (§12.68).
    pub(crate) cell: (i32, i32),
}

/// Миссия — вылазка за пределы базы. Это **разметка работы**, как чертёж: игрок
/// говорит «идём туда», а исполнителей набирает симуляция (§12.16, §12.22).
#[derive(Component)]
pub(crate) struct Mission {
    /// Индекс записи в `missions:` рулсета.
    pub(crate) def: usize,
    /// Клетка гаража: там собирается отряд, оттуда он уходит и туда же
    /// возвращается с добычей. Она же **держит слот** вылазки (§12.152): сколько
    /// гаражей, столько отрядов разом, — до §12.152 это считала рация, а шлюз
    /// угадывался `pick_gate` по ближайшему ко всем. Оба поля были про место, и
    /// §12.152 схлопнула их в одно: дверь называет игрок.
    pub(crate) gate: (i32, i32),
    /// Тиков до возвращения. Тикает только у ушедшего отряда: сбор длится
    /// столько, сколько коты идут к шлюзу, и в срок миссии не входит.
    ///
    /// До ухода это ноль: срок зависит от того, сколько лап дошло, и считается
    /// в момент ухода (§12.70).
    pub(crate) left: i32,
    /// Весь замороженный срок вылазки — то, чем `left` был на уходе (§12.70).
    /// Нужен затем же, зачем раньше служил `ticks` у правила: связь копится за
    /// каждый тик в поле, а мерить её долю не от чего, если полного срока не
    /// помнить (§12.60).
    pub(crate) span: i32,
    /// Набежавшая связь: за каждый тик в поле сюда падает вклад **всех**
    /// дежурных базы (§12.60, §12.152). Мерить связь на возвращении нельзя —
    /// бонус повис бы на том, кто случайно оказался у рации в последний тик.
    ///
    /// С §12.152 связь общая: рация больше не приписана к вылазке, поэтому у
    /// всех идущих отрядов слагаемое за тик одно и то же. Поле остаётся у
    /// миссии, а не у мира, потому что делится оно на **её** срок.
    pub(crate) covered: i32,
}

/// Кот в отряде (ссылка на сущность-миссию) — **пятая задача общего слоя**.
/// Как и остальные четыре, обязана попасть во все фильтры «кот свободен»,
/// иначе раздатчик тихо уведёт бойца из отряда (инвариант занятости).
#[derive(Component)]
pub(crate) struct Squad(pub(crate) Entity);

/// Кот дежурит на узле связи — **двенадцатая задача общего слоя** (§12.60).
///
/// Раздаётся предпоследней, перед дремотой: на узел садится только тот, кому
/// ничего не досталось, — бонус к вылазке берётся из простоя, а не отнимается у
/// стройки. **Но раз сел — сидит**: появившийся чертёж дежурного не срывает,
/// как не срывает он и любую другую начатую работу (инвариант 7). Отпускают его
/// приказ игрока, голод, усталость и рана — всё то же, что и остальных.
///
/// Это первая задача **без естественного конца**: чертёж достраивается, куча
/// доносится, сон упирается в потолок, — а дежурство кончается возвращением
/// отряда. Поэтому раздатчик сажает кота, только пока вылазка этого узла в
/// поле, и он же снимает задачу, когда она кончилась.
#[derive(Component)]
pub(crate) struct OnDuty {
    /// Клетка узла: занятость держит сам `OnDuty`, как лежанку держит `Rest`.
    pub(crate) spot: (i32, i32),
}

/// Кот **приписан** к узлу связи волей игрока (§12.60).
///
/// Это конфигурация, а не задача: приписанный работает как все и садится на
/// узел, только когда там нужна связь. Разница с разовой посадкой существенна —
/// голод и сон снимают `OnDuty`, но не приписку, и раздатчик вернёт кота на узел
/// сам. Иначе повторилась бы дыра парты: игрок посадил, кот поел и больше не
/// вернулся, а пропажу связи видно только просевшим бонусом на возвращении.
///
/// Приписка **не занятость**: в фильтрах «кот свободен» её нет, и работать она
/// не мешает. Снимает её только игрок (`unpost`), и вместе с ней — дежурство.
#[derive(Component)]
pub(crate) struct Posted {
    pub(crate) spot: (i32, i32),
}

/// Кот **числится в отряде гаража** (§12.61, §12.152) — постоянный состав.
///
/// Это конфигурация той же природы, что `Posted`: не задача, работать не мешает,
/// снимается только игроком и **переживает вылазку** — вернувшийся отряд
/// остаётся отрядом. Уходящих в поле помечает `Squad` (ссылка на миссию), и
/// путать их нельзя: `Squad` живёт от заявки до возвращения, а `Enlisted` — до
/// тех пор, пока игрок не передумает.
///
/// Кот числится **не более чем в одном отряде**: приписка ко второму гаражу
/// снимает первую. Две двери, зовущие одного кота, — это вылазка, состав которой
/// зависит от того, какую кнопку нажали раньше.
///
/// До §12.152 состав жил на **рации**, а шлюз к нему подбирался автоматом. Отряд
/// принадлежит двери, а не радиоприёмнику: с §12.152 клетка здесь — гараж, и она
/// же держит слот вылазки.
#[derive(Component)]
pub(crate) struct Enlisted {
    /// Клетка гаража — та же форма ссылки на место, что у `Posted` и `Rest::spot`.
    pub(crate) spot: (i32, i32),
}

/// Кот **приписан к парте** волей игрока (§12.84): пока он не доучился, он
/// возвращается за неё сам.
///
/// Третья конфигурация после `Posted` и `Enlisted`, и заведена ровно по их
/// образцу. До §12.84 обучение было разовым назначением: `Study` — задача, и
/// её снимал первый же сон, голод или рана, а обратно кота никто не сажал.
/// Игрок видел это как «кликнул, а кот перестал учиться», причём без единого
/// сообщения — тот же провал, из-за которого §12.60 не стала сажать связиста
/// разово.
///
/// Приписка **не занятость**: в фильтрах «кот свободен» её нет, и работать она
/// не мешает — работу забирает выданный по ней `Study`. Снимают её двое:
/// игрок кнопкой (`unteach`) и сама учёба, дошедшая до потолка. Второе
/// обязательно: доучившийся кот с припиской ходил бы к парте до скончания
/// партии, ничего за ней не получая.
///
/// **Приказ «иди туда» её не снимает**, как не снимает `Posted`. День она так
/// работала, и это ломало саму механику: клетка парты — то самое место, куда
/// игрок кликает, отправляя кота учиться, а клик по клетке это приказ, — кот
/// доходил до парты и уходил, потому что тем же кликом учёбу и отменили.
#[derive(Component)]
pub(crate) struct Enrolled {
    /// Домен, которому кот учится. Клетки здесь нет **намеренно**: парта — это
    /// место работы, а не решение игрока (§12.16), и пересесть за соседнюю
    /// свободную кот волен сам. Тем приписка к парте и отличается от приписки
    /// к узлу связи, где узел выбран поимённо.
    pub(crate) skill: usize,
}

/// Кот ушёл с базы. Позиция остаётся последней (шлюз), но кота нет ни в
/// рендере, ни в системах базы: он не ходит, не устаёт и не выбирается из ям —
/// пока он вне базы, ими занимается авторасчёт миссии, а не симуляция (§12.22).
///
/// **«Нет на базе» — это `Away`, а не `Squad`** (§12.40). До плена одно влекло
/// другое, и раздатчикам хватало `Without<Squad>`; пленный — тот же `Away`, но
/// уже без отряда, и фильтр по отряду отдал бы его первому же чертежу.
#[derive(Component)]
pub(crate) struct Away;

/// Кот остался в плену: провал вылазки не смог унести его домой (§12.40).
///
/// Это **не задача** — кот ничего не делает и ничего не решает, — а место, где
/// он находится: `Away` без `Squad`. Отсюда и весь список того, что с ним не
/// происходит: не работает, не устаёт, не голодает, не лечится и приказам не
/// подчиняется. Вернуть его может только вылазка с `rescue`, и это единственный
/// способ: сам он не приходит ни через сколько тиков.
///
/// **Причину плена игра не называет** (§12.40). Кто именно остался — первый по
/// `id`, и это ровно детерминизм, а не объяснение: раны, навык и снаряжение на
/// выбор не влияют. Само время в плену не стоит коту ничего: там его не
/// калечат — но и не лечат, как и в поле (§12.22).
///
/// **Смерти в игре нет** (§12.37), и плен её не вводит: это та же цена, что у
/// ранения, — котовремя, только отнятое целиком и до тех пор, пока база не
/// сходит за ним сама.
#[derive(Component)]
pub(crate) struct Captive;

/// Перки — статичные теги из рулсета. В отличие от навыка, не растут: это
/// сложение кота, а не его мастерство (§12.17).
#[derive(Component, Default)]
pub(crate) struct Perks(pub(crate) Vec<String>);

/// Перк «Носильщик»: удваивает объём лап. Единственный перк POC.
pub(crate) const PERK_HAULER: &str = "hauler";

/// Кот идёт за вещью из шаблона — **восьмая задача общего слоя** (§12.34).
///
/// Как и семь остальных, обязана попасть во все фильтры «кот свободен»:
/// пропущенный `Without<Equipping>` не уронит ничего, а тихо развернёт кота на
/// полдороге к складу, и комплект он будет добирать вечно.
///
/// Куча-источник хранится сущностью, а не клеткой: клетку кот и так получает
/// маршрутом, а вот **та ли это куча**, проверяется только по сущности —
/// разошлись бы иначе «пришёл куда шёл» и «взял что хотел».
#[derive(Component)]
pub(crate) struct Equipping {
    /// Что надевает: индекс палитры `items:`.
    pub(crate) item: usize,
    /// Куча, из которой берёт. Могла исчезнуть, пока кот шёл, — это промах, а
    /// не ошибка (§12.15).
    pub(crate) pile: Entity,
}

/// Кот идёт к куче с едой — **девятая задача общего слоя** (§12.36).
///
/// Копия `Equipping` по устройству и по причине: удовлетворитель потребности —
/// это предмет, лежащий где-то на базе, а не услуга склада. Съедается штука
/// мгновенно по приходу, вся длительность задачи — дорога.
///
/// Как и восемь остальных, обязана попасть во все фильтры «кот свободен»:
/// пропущенный `Without<Eating>` не уронит ничего, а тихо развернёт кота на
/// полдороге к пайку — и голодать он будет при полном складе.
#[derive(Component)]
pub(crate) struct Eating {
    /// Что ест: индекс палитры `items:`.
    pub(crate) item: usize,
    /// Куча, из которой берёт. Могла исчезнуть, пока кот шёл, — это промах, а
    /// не ошибка (§12.15).
    pub(crate) pile: Entity,
}

/// Что на коте надето: индексы предметов палитры, в порядке шаблона (§12.29).
///
/// Не инвентарь: предмет надет либо нет, класть в него нечего (§12.21). Компонента
/// нет — кот не экипирован вовсе, и это нормальное состояние, а не недостача.
#[derive(Component)]
pub(crate) struct Gear(pub(crate) Vec<usize>);

/// Опыт кота по доменам работы; индекс — номер записи в `skills:` рулсета.
/// Уровень не хранится: он выводится из опыта по порогам (`SkillRules`), и
/// второе место, где его можно забыть обновить, не заводится.
#[derive(Component, Default)]
pub(crate) struct Skills {
    pub(crate) xp: Vec<i32>,
}

impl Skills {
    pub(crate) fn xp_of(&self, skill: usize) -> i32 {
        self.xp.get(skill).copied().unwrap_or(0)
    }

    pub(crate) fn add_xp(&mut self, skill: usize, amount: i32, cap: i32) {
        if self.xp.len() <= skill {
            self.xp.resize(skill + 1, 0);
        }
        self.xp[skill] = (self.xp[skill] + amount).min(cap);
    }
}

/// Врождённые параметры кота по индексу палитры `stats:` (§12.19, §12.42).
///
/// Не вторая растущая шкала: параметр **дан и не двигается**, а работает
/// пределом навыка — докуда кот вырастет в домене. Ни одна система его не
/// меняет, поэтому поле только читается; рост от работы сделал бы его вторым
/// навыком под другим именем.
///
/// Компонента нет — параметры кота нули, и в домене с `demands` он упрётся в
/// первый уровень. Это видно в панели («Ум 0»), а не молча: коты из
/// ASCII-схем живут в мире без палитры параметров, где `demands` пусты и
/// предела нет вовсе.
#[derive(Component, Default)]
pub(crate) struct Stats(pub(crate) Vec<i32>);

impl Stats {
    pub(crate) fn value_of(&self, stat: usize) -> i32 {
        self.0.get(stat).copied().unwrap_or(0)
    }

    pub(crate) fn set(&mut self, stat: usize, value: i32) {
        if self.0.len() <= stat {
            self.0.resize(stat + 1, 0);
        }
        self.0[stat] = value;
    }
}

/// «Кот работал в этом тике по такому-то домену». Ставит система работы, снимает
/// `train_skills`: правило роста живёт в одном месте и не копируется в каждую
/// новую работу (§12.17).
#[derive(Component)]
pub(crate) struct Worked(pub(crate) usize);

#[derive(Resource)]
pub(crate) struct SimTime {
    pub(crate) tick: u64,
}

/// Убирать ли лом с пола без приказа. Выключатель для случая, когда лом нарочно
/// оставлен у стройки (§12.16).
#[derive(Resource)]
pub(crate) struct AutoTidy(pub(crate) bool);

/// Бросает ли кот начатое, когда бодрость ушла ниже критического порога
/// (§12.33). Выключатель для случая, когда игрок сознательно гонит базу до
/// упора: коты доработают до нуля и свалятся, как до второго порога.
#[derive(Resource)]
pub(crate) struct AutoRest(pub(crate) bool);

/// Сколько чего держать на базе: по индексу рецепта — минимум штук того, что
/// этот рецепт даёт (§12.65). Ноль — правила нет, длина растёт под палитру.
///
/// Это **правило, а не заказ** (§12.64): игрок задаёт его один раз, а
/// `plan_craft` каждый тик приводит мир в соответствие — заводит заказ, когда
/// просело, и снимает свой, когда порога больше нет. Второй такой ресурс —
/// `Selling` (§12.87), и форма у него та же.
///
/// Порог висит на **рецепте**, а не на предмете: рецептов, дающих один и тот
/// же предмет, может быть два, и выбор между ними — решение игрока, а не
/// «первый по палитре».
#[derive(Resource, Default)]
pub(crate) struct Stocking(pub(crate) Vec<i32>);

impl Stocking {
    pub(crate) fn min_of(&self, def: usize) -> i32 {
        self.0.get(def).copied().unwrap_or(0)
    }

    pub(crate) fn set(&mut self, def: usize, min: i32) {
        if self.0.len() <= def {
            self.0.resize(def + 1, 0);
        }
        self.0[def] = min.max(0);
    }
}

/// Ворота автоматики: какая технология открывает какое правило игрока (§12.93).
/// Пустая строка — правило доступно с первого тика.
///
/// Это `*Rules`-ресурс, то есть разобранный рулсет: в снимок он не уходит
/// никогда (§12.45), а `Sim::new` пересобирает его заново.
///
/// **Проверяются эти ворота только в командах фасада**, а не в системах:
/// технологии только растут и только открывают (§12.18), забытой технологии не
/// бывает, — поэтому правило, поставленное законно, работать не перестанет, и
/// второй проверки в `plan_craft` / `run_auto_raids` / `run_auto_sales` не
/// нужно. Снятие правила ворота не проверяют вовсе: запертая отмена оставила бы
/// правило несбрасываемым.
#[derive(Resource, Default)]
pub(crate) struct AutoRules {
    pub(crate) sales: String,
    pub(crate) crafting: String,
    pub(crate) raids: String,
}

impl AutoRules {
    /// Открыто ли правило: ворот нет или технология изучена.
    fn opens(gate: &str, techs: &Techs) -> bool {
        gate.is_empty() || techs.knows(gate)
    }

    pub(crate) fn sales_open(&self, techs: &Techs) -> bool {
        Self::opens(&self.sales, techs)
    }

    pub(crate) fn crafting_open(&self, techs: &Techs) -> bool {
        Self::opens(&self.crafting, techs)
    }

    pub(crate) fn raids_open(&self, techs: &Techs) -> bool {
        Self::opens(&self.raids, techs)
    }
}

/// Куда девать излишек предмета: **продать названной стороне или разобрать**
/// (§12.115). Одно правило на предмет, адресат — его поле.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Surplus {
    /// Продать этой фракции (§12.87, §12.88).
    Sell(usize),
    /// Отдать в мастерскую на разбор (§12.114, §12.115).
    Salvage,
}

/// Что делать с излишком: тройки «предмет, куда, сколько держать» (§12.87,
/// §12.88, §12.115). Ноль — правила нет, как и у порога производства.
///
/// Зеркало `Stocking` с другого конца: тот держит запас **снизу** («меньше
/// пяти — доделать»), этот **сверху** («больше пятидесяти — продать»). Отсюда
/// и общая форма: ресурс-правило, которое игрок задаёт один раз, а фасад
/// повторяет каждым тиком (§12.64).
///
/// **Ключ — предмет, а адресат это поле правила** (§12.88, §12.115). Адресатов
/// с §12.115 двое — покупатель и мастерская, — и это одно правило с выбором, а
/// не два правила рядом: «продавать сверх 10» и «разбирать сверх 5» меряют
/// **один и тот же излишек одного склада**, и предмет сверх десяти
/// удовлетворяет обоим условиям разом. Кто его заберёт, решал бы порядок
/// вызовов в `Sim::tick` — детерминизм формально цел, читаемость нет.
/// Переключение адресата стирает прежний ровно так же, как смена покупателя
/// стирает прежнего покупателя: это переписанное решение, а не второе.
///
/// **С порогом производства (`Stocking`) правило не спорит и его не отменяет**:
/// тот **кладёт** на базу, этот **снимает** со склада — разные направления и
/// разные вопросы. Перекрыть полосы игрок может («держать 5, сбывать сверх 3»),
/// и это видимая беготня, а не двусмысленность: игра в неё не вмешивается.
///
/// Адресата
/// по-прежнему называет игрок: «продать тому, кто в этот тик даёт больше» ядру
/// вычислить нетрудно — курс чистая функция тика (§12.44), — и ровно поэтому
/// нельзя, иначе правило обыгрывало бы игрока на его же расписании, а развилка
/// §12.43 перестала бы значить что-либо. Но **правило на предмет только одно**:
/// на паре «фракция + предмет» их выходило по два на один лом, и излишек молча
/// доставался первому по палитре — интерфейс предлагал выбор, который сам же и
/// разрешал. «Продавать сверх пяти Полиции» и «сверх двадцати Синдикату» это не
/// два решения, а переписанное одно.
///
/// Список **отсортирован по предмету**: порядок доходит до заявок (два разных
/// предмета спорят за последнюю свободную ячейку поста), а `HashMap` сделал бы
/// его недетерминированным (§11).
#[derive(Resource, Default)]
pub(crate) struct Selling(pub(crate) Vec<(usize, Surplus, i32)>);

impl Selling {
    /// Правило по предмету: `(куда, сколько придержать)`; `None` — правила нет.
    ///
    /// Ядру наружу оно не нужно (снимок раскладывает список целиком, а фасад
    /// перебирает его), но раскладку тройки прячет именно этот метод — и тесты
    /// спрашивают правило через него, а не через `.0`.
    #[cfg_attr(not(test), allow(dead_code))]
    pub(crate) fn rule_of(&self, item: usize) -> Option<(Surplus, i32)> {
        self.0
            .iter()
            .find(|&&(i, ..)| i == item)
            .map(|&(_, dest, keep)| (dest, keep))
    }

    /// Поставить правило или снять его (`keep <= 0`). Прежнее правило предмета
    /// снимается целиком — **вместе с адресатом**: сменить сторону (или увести
    /// излишек из продажи в разбор) и есть переписать решение.
    pub(crate) fn set(&mut self, dest: Surplus, item: usize, keep: i32) {
        self.0.retain(|&(i, ..)| i != item);
        if keep > 0 {
            self.0.push((item, dest, keep));
            self.0.sort_unstable_by_key(|&(i, ..)| i);
        }
    }
}

/// Предметы, которые хоть раз побывали в мире базы (§12.131).
///
/// **Только растёт и только открывает** — та же шкала-ворота, что `Techs` и
/// известность (§12.24). Строка склада, умеющая пропасть, читается как баг:
/// «Ткань — 0» обязана остаться после того, как ткань кончилась, иначе игрок
/// решит, что механика ему привиделась.
///
/// Отвечает она **только** на «показывать ли строку запаса» — в шапке и в окне
/// «Склад». Там, где предмет назван ценой, требованием, добычей или
/// содержимым кучи, он показывается всегда: скрытая цена — это отказ без
/// причины (§12.53), а скрытая строка запаса — отсутствие ответа на вопрос,
/// которого игрок ещё не задавал.
///
/// В отличие от прочих шкал-ворот, у этой **есть система** (`seen::note_seen`):
/// «побывал в мире» — состояние мира каждого тика, а не выражение фасада, и
/// считает его цепочка, как `check_goals`. Довод `note_news`, живущего в
/// фасаде, тут не работает: тот читает ворота, которых в системе нет.
///
/// Длина — палитра предметов, индекс — номер записи в `items:`.
#[derive(Resource, Default)]
pub(crate) struct Seen(pub(crate) Vec<bool>);

impl Seen {
    /// Видел ли игрок этот предмет хоть раз.
    pub(crate) fn saw(&self, item: usize) -> bool {
        self.0.get(item).copied().unwrap_or(false)
    }

    /// Отметить встречу. Растёт, если палитра оказалась длиннее (снимок чужой
    /// сборки), — терять отметки молча дороже, чем держать лишний `push`.
    pub(crate) fn mark(&mut self, item: usize) {
        if self.0.len() <= item {
            self.0.resize(item + 1, false);
        }
        self.0[item] = true;
    }
}

/// Что игрок держит наверху списка в окне «Склад» (§12.100).
///
/// Закладка вида, но **состояние партии**, а не раскладка стола: держать её в
/// JS уже пробовали с тумблером «Убирать сам» — после загрузки зеркало врало
/// (§12.96). Поэтому она здесь и уходит в снимок.
///
/// Только предметы: избранное отвечает за **порядок строк**, а не за торговлю,
/// и стороны ему не нужно — в отличие от `Tickers`. Отсюда и то, что закрепить
/// можно предмет, которым не торгует никто: следить за запасом аптечек —
/// причина не хуже курса.
///
/// Список отсортирован по индексу предмета: порядок доходит до вида, а обход
/// ECS недетерминирован (§11).
#[derive(Resource, Default)]
pub(crate) struct Favorites(pub(crate) Vec<usize>);

impl Favorites {
    /// Ядру наружу не нужно (снимок отдаёт список целиком, а фасад пишет через
    /// `set`), но спрашивают закладку именно так — и тесты, и будущий читатель;
    /// та же оговорка, что у `Selling::rule_of`.
    #[cfg_attr(not(test), allow(dead_code))]
    pub(crate) fn has(&self, item: usize) -> bool {
        self.0.contains(&item)
    }

    /// Положить в избранное или вынуть (`on == false`).
    pub(crate) fn set(&mut self, item: usize, on: bool) {
        self.0.retain(|&i| i != item);
        if on {
            self.0.push(item);
            self.0.sort_unstable();
        }
    }
}

/// Что вынесено на главный экран лентой: предмет → сторона, у которой он
/// покупается и продаётся в один клик (§12.100).
///
/// Второй вопрос, а не второе имя первого: избранное отвечает «где эта строка
/// в окне», тикер — «видно ли её, не открывая окна, и с кем по ней торгуют».
/// Данные у них поэтому разные, и складывать их в один флаг нельзя.
///
/// **Ключ — предмет, тикер один**: форма дословно `Selling` (§12.88), и довод
/// тот же — два тикера на один предмет это переписанное одно решение, а не два.
/// **Сторона обязательна**, в отличие от избранного: у тикера есть кнопки
/// сделки, а сделке нужен адресат, и называет его игрок (§12.87).
///
/// Список отсортирован по предмету — по той же причине, что и `Selling`.
#[derive(Resource, Default)]
pub(crate) struct Tickers(pub(crate) Vec<(usize, usize)>);

impl Tickers {
    /// Сторона, с которой торгуют по этому тикеру; `None` — тикера нет.
    ///
    /// Как и `Favorites::has`, наружу не нужна: список едет в снимок целиком.
    #[cfg_attr(not(test), allow(dead_code))]
    pub(crate) fn side_of(&self, item: usize) -> Option<usize> {
        self.0
            .iter()
            .find(|&&(i, _)| i == item)
            .map(|&(_, faction)| faction)
    }

    /// Поставить тикер или снять его. Прежний снимается целиком — **вместе со
    /// стороной**: сменить сторону и есть переписать решение (§12.88).
    pub(crate) fn set(&mut self, item: usize, faction: usize, on: bool) {
        self.0.retain(|&(i, _)| i != item);
        if on {
            self.0.push((item, faction));
            self.0.sort_unstable_by_key(|&(i, _)| i);
        }
    }
}

/// Куда узел связи отправляет свой отряд сам: клетка рации и заказ (§12.67).
///
/// Это **правило, а не заявка**, ровно как порог у производства (§12.65):
/// игрок задаёт его один раз, а фасад каждый тик повторяет за него тот самый
/// клик — но только когда клик прошёл бы и у игрока. Ни новой заявки, ни
/// второго способа уйти в поле: `launch_node` остаётся единственным.
///
/// Правило живёт на **клетке**, а не на отряде: отряд и так приписан к узлу
/// (§12.61), а узел — это слот вылазки (§12.59). Ключ — пара координат,
/// поэтому список хранится плоским и **отсортированным по клетке**: порядок
/// доходит до заявок, а `HashMap` сделал бы его недетерминированным (§11).
///
/// **У правила два состояния, а не два значения** (§12.77): четвёртое поле —
/// «работает ли оно прямо сейчас». Пауза нужна ровно там, где рутину прерывают
/// на разовое дело: отряд привёз гору лома, её надо разгрести, а через сотню
/// тиков вернуться к тому же кругу. Снятое правило пришлось бы искать заново
/// среди заказов — то есть принимать решение второй раз, хотя игрок его не
/// менял. Поэтому и явный приказ, и отзыв отряда правило **усыпляют**, а не
/// стирают: решение живёт, пока игрок сам его не отменил.
#[derive(Resource, Default)]
pub(crate) struct AutoRaids(pub(crate) Vec<(i32, i32, usize, bool)>);

impl AutoRaids {
    /// Заказ, на который этот узел ходит сам, — **и активный, и усыплённый**:
    /// панель обязана называть оба, иначе неактивное правило невидимо и снять
    /// (или разбудить) его нечем.
    pub(crate) fn of(&self, x: i32, y: i32) -> Option<usize> {
        self.0
            .iter()
            .find(|&&(ax, ay, ..)| (ax, ay) == (x, y))
            .map(|&(_, _, def, _)| def)
    }

    /// Работает ли правило прямо сейчас. Только по этому признаку отряд уходит
    /// сам: у усыплённого заказ помнится, но заявок оно не заводит.
    pub(crate) fn is_on(&self, x: i32, y: i32) -> bool {
        self.0
            .iter()
            .any(|&(ax, ay, _, on)| (ax, ay) == (x, y) && on)
    }

    /// Поставить правило. Второго на ту же клетку не бывает: узел ходит на один
    /// заказ, а не по списку, — очередь заказов это уже план, а не повторение
    /// клика (§12.67). Поставленное правило всегда активно: игрок только что
    /// сказал «ходи», а не «помни».
    pub(crate) fn set(&mut self, x: i32, y: i32, def: usize) {
        self.clear(x, y);
        self.0.push((x, y, def, true));
        // Порядок — row-major по карте, тот же, что у `gate_cells`: с ним
        // совпадают и номера отрядов в панели, и очередь заявок.
        self.0.sort_by_key(|&(x, y, ..)| (y, x));
    }

    /// Перевести правило узла в «Неактивно» и обратно (§12.77). Правила нет —
    /// и делать нечего: будить нечего, а заводить правило умеет только `set`.
    pub(crate) fn set_on(&mut self, x: i32, y: i32, on: bool) -> bool {
        match self
            .0
            .iter_mut()
            .find(|&&mut (ax, ay, ..)| (ax, ay) == (x, y))
        {
            Some(rule) => {
                rule.3 = on;
                true
            }
            None => false,
        }
    }

    pub(crate) fn clear(&mut self, x: i32, y: i32) {
        self.0.retain(|&(ax, ay, ..)| (ax, ay) != (x, y));
    }
}

/// Журнал команд игрока — отладочный трейс «как игрок дошёл до такого
/// состояния» (§12.45).
///
/// Источником правды он **не является**: партию восстанавливает снимок, а
/// трейс только объясняет, что игрок делал по дороге. Едет внутри файла
/// сохранения, чтобы объяснение переживало перезагрузку.
///
/// Пишется он в единственном месте — в фасаде (`save::note`), потому что
/// команда игрока и есть вызов фасада; система для него не заводится.
/// Это единственное в мире, что росло бы неограниченно, поэтому у журнала
/// есть потолок и старые записи вытесняются (`save::TRACE_MAX`).
#[derive(Resource, Default)]
pub(crate) struct Trace(pub(crate) VecDeque<TraceEntry>);

/// Одна команда: на каком тике и что именно.
#[derive(Clone)]
pub(crate) struct TraceEntry {
    pub(crate) tick: u64,
    pub(crate) cmd: String,
}

/// Ступени врождённых параметров по индексу палитры `stats:` (§12.70).
///
/// Пустой ресурс = параметры ничего не делают сверх потолка навыка (§12.42), и
/// синтетические схемы живут ровно так: проводника в них нет, опасность вылазки
/// никем не режется. Это тот же приём, что пустой `SkillRules`.
#[derive(Resource, Default)]
pub(crate) struct StatRules(pub(crate) Vec<StatRule>);

#[derive(Default, Clone)]
pub(crate) struct StatRule {
    pub(crate) id: String,
    /// Значения, на которых параметр даёт ступень. Пусто — ступеней нет.
    pub(crate) steps: Vec<i32>,
}

impl StatRules {
    /// Индекс параметра по имени. Систем, которым нужен конкретный параметр,
    /// будет больше одной, и каждая знает имя, а не номер: порядок записей —
    /// дело рулсета (как `SkillRules::index_of`).
    pub(crate) fn index_of(&self, id: &str) -> Option<usize> {
        self.0.iter().position(|s| s.id == id)
    }

    /// Ступень параметра — сколько порогов пройдено. Параметра у кота может не
    /// быть вовсе (коты из ASCII-схем), это нулевая ступень, а не ошибка.
    pub(crate) fn step(&self, stat: usize, stats: Option<&Stats>) -> i32 {
        let value = stats.map_or(0, |s| s.value_of(stat));
        self.0.get(stat).map_or(0, |r| {
            r.steps.iter().filter(|&&t| value >= t).count() as i32
        })
    }
}

/// Пороги уровней по индексу домена. Пустой ресурс = навыков в мире нет, и
/// работа идёт с базовой скоростью: тесты чужих механик о навыках не знают.
#[derive(Resource, Default)]
pub(crate) struct SkillRules(pub(crate) Vec<SkillRule>);

#[derive(Default, Clone)]
pub(crate) struct SkillRule {
    pub(crate) id: String,
    pub(crate) levels: Vec<i32>,
    /// До какого уровня доводит парта. Ноль — домен не преподаётся вовсе: так
    /// живёт «Стройка», которой учиться незачем (§12.18).
    pub(crate) taught: i32,
    /// Каким врождённым параметром домен ограничен; `None` — ничем (§12.42).
    pub(crate) stat: Option<usize>,
    /// Сколько параметра нужно на 2-й, 3-й, … уровень: первый не закрыт
    /// никогда. Пусто — предела нет, все дорастают до потолка навыка.
    pub(crate) demands: Vec<i32>,
}

impl SkillRules {
    /// Индекс домена по имени. Систем работы будет больше одной, и каждая знает
    /// имя своего домена, а не его номер: порядок записей — дело рулсета.
    pub(crate) fn index_of(&self, id: &str) -> Option<usize> {
        self.0.iter().position(|s| s.id == id)
    }

    /// Уровень навыка — сколько порогов пройдено. Потолок = число порогов.
    pub(crate) fn level(&self, skill: usize, xp: i32) -> i32 {
        self.0
            .get(skill)
            .map_or(0, |s| s.levels.iter().filter(|&&t| xp >= t).count() as i32)
    }

    /// Порог следующего уровня; ноль — навык на потолке. Для полоски в UI.
    pub(crate) fn next_threshold(&self, skill: usize, xp: i32) -> i32 {
        self.0
            .get(skill)
            .and_then(|s| s.levels.iter().find(|&&t| xp < t).copied())
            .unwrap_or(0)
    }

    /// Опыт, на котором парта останавливается: порог уровня `taught`.
    ///
    /// Ноль — домену не учат (парта не поможет), и это не то же самое, что
    /// потолок навыка: обучение — вход в домен, мастерство — из домена
    /// (§12.18). Уровень выше длины списка порогов упирается в последний.
    pub(crate) fn taught_cap(&self, skill: usize) -> i32 {
        let Some(rule) = self.0.get(skill).filter(|r| r.taught > 0) else {
            return 0;
        };
        let last = rule.levels.len().saturating_sub(1);
        rule.levels
            .get((rule.taught as usize - 1).min(last))
            .copied()
            .unwrap_or(0)
    }

    /// Докуда кот с таким параметром вырастет в домене (§12.42).
    ///
    /// Первый уровень открыт всегда — предел мягкий, а не запрет (§12.19):
    /// список порогов начинается со второго. Пустые `demands` — домен
    /// параметром не ограничен, и потолок у него общий, из `levels`.
    pub(crate) fn stat_level_cap(&self, skill: usize, value: i32) -> i32 {
        let Some(rule) = self.0.get(skill) else {
            return 0;
        };
        let top = rule.levels.len() as i32;
        // Параметр и его пороги значат что-то только вместе: одно без другого —
        // это домен без предела, а не домен, закрытый на первом уровне.
        if rule.stat.is_none() || rule.demands.is_empty() {
            return top;
        }
        let reached = 1 + rule.demands.iter().filter(|&&d| d <= value).count() as i32;
        reached.min(top)
    }

    /// Опыт, выше которого коту с таким параметром копить незачем: порог его
    /// предельного уровня. У домена без параметра это последний порог, то есть
    /// общий потолок навыка (§12.17), — отдельного числа для него не заводится.
    ///
    /// Предел режет **опыт**, а не показанный уровень: иначе кот годами
    /// копил бы очки, которые никогда ни во что не превратятся, — рост,
    /// которого не видно, не существует (§12.17).
    pub(crate) fn stat_xp_cap(&self, skill: usize, value: i32) -> i32 {
        let Some(rule) = self.0.get(skill) else {
            return 0;
        };
        let cap = self.stat_level_cap(skill, value).max(1) as usize;
        rule.levels.get(cap - 1).copied().unwrap_or(0)
    }
}

/// Штампы по индексу секции `structures:` рулсета (§12.160). Ресурс-`*Rules`,
/// то есть разобранный YAML: в снимок партии не идёт никогда (инвариант 26).
#[derive(Resource, Default)]
pub(crate) struct StructureRules(pub(crate) Vec<StructureRule>);

/// Разобранный штамп: сетка индексов палитры вместо id.
#[derive(Default, Clone)]
pub(crate) struct StructureRule {
    /// `cells[row][col]`; `None` — клетку штамп не трогает.
    pub(crate) cells: Vec<Vec<Option<i16>>>,
    /// Технология, открывающая объект; пусто — доступен сразу (§12.27).
    ///
    /// Ворота **свои**, сверх ворот каждого тайла штампа: объект бывает закрыт,
    /// когда все его клетки давно открыты, — именно так лаборатория на три
    /// места становится наукой, а не подарком к первой обычной.
    pub(crate) tech: String,
}

impl StructureRule {
    /// Ширина штампа без поворота.
    pub(crate) fn width(&self) -> i32 {
        self.cells.first().map_or(0, |r| r.len() as i32)
    }

    /// Высота штампа без поворота.
    pub(crate) fn height(&self) -> i32 {
        self.cells.len() as i32
    }

    /// Клетки штампа, поставленного якорем в `anchor`: `((x, y), тайл)`.
    ///
    /// Якорь — левый верхний угол занятого прямоугольника **после** поворота,
    /// поэтому рамка превью и рамка постановки — это буквально `size(rot)` от
    /// якоря, без второй арифметики на стороне вида.
    ///
    /// Поворот по часовой стрелке; пустые ячейки сетки просто не попадают в
    /// список, поэтому Г-образный штамп не требует отдельного понятия.
    pub(crate) fn stamp(&self, anchor: (i32, i32), rot: u8) -> Vec<((i32, i32), i16)> {
        let (w, h) = (self.width(), self.height());
        let mut out = Vec::new();
        for (row, line) in self.cells.iter().enumerate() {
            for (col, cell) in line.iter().enumerate() {
                let Some(tile) = *cell else { continue };
                let (col, row) = (col as i32, row as i32);
                // Поворот на месте: (col, row) в системе повёрнутой сетки.
                let (dx, dy) = match rot % 4 {
                    1 => (h - 1 - row, col),
                    2 => (w - 1 - col, h - 1 - row),
                    3 => (row, w - 1 - col),
                    _ => (col, row),
                };
                out.push(((anchor.0 + dx, anchor.1 + dy), tile));
            }
        }
        out
    }
}

/// Свойства тайлов по индексу палитры. Ресурс, а не константы: и цена, и
/// ёмкость — контент из рулсета, как и сама палитра (§11).
#[derive(Resource, Default)]
pub(crate) struct TileRules(pub(crate) Vec<TileRule>);

#[derive(Default, Clone)]
pub(crate) struct TileRule {
    /// Цена постройки набором `(предмет, сколько)`, упорядоченным по имени
    /// предмета в рулсете: порядок обхода детерминирован (§11, §12.21).
    pub(crate) cost: Vec<(usize, i32)>,
    pub(crate) capacity: i32,
    pub(crate) rest: i32,
    /// Докуда здесь высыпаются: на этом уровне бодрости сон кончается и кот
    /// переходит в дремоту (§12.52). Ноль — до полной, по общему правилу нулей
    /// в рулсете. Близнец `rest`: у места для сна два числа — как быстро и
    /// докуда, — и второе делает гнездо лучше лежанки не только скоростью.
    pub(crate) wake: i32,
    /// Койка лазарета: сколько здоровья кот восстанавливает здесь за тик.
    /// Девятый случай той же схемы, и близнец `rest` — лечиться, как и спать,
    /// можно где угодно, лазарет лишь быстрее (§12.37).
    pub(crate) heal: i32,
    /// Шлюз: отсюда отряд уходит на миссию и сюда же возвращается. Четвёртый
    /// случай той же схемы после `capacity`, `teaches` и `rest` — комната
    /// получает смысл сверх цвета в палитре, а не новый слой карты (§12.22).
    pub(crate) gate: bool,
    /// Парта: какому домену учит эта клетка (индекс в `skills:`). `None` —
    /// не учит ничему. Пятый случай той же схемы (§12.18).
    pub(crate) teaches: Option<usize>,
    /// Лаборатория: здесь идёт работа над темой. Шестой случай той же схемы —
    /// у комнаты появляется смысл сверх цвета, а карта остаётся одним слоем.
    pub(crate) lab: bool,
    /// Мастерская: здесь идёт работа над заказом. Седьмой случай той же схемы
    /// (§12.30).
    pub(crate) shop: bool,
    /// Заставлено доверху: пройти можно, остаться нельзя (§12.35). Восьмой
    /// случай той же схемы — и первый, который говорит не о работе, а о том,
    /// что клетка вообще такое. Правило разбирается после факта (`clear_solids`),
    /// как и «два кота в одной клетке» (§12.32): проходимость оно не трогает.
    pub(crate) solid: bool,
    /// Торговый пост: без него сделку не заключить (§12.44). Девятый случай той
    /// же схемы и первый, за которым никто не работает, — лицензия, а не место
    /// работы. Товар едет к шлюзу, а не сюда.
    pub(crate) trade: bool,
    /// Сколько штук влезает в один контейнер этого поста; ноль — без предела
    /// (§12.90). Второе число у той же клетки, как `comms` при `relay`.
    ///
    /// Это предел **объёма одной сделки**, и он же переводит счётность поста из
    /// «сколько сделок разом» в «сколько товара разом»: без него автопродажа
    /// вывозила бы весь склад через единственную ячейку, и строить второй пост
    /// было бы незачем.
    pub(crate) lot: i32,
    /// Узел связи: держит одну вылазку (§12.59). Десятый случай той же схемы.
    /// Сколько узлов построено, столько отрядов база выводит разом — потолок
    /// параллельных вылазок стал стройкой, а не числом в фасаде (§12.55).
    ///
    /// Слот от дежурного не зависит: пустой узел вылазку не отменяет — иначе
    /// база без свободного кота теряла бы вылазки вовсе, то есть ровно тот
    /// тупик, которого §12.37 избегает у лечения.
    pub(crate) relay: bool,
    /// Сколько силы даёт отряду полное дежурство на этой клетке (§12.60).
    /// Второе число у той же клетки, как `wake` при `rest`. Ноль — «дежурить
    /// незачем», и раздатчик сюда никого не зовёт.
    pub(crate) comms: i32,
    /// Технология, открывающая постройку; пусто — доступен сразу (§12.27).
    pub(crate) tech: String,
    /// Зонирование, пара «тишина» (§12.157): `quiet` не встаёт боком к `noisy`.
    /// Одиннадцатый случай той же схемы — и второй после `solid`, который
    /// говорит не о работе, а о том, что клетка вообще такое.
    pub(crate) quiet: bool,
    pub(crate) noisy: bool,
    /// Зонирование, пара «чистота» (§12.157): `clean` не встаёт боком к `dirty`.
    pub(crate) clean: bool,
    pub(crate) dirty: bool,
}

impl TileRules {
    /// Свойства тайла. У пустоты (`< 0`) и неизвестного индекса всё по нулям:
    /// снос сам по себе материала не требует, он его возвращает.
    fn of(&self, tile: i16) -> Option<&TileRule> {
        (tile >= 0).then(|| self.0.get(tile as usize))?
    }

    /// Из чего строится тайл; пусто — бесплатно.
    pub(crate) fn cost_of(&self, tile: i16) -> &[(usize, i32)] {
        self.of(tile).map_or(&[], |r| &r.cost)
    }

    pub(crate) fn capacity_of(&self, tile: i16) -> i32 {
        self.of(tile).map_or(0, |r| r.capacity)
    }

    pub(crate) fn rest_of(&self, tile: i16) -> i32 {
        self.of(tile).map_or(0, |r| r.rest)
    }

    /// Докуда высыпаются на этой клетке; ноль — до полной (§12.52).
    pub(crate) fn wake_of(&self, tile: i16) -> i32 {
        self.of(tile).map_or(0, |r| r.wake)
    }

    pub(crate) fn heal_of(&self, tile: i16) -> i32 {
        self.of(tile).map_or(0, |r| r.heal)
    }

    pub(crate) fn is_gate(&self, tile: i16) -> bool {
        self.of(tile).is_some_and(|r| r.gate)
    }

    /// Какому домену учит клетка; `None` — обычный пол.
    pub(crate) fn teaches_of(&self, tile: i16) -> Option<usize> {
        self.of(tile).and_then(|r| r.teaches)
    }

    /// Можно ли на клетке **задержаться**; проходимость это не трогает (§12.35).
    pub(crate) fn is_solid(&self, tile: i16) -> bool {
        self.of(tile).is_some_and(|r| r.solid)
    }

    /// Требует тишины: не встаёт боком к шумному (§12.157).
    pub(crate) fn is_quiet(&self, tile: i16) -> bool {
        self.of(tile).is_some_and(|r| r.quiet)
    }

    /// Шумит: не пускает к себе боком того, кому нужна тишина (§12.157).
    pub(crate) fn is_noisy(&self, tile: i16) -> bool {
        self.of(tile).is_some_and(|r| r.noisy)
    }

    /// Требует чистоты (§12.157).
    pub(crate) fn is_clean(&self, tile: i16) -> bool {
        self.of(tile).is_some_and(|r| r.clean)
    }

    /// Грязнит (§12.157).
    pub(crate) fn is_dirty(&self, tile: i16) -> bool {
        self.of(tile).is_some_and(|r| r.dirty)
    }

    pub(crate) fn is_lab(&self, tile: i16) -> bool {
        self.of(tile).is_some_and(|r| r.lab)
    }

    pub(crate) fn is_shop(&self, tile: i16) -> bool {
        self.of(tile).is_some_and(|r| r.shop)
    }

    pub(crate) fn is_trade_post(&self, tile: i16) -> bool {
        self.of(tile).is_some_and(|r| r.trade)
    }

    /// Сколько влезает в контейнер этой клетки; ноль — без предела (§12.90).
    /// Ноль и есть «правила нет», как у `capacity`, `comms` и `wake`: в
    /// синтетических схемах тестов предела нет, и сделки там любого размера.
    pub(crate) fn lot_of(&self, tile: i16) -> i32 {
        self.of(tile).map_or(0, |r| r.lot)
    }

    /// Узел связи: слот одновременной вылазки (§12.59).
    pub(crate) fn is_relay_node(&self, tile: i16) -> bool {
        self.of(tile).is_some_and(|r| r.relay)
    }

    /// Сколько силы даёт отряду полное дежурство на этой клетке (§12.60).
    pub(crate) fn comms_of(&self, tile: i16) -> i32 {
        self.of(tile).map_or(0, |r| r.comms)
    }

    /// Технология, без которой тайл не построить; `None` — доступен сразу.
    /// У сноса (`tile < 0`) ворот нет: разбирать можно что угодно и всегда.
    pub(crate) fn tech_of(&self, tile: i16) -> Option<&str> {
        self.of(tile)
            .map(|r| r.tech.as_str())
            .filter(|t| !t.is_empty())
    }
}

/// Чего площадке ещё не хватает: цена тайла минус завезённое, только недостача.
/// Чего заказу ещё не хватает: цена рецепта на **все оставшиеся штуки** минус
/// уже завезённое (§12.102). Близнец `missing` у площадки, и разница ровно
/// одна — множитель `left`: у чертежа штука всегда одна.
pub(crate) fn craft_missing(rules: &CraftRules, order: &Craft) -> Vec<(usize, i32)> {
    let Some(rule) = rules.0.get(order.def) else {
        return Vec::new();
    };
    rule.cost
        .iter()
        .filter_map(|&(item, per)| {
            let need = per * order.left.max(0);
            let have = order
                .delivered
                .iter()
                .find(|&&(i, _)| i == item)
                .map_or(0, |&(_, n)| n);
            (need > have).then_some((item, need - have))
        })
        .collect()
}

/// Хватает ли завезённого на **одну** штуку: этим ворота и открываются — и
/// раздача мастера, и сама работа (§12.102).
pub(crate) fn craft_supplied(rules: &CraftRules, order: &Craft) -> bool {
    let Some(rule) = rules.0.get(order.def) else {
        return false;
    };
    rule.cost.iter().all(|&(item, per)| {
        order
            .delivered
            .iter()
            .find(|&&(i, _)| i == item)
            .map_or(0, |&(_, n)| n)
            >= per
    })
}

pub(crate) fn missing(rules: &TileRules, bp: &Blueprint) -> Vec<(usize, i32)> {
    rules
        .cost_of(bp.tile)
        .iter()
        .filter_map(|&(item, need)| {
            let have = delivered_of(&bp.delivered, item);
            (need > have).then_some((item, need - have))
        })
        .collect()
}

pub(crate) fn delivered_of(delivered: &[(usize, i32)], item: usize) -> i32 {
    delivered
        .iter()
        .find(|&&(i, _)| i == item)
        .map_or(0, |&(_, n)| n)
}

/// Записать доставку в набор площадки.
pub(crate) fn add_delivered(delivered: &mut Vec<(usize, i32)>, item: usize, count: i32) {
    match delivered.iter_mut().find(|(i, _)| *i == item) {
        Some((_, have)) => *have += count,
        None => delivered.push((item, count)),
    }
}

/// Свойства предметов по индексу палитры `items:`. Ресурс той же природы, что и
/// `TileRules`: предмет значит что-то сверх цвета, потому что у него есть
/// свойство, — а не потому, что код знает его по имени (§12.29).
#[derive(Resource, Default)]
pub(crate) struct ItemRules(pub(crate) Vec<ItemRule>);

#[derive(Default, Clone)]
pub(crate) struct ItemRule {
    /// Сколько силы предмет добавляет отряду, если надет. Ноль — обычный
    /// материал: надеть его нельзя, и в шаблон он не попадает.
    pub(crate) force: i32,
    /// Сколько сытости даёт одна съеденная штука. Ноль — предмет несъедобен, и
    /// кот к нему не пойдёт. То же свойство-переключатель, что и `force`:
    /// еда — это предмет с числом, а не отдельная сущность (§12.36).
    pub(crate) nutrition: i32,
    /// Сколько заживления за тик добавляет израсходованная аптечка (§12.47).
    /// Ноль — обычный предмет. Аптечка **ускоряет, а не открывает**: без неё
    /// лечение идёт, просто дольше.
    pub(crate) mends: i32,
    /// Технологии, без которых база **не понимает, что это** (§12.114, §12.131).
    /// Пусто — предмет понятен сразу.
    ///
    /// Ворота шире, чем «нельзя надеть», хотя начинались с надевания. Непонятый
    /// предмет не идёт в шаблон снаряжения, не кормит и не лечит — то есть ни
    /// одна механика не берёт его в дело; в окне «Склад» он стоит строкой
    /// «Ткань(?)» и умеет только лежать и продаваться.
    ///
    /// Ворота у цены (рецепт, тайл, найм) отдельно **не проверяются**: там их
    /// держит сам порядок дерева технологий, за которым следит сторож
    /// (§12.134). Рантайм-проверка в семи местах была бы семью местами, где
    /// однажды забудут восьмое.
    ///
    /// Проверяется всё это **только в раздатчиках**: снимать надетое и
    /// отбирать надкушенное не приходится, потому что технологии не забываются
    /// (§12.18).
    pub(crate) requires: Vec<String>,
}

impl ItemRules {
    /// Сила предмета; неизвестный индекс — ноль, как у тайла вне палитры.
    pub(crate) fn force_of(&self, item: usize) -> i32 {
        self.0.get(item).map_or(0, |r| r.force)
    }

    /// Сытость от одной штуки; ноль — предмет несъедобен **или ещё не понят**
    /// (§12.131). Непонятую еду кот не ест: банка без этикетки — это не паёк.
    pub(crate) fn nutrition_of(&self, item: usize, techs: &Techs) -> i32 {
        match self.understood(item, techs) {
            true => self.0.get(item).map_or(0, |r| r.nutrition),
            false => 0,
        }
    }

    /// Поняла ли база, что это за предмет (§12.131). Предмета вне палитры не
    /// бывает, но отвечаем как везде — «да»: неизвестный индекс это не запрет.
    ///
    /// Одни ворота на все механики, которые берут предмет в дело. Второй набор
    /// рядом с первым однажды разъедется, и надеть будет можно то, что нельзя
    /// съесть, без единой причины различать.
    pub(crate) fn understood(&self, item: usize, techs: &Techs) -> bool {
        self.0
            .get(item)
            .is_none_or(|r| r.requires.iter().all(|t| techs.knows(t)))
    }

    /// Открыты ли ворота на надевание (§12.114). Тонкая обёртка над
    /// `understood` — имя оставлено ради `assign_equip`, где вопрос звучит
    /// именно так.
    pub(crate) fn wearable(&self, item: usize, techs: &Techs) -> bool {
        self.understood(item, techs)
    }

    /// Аптечки палитры — индексы понятых предметов с `mends`, по возрастанию.
    /// Порядок фиксирован индексом, а не обходом: какую именно израсходуют,
    /// когда их несколько, должно быть предсказуемо (§11).
    ///
    /// Непонятая аптечка не лечит (§12.131) — и это не отнимает у базы
    /// лечение: аптечка **ускоряет, а не открывает** (§12.47), так что раненый
    /// встаёт и без неё.
    pub(crate) fn medkits<'a>(
        &'a self,
        techs: &'a Techs,
    ) -> impl Iterator<Item = (usize, i32)> + 'a {
        self.0
            .iter()
            .enumerate()
            .filter(|(_, r)| r.mends > 0)
            .filter(|&(i, _)| self.understood(i, techs))
            .map(|(i, r)| (i, r.mends))
    }

    /// Сила всего надетого на коте. Компонента нет — кот не экипирован, и это
    /// ноль, а не отсутствие данных.
    pub(crate) fn force_of_gear(&self, gear: Option<&Gear>) -> i32 {
        gear.map_or(0, |g| g.0.iter().map(|&i| self.force_of(i)).sum())
    }
}

/// Шаблон снаряжения: какие предметы кот носит (§4.2, §12.29). Один на всех и
/// задан рулсетом — редактор шаблонов это интерфейс поверх выбора, которого на
/// POC нет. Пустой ресурс = снаряжения в мире нет: так живут тесты чужих механик.
#[derive(Resource, Default)]
pub(crate) struct LoadoutRules(pub(crate) Vec<usize>);

/// Миссии из рулсета по индексу записи. Пустой ресурс = вылазок в мире нет:
/// так живут тесты чужих механик, как и с пустыми `SkillRules`/`NeedRules`.
#[derive(Resource, Default)]
pub(crate) struct MissionRules(pub(crate) Vec<MissionRule>);

#[derive(Default, Clone)]
pub(crate) struct MissionRule {
    /// Сколько котов нужно, чтобы вылазка состоялась (§12.23, §12.70).
    pub(crate) squad: usize,
    /// Сколько котов бригада может увести с собой. Равен `squad` — вилки нет,
    /// уходят ровно столько, сколько нужно (так живёт вылазка за своим).
    pub(crate) squad_max: usize,
    /// Дорога туда и обратно, в тиках; от состава не зависит (§12.70).
    pub(crate) travel: i32,
    /// Работа на месте в очках: отряд вырабатывает их сообща, по очку за тик на
    /// лапу (§12.70). Ноль = срок равен одной дороге.
    pub(crate) work: i32,
    /// Разведка: сила отряда считается по лучшему, а опасность растёт с числом
    /// лап (§12.113). Ноль лишних котов — ноль лишней заметности.
    pub(crate) stealth: bool,
    /// Сложность: с ней сравнивается сила отряда (§12.23). Ноль = удаётся всегда.
    pub(crate) danger: i32,
    /// Во сколько бодрости вылазка обходится каждому коту (провал — во всю).
    pub(crate) toll: i32,
    /// Во сколько здоровья обходится **полный провал**; частичный успех бьёт
    /// той же долей, какой недобрал добычи (§12.37). Ноль = вылазка безопасна.
    pub(crate) harm: i32,
    /// Известности за полный успех; доля добычи — та же доля известности.
    pub(crate) fame: i32,
    /// Порог известности, ниже которого за вылазку не берутся (§12.24).
    pub(crate) requires: i32,
    /// Добыча набором `(предмет, сколько)`, упорядоченным по имени предмета —
    /// как цена тайла, и по той же причине: порядок детерминирован (§12.21).
    pub(crate) loot: Vec<(usize, i32)>,
    /// Вылазка за своим: заявка принимается, только пока есть пленные, а успех
    /// возвращает их домой. Пленных сама не оставляет — даже провалившись
    /// (§12.40).
    pub(crate) rescue: bool,
    /// Чей заказ и кому он поперёк — индексы палитры фракций; `None` = ничей
    /// (нейтральная вылазка, §4.4). Два поля вместо набора `(фракция, сколько)`
    /// намеренно: набором можно было бы написать заказ, который нравится всем, —
    /// а это фракции без решения, отвергнутые §12.24 (§12.43).
    pub(crate) patron: Option<usize>,
    pub(crate) against: Option<usize>,
    /// На сколько успех двигает репутацию: заказчику вверх, пострадавшему вниз,
    /// ровно настолько же. Той же долей, что добыча, — провал не двигает вовсе.
    pub(crate) standing: i32,
    /// Пол доверия набором `(фракция, сколько)`: ниже него заказ не дают.
    /// Известность решает, дорос ли ты вообще; это — станут ли с тобой говорить
    /// именно эти (§12.43).
    pub(crate) needs: Vec<(usize, i32)>,
}

/// Известность базы: копится от вылазок и открывает доступ к следующим.
///
/// **Только растёт и только открывает** (§12.24). Не валюта: платят предметами.
/// Ворота, которые могут закрыться, читаются как поломка — игрок не поймёт,
/// почему доступная вчера вылазка сегодня исчезла.
#[derive(Resource, Default)]
pub(crate) struct Fame(pub(crate) i32);

/// Фракции из рулсета по индексу записи. Пустой ресурс = фракций в мире нет:
/// так живут тесты чужих механик, как живут они без вылазок и без голода.
#[derive(Resource, Default)]
pub(crate) struct FactionRules(pub(crate) Vec<FactionRule>);

impl FactionRules {
    /// Предел репутации у фракции; за пределами палитры — ноль, то есть без
    /// предела: неизвестную фракцию ядро не ограничивает, а просто не знает.
    pub(crate) fn span_of(&self, faction: usize) -> i32 {
        self.0.get(faction).map_or(0, |f| f.span)
    }
}

#[derive(Default, Clone)]
pub(crate) struct FactionRule {
    /// Предел репутации **в обе стороны**: дно достижимо и конечно, а значит и
    /// дорога назад имеет измеримую длину. Ноль = без предела.
    pub(crate) span: i32,
    /// Тиков от заказа до поставки (§12.44).
    pub(crate) lead: i32,
    /// Наценка на покупку, в процентах: купить дороже, чем продать.
    pub(crate) spread: i32,
    /// Насколько репутация двигает курс при полном доверии, в процентах.
    pub(crate) favor: i32,
    /// Длина одной фазы расписания в тиках. Ноль = курс не меняется.
    pub(crate) period: u64,
    /// Расписание базовых курсов: `(предмет, строка)`, упорядоченное по индексу
    /// предмета — как цена тайла и добыча, и по той же причине (§11).
    /// Предмета в списке нет — фракция им не торгует.
    pub(crate) prices: Vec<(usize, PriceLine)>,
}

impl FactionRule {
    /// Строка прайса по предмету; `None` — фракция им не торгует.
    pub(crate) fn price_of(&self, item: usize) -> Option<&PriceLine> {
        self.prices
            .iter()
            .find(|(i, _)| *i == item)
            .map(|(_, line)| line)
    }
}

/// Строка прайса в мире: расписание курса и ворота на товар (§12.150).
///
/// Ворота здесь только лежат — считает их `trade::offer_gates`, одним
/// выражением на фасад и снимок (инвариант 14), как `quote` считает цену.
#[derive(Default, Clone)]
pub(crate) struct PriceLine {
    /// Базовый курс по фазам; пусто — торговли нет, как и отсутствия строки.
    pub(crate) phases: Vec<i32>,
    /// Порог известности: дорос ли ты до этого товара вообще (§12.24).
    pub(crate) requires: i32,
    /// Пол доверия: пары `(фракция, сколько)`, упорядоченные по индексу
    /// фракции — как `needs` у вылазки и кандидата, и по той же причине (§11).
    pub(crate) needs: Vec<(usize, i32)>,
}

/// Котоденьги — валюта внешнего рынка и **только его** (§12.44).
///
/// Входят единственным путём (продажа) и уходят единственным (покупка);
/// напечатать их нельзя. Отсюда главное свойство торговли: она не создаёт
/// богатства, а меняет его состав — и всегда с убытком, потому что купить
/// дороже, чем продать (спред). Поэтому она не обесценивает ни вылазку, ни
/// мастерскую.
///
/// **Это не четвёртая шкала-ворота.** Известность, технология и репутация
/// открывают доступ и не тратятся (§12.24, §12.27, §12.43); деньги, наоборот,
/// и копятся, и тратятся — и читается это нормально ровно потому, что они счёт,
/// а не ворота: «потратил, теперь не хватает» никто багом не назовёт.
///
/// За найм, науку и производство по-прежнему платит склад **предметами**
/// (§12.24): деньгами торгуют, а не живут.
#[derive(Resource, Default)]
pub(crate) struct Money(pub(crate) i32);

/// Репутация базы у каждой фракции: индекс — номер записи в `factions:`
/// (§12.43).
///
/// Третья шкала-ворота и **единственная знаковая**. Известность и технология
/// отвечают «насколько высоко» и только растут (§12.24, §12.27); эта отвечает
/// «от кого» и потому умеет закрывать. Честной её держат три правила, и
/// работают они только вместе: двигает её **только выполненный заказ** (той же
/// долей, что добычу, — значит провал не двигает вовсе), она **никогда не
/// платит** (валюта по-прежнему предметы), и **дорога назад есть всегда**.
#[derive(Resource, Default)]
pub(crate) struct Standing(pub(crate) Vec<i32>);

impl Standing {
    pub(crate) fn value_of(&self, faction: usize) -> i32 {
        self.0.get(faction).copied().unwrap_or(0)
    }

    /// Подвинуть репутацию, не выпуская её за предел. Правило клампа живёт
    /// здесь одним местом: разойдись `launch`, `hire` и снапшот в трактовке
    /// предела — игрок увидел бы кнопку, которую ядро отклоняет (§12.24).
    pub(crate) fn add(&mut self, faction: usize, delta: i32, span: i32) {
        if self.0.len() <= faction {
            self.0.resize(faction + 1, 0);
        }
        let moved = self.0[faction] + delta;
        self.0[faction] = if span > 0 {
            moved.clamp(-span, span)
        } else {
            moved
        };
    }

    /// Хватает ли доверия на весь набор `(фракция, сколько)`; пустой набор
    /// покрыт всегда — как пустой набор технологий (§12.27).
    pub(crate) fn covers(&self, needs: &[(usize, i32)]) -> bool {
        needs
            .iter()
            .all(|&(faction, need)| self.value_of(faction) >= need)
    }
}

/// Темы исследования из рулсета по индексу записи. Пустой ресурс = изучать
/// нечего: так живут тесты чужих механик.
#[derive(Resource, Default)]
pub(crate) struct ResearchRules(pub(crate) Vec<ResearchRule>);

#[derive(Default, Clone)]
pub(crate) struct ResearchRule {
    /// Он же id технологии на выходе: у темы и результата одно имя, второе
    /// значило бы два списка, которые однажды разойдутся.
    pub(crate) id: String,
    /// Уровень «Науки», ниже которого кот за тему не берётся вовсе. Это
    /// **допуск**, а не скорость (§12.18): без навыка нельзя, а не медленно.
    pub(crate) level: i32,
    /// Очки работы, как у чертежа: скорость даёт навык исполнителя (§12.17).
    pub(crate) work: i32,
    /// Чем платим — набор `(предмет, сколько)` со склада, как у найма (§12.24).
    /// Списывается в момент заявки: это **плата**, а не материал.
    pub(crate) cost: Vec<(usize, i32)>,
    /// Что привезти в лабораторию, чтобы вскрыть (§12.133). Пусто — тема
    /// обычная. Это **материал**: его возят ногами, как на станок (§12.102),
    /// и до приезда тема просто ждёт.
    pub(crate) specimen: Vec<(usize, i32)>,
    /// Что тема даёт кучей на клетку лаборатории, кроме технологии (§12.133).
    /// Одноразово — тема изучается ровно раз.
    pub(crate) gives: Vec<(usize, i32)>,
    /// Технологии, без которых темы не существует: дерево в §4.3.
    pub(crate) requires: Vec<String>,
}

/// Чего теме ещё не хватает: образец минус завезённое, только недостача.
/// Дословно `craft_missing` (§12.102, §12.133), минус множитель штук: тема
/// одноразова, и партии у неё не бывает.
pub(crate) fn topic_missing(rules: &ResearchRules, topic: &Research) -> Vec<(usize, i32)> {
    let Some(rule) = rules.0.get(topic.def) else {
        return Vec::new();
    };
    rule.specimen
        .iter()
        .filter_map(|&(item, need)| {
            let have = topic
                .delivered
                .iter()
                .find(|&&(i, _)| i == item)
                .map_or(0, |&(_, n)| n);
            (need > have).then_some((item, need - have))
        })
        .collect()
}

/// Завезён ли образец целиком: этим и открывается раздача учёного (§12.133).
/// Близнец `craft_supplied`; тема без `specimen` снабжена всегда.
pub(crate) fn topic_supplied(rules: &ResearchRules, topic: &Research) -> bool {
    topic_missing(rules, topic).is_empty()
}

/// Рецепты из рулсета по индексу записи. Пустой ресурс = производства в мире
/// нет: так живут тесты чужих механик.
#[derive(Resource, Default)]
pub(crate) struct CraftRules(pub(crate) Vec<CraftRule>);

#[derive(Default, Clone)]
pub(crate) struct CraftRule {
    /// `id` записи в рулсете. **Ядро по нему ничего не ищет** — рецепт
    /// адресуется индексом палитры, как предмет и тайл, — но сторожам на боевом
    /// контенте он нужен по тому же доводу, что `id` у темы: порядок записей в
    /// YAML и есть индекс, и зашитый в тест числом он разъезжается **молча**,
    /// стоит дописать рецепт в середину списка (на этом уже попался
    /// `the_shipped_ruleset_opens_the_cloth_branch_in_order`).
    ///
    /// Отсюда и `cfg_attr`: читает поле только `recipe_index`, а он под
    /// `#[cfg(test)]`, — в боевой сборке оно честно мертво. Идиома та же, что у
    /// `Selling::rule_of`. У `ResearchRule::id` этого нет и не нужно: там `id`
    /// темы — он же `id` технологии на выходе, и его читает само ядро.
    #[cfg_attr(not(test), allow(dead_code))]
    pub(crate) id: String,
    /// Очки работы на одну штуку, как у чертежа (§12.17).
    pub(crate) work: i32,
    /// Чем платим за штуку — набор `(предмет, сколько)` со склада, упорядоченный
    /// по имени предмета, как цена тайла (§12.21).
    pub(crate) cost: Vec<(usize, i32)>,
    /// Что выходит: набор `(предмет, сколько)`. Ложится кучей под ноги мастеру,
    /// как добыча на шлюз, — дальше её разносит обычная уборка (§12.30).
    pub(crate) gives: Vec<(usize, i32)>,
    /// Технологии, без которых рецепта не существует: ворота те же, что у тайла
    /// (§12.27). Допуска по навыку у производства нет — навык только ускоряет.
    pub(crate) requires: Vec<String>,
    /// Разбор (§12.114): для ядра обычный рецепт, для вида — кнопка в строке
    /// **входного** предмета и отсутствие порога. Ядро знает о нём ровно
    /// затем, чтобы отказать `set_stock`: правило «держать ткани до N» рвало бы
    /// надетые комбинезоны без спроса, а решение необратимо.
    pub(crate) salvage: bool,
}

/// Изученные технологии. **Только растёт и только открывает** — та же шкала-
/// ворота, что и известность (§12.24): технология, которая может пропасть,
/// закрыла бы уже доступное, и игрок прочтёт это как баг.
#[derive(Resource, Default)]
pub(crate) struct Techs(pub(crate) Vec<String>);

impl Techs {
    pub(crate) fn knows(&self, tech: &str) -> bool {
        self.0.iter().any(|t| t == tech)
    }

    /// Известны ли все технологии набора; пустой набор известен всегда.
    pub(crate) fn covers(&self, techs: &[String]) -> bool {
        techs.iter().all(|t| self.knows(t))
    }
}

/// События таймлайна по индексу записи. Пустой ресурс = мир ничего не делает
/// сам: так живут тесты чужих механик.
#[derive(Resource, Default)]
pub(crate) struct TimelineRules(pub(crate) Vec<EventRule>);

/// Имени у правила нет: событие адресуется индексом записи, как миссия и тема,
/// а `id` из рулсета — это ключ контента, и второе его хранилище было бы
/// ещё одним местом, где он может разойтись.
#[derive(Default, Clone)]
pub(crate) struct EventRule {
    /// Тик, на котором событие происходит: дата — это номер тика (§12.28).
    pub(crate) at: u64,
    /// За сколько тиков до срока проступают детали («туман предзнания», §4.6).
    pub(crate) reveal: u64,
    /// Технологии, к которым база должна успеть; пусто — событие безусловно.
    pub(crate) requires: Vec<String>,
    /// Что ляжет кучей на шлюз, если база готова.
    pub(crate) gift: Vec<(usize, i32)>,
    pub(crate) fame: i32,
    /// Чего стоит неготовность — бодрости каждому коту на базе.
    pub(crate) toll: i32,
}

/// Что уже случилось: журнал сработавших событий, в порядке дат.
///
/// **Только растёт**, как известность и технологии (§12.24, §12.27): прошедшее
/// событие не отменяется. Он же признак «сработало» — второго списка не
/// заводим, иначе однажды разойдутся.
#[derive(Resource, Default)]
pub(crate) struct Chronicle(pub(crate) Vec<Happened>);

#[derive(Clone, Copy)]
pub(crate) struct Happened {
    /// Индекс записи в `timeline:`.
    pub(crate) def: usize,
    /// Была ли база готова — этим и различаются два исхода.
    pub(crate) ready: bool,
}

impl Chronicle {
    pub(crate) fn happened(&self, def: usize) -> Option<Happened> {
        self.0.iter().copied().find(|h| h.def == def)
    }
}

/// Цели партии из рулсета по индексу записи (§12.58). Пустой ресурс = целей нет:
/// так живут тесты чужих механик, как живут они без вылазок и без рынка.
#[derive(Resource, Default)]
pub(crate) struct GoalRules(pub(crate) Vec<GoalRule>);

impl GoalRules {
    /// Сколько целей идёт в счёт «Цели 3/7»: только обязательные (§12.58).
    pub(crate) fn required(&self) -> usize {
        self.0
            .iter()
            .filter(|g| g.kind == GoalKind::Required)
            .count()
    }
}

/// Что цель значит для партии. Статусов **три**, а не два (§12.158).
///
/// До срока ролей было ровно две — «держит финал» и «её не существует, пока не
/// взята», — и вызову на самопроверку не годится ни одна. Обязательная со
/// сроком означала бы, что партию можно проиграть по времени, а такого исхода в
/// игре нет ни одного (§12.5, §12.37, §12.40). Скрытая не даёт к сроку
/// целиться: о ней узнают, уже опоздав, — то есть срок в ней не значит ничего.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub(crate) enum GoalKind {
    /// Видна с начала, идёт в счёт «Цели 3/7» и держит финал.
    Required,
    /// Видна с начала, но в счёт не идёт: вызов, а не программа партии.
    Optional,
    /// Не показывается, пока не взята. Для целей, которых нельзя требовать, —
    /// «вернуть кота из плена»: требовать её значило бы требовать провалить
    /// вылазку (§12.58).
    Hidden,
}

#[derive(Clone)]
pub(crate) struct GoalRule {
    /// Условия, и их **список**, а не одно (§12.158). «Набрать столько-то и
    /// дойти до такой-то репутации» — одно достижение, а не два: разложенное на
    /// две цели оно стало бы двумя галочками, которые берутся порознь, и общий
    /// срок им уже не назначить. Выполнены обязаны быть **все**.
    pub(crate) tests: Vec<GoalTest>,
    pub(crate) kind: GoalKind,
    /// Последний тик, на котором цель ещё можно взять; `None` — срока нет.
    ///
    /// **Просроченная цель не проигрывает партию, она просто не даётся**
    /// (§12.158). Это единственная форма, в которой дедлайн выразим, не заводя
    /// нового класса исхода: не успел — не получил, мир идёт дальше.
    pub(crate) before: Option<u64>,
}

/// Условие цели. **Закрытый** словарь: произвольный предикат в YAML невыразим,
/// и форм ровно столько, сколько используется — мёртвых не заводим.
///
/// Делится надвое, и путать половины нельзя (§12.58):
///   * **состояние** — каков мир прямо сейчас. Расходуемо: лом тратят, аптечку
///     переводят на раненого.
///   * **журнал** — что случилось хоть раз. Не расходуемо и не выводится из
///     состояния.
///
/// Правило выбора: **ярлык описывает поступок → условие обязано быть журнальным.**
/// Состояние на месте поступка врёт дважды — засчитывает чужое (аптечку купили,
/// а не сделали) и не засчитывает своё (заработали и потратили).
/// ⚠️ Наружу едет **сам словарь** (в `meta.goals[].parts`, §12.159), тегом и
/// содержимым: вид называет условие словом, а порядок и состав связки остаются
/// одним источником — этим перечислением. Собери вид список сам из полей
/// `GoalDef`, и он разошёлся бы с ядром на первой же новой форме условия, а
/// даты в поздравлении встали бы не напротив своих строк.
#[derive(Clone, Debug, Serialize)]
#[serde(tag = "kind", content = "need")]
pub(crate) enum GoalTest {
    /// Состояние: столько-то клеток этого тайла построено.
    Tile(usize, i32),
    /// Состояние: столько-то предметов **на складе** — том самом, которым платят
    /// (§12.24, §12.53). Пол и лапы не в счёт.
    Stored(Vec<(usize, i32)>),
    /// Состояние: технология изучена.
    Tech(String),
    /// Состояние: столько-то котов у базы. Ушедшие и пленные считаются — они
    /// твои; §12.22 про то, что мир не касается ушедших, — это про усталость и
    /// голод, а не про принадлежность.
    Cats(i32),
    /// Журнал: эта вылазка завершена успешно хоть раз.
    Raid(usize),
    /// Журнал: по этому рецепту сделана хоть одна штука. Именно журнал, а не
    /// «предмет есть на базе»: тот засчитал бы и покупку, и добычу, а смысл
    /// цели — в мастерской.
    Craft(usize),
    /// Журнал: столько-то котоденег заработано продажей **за всю партию**.
    /// Состояние (`Money`) тут не годится: заработал и потратил — цель не
    /// закрылась бы никогда.
    Earned(i32),
    /// Состояние: столько-то котоденег **в казне сейчас** (§12.159).
    ///
    /// Состояние, а не журнал `Earned`, и это осознанно: «изобилие» — это то,
    /// что у базы есть в руках, и расходуемость тут не дефект, а цена. Заодно
    /// условие спорит с соседями по связке: нанять всех котов — это трата.
    Money(i32),
    /// Состояние: репутация у этих фракций не ниже названной (§12.158).
    ///
    /// Состояние, а не журнал, и это не оговорка: репутация **знаковая** и умеет
    /// падать (§12.43), значит «доходил хоть раз» и «стоишь сейчас» — разные
    /// вещи, а достижением тут названо второе. Набором, как `Stored`, по той же
    /// причине: у цели на развилку обязаны быть названы обе стороны, иначе она
    /// выбирает сторону за игрока.
    Standing(Vec<(usize, i32)>),
}

/// Лента новостей: что открылось и что закрылось (§12.120).
///
/// До неё игрок узнавал о новом заказе, кандидате или теме, только заглянув в
/// список руками — мир об этом молчал. Считает ленту **наблюдатель** (`note_news`
/// в `Sim::tick`, после цепочки), дословно как `check_goals` (§12.58): крючков по
/// местам, где ворота проверяются, нет ни одного — это десять мест вместо одного,
/// и однажды одно забудут.
///
/// ⚠️ **Это не журнал в смысле §12.58.** `Raids`, `Crafted` и `Earned` только
/// растут, потому что на них смотрят цели: потраченный лом не отнимает «Кладовую».
/// Здесь смотрит человек, и новость, которую он уже прочитал, ценности не имеет, —
/// поэтому лента ограничена (`NEWS_MAX`) и старое из неё вытесняется. Заводить
/// цель на «открылось столько-то» через неё **нельзя**: возьми она хвост ленты за
/// правду, и цель закрывалась бы или нет в зависимости от того, что случилось
/// после. Такой цели нужен свой журнал, по правилам §12.58.
///
/// Базовая линия (`open`) — часть состояния мира и уходит в снимок: без неё
/// загруженная партия объявила бы новостью всё, что у базы и так открыто.
#[derive(Resource, Default, Clone)]
pub(crate) struct News {
    /// Было ли открыто на прошлом тике — по виду (`NewsKind`) и записи палитры.
    pub(crate) open: Vec<Vec<bool>>,
    /// Сама лента, от старого к новому.
    pub(crate) feed: Vec<Note>,
    /// Базовая линия снята. Стартовая доступность — не новость: партия
    /// начинается с открытой первой ступени, и говорить о ней нечего.
    pub(crate) started: bool,
}

/// Сколько новостей лента помнит. Не политика показа — её задаёт вид по
/// `news:` из рулсета, — а предел роста: без него оскорблённая и прощённая
/// фракция за сотню вылазок насыпала бы сюда сотни записей, и все они каждый
/// кадр ехали бы в снимок.
pub(crate) const NEWS_MAX: usize = 64;

/// Шесть реестров, о которых говорит лента. Ровно те, что открываются
/// шкалами-воротами (инвариант 18) и стоят списком: заказ вылазки, кандидат,
/// тема, рецепт, **тайл палитры**, **предмет**. Порядок значим — он же индекс в
/// `News::open`.
///
/// ⚠️ **Тайл попал сюда вместе с §12.126.** Пока закрытая технологией постройка
/// стояла в палитре погашенной, её появление игрок видел сам — кнопка гасла и
/// зажигалась на месте. Спрятав её, мы сделали открытие невидимым: список
/// молча становится длиннее, и заметить это можно, только пересчитав его до и
/// после. Новость и есть то, что вернуло событию голос.
///
/// ⚠️ **Предмет попал сюда вместе с §12.136, и это отмена решения §12.131.**
/// Там шестой вид был отвергнут доводом «приезд кучи — и так самое заметное
/// событие в игре». Довод оказался неверным: игрок в этот момент смотрит на
/// карту и на котов, куча у шлюза среди других куч не читается как «в мире
/// появился новый вид вещей», а окно «Склад» закрыто. То есть ровно тот случай,
/// из-за которого §12.126 завела новость о постройке, — **появление, которого
/// не видно**.
///
/// Ворота у него — шкала `Seen` (§12.131), и закрытий не бывает по той же
/// причине, что у рецепта: она только растёт. Базовую линию снимает первый же
/// `note_news`, а `Seen` к этому моменту уже отмечен конструктором — поэтому
/// стартовый склад новостью не становится.
///
/// ⚠️ **У рецепта закрытий не бывает.** Его ворота — одна технология, а
/// технологии не забываются (§12.18), значит `recipe_is_open` только растёт.
/// Это не забытая ветка, а правда о мире: «Комбинезон разучились делать» —
/// событие, которого в игре нет. Тем же свойством обладают тема и тайл; у
/// заказа и кандидата вторые ворота — репутация, и она умеет падать (§12.43).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub(crate) enum NewsKind {
    Raid,
    Recruit,
    Topic,
    Recipe,
    Tile,
    Item,
}

impl NewsKind {
    pub(crate) const ALL: [NewsKind; 6] = [
        NewsKind::Raid,
        NewsKind::Recruit,
        NewsKind::Topic,
        NewsKind::Recipe,
        NewsKind::Tile,
        NewsKind::Item,
    ];

    /// Индекс вида в `News::open` и число, которым он едет в снимок.
    pub(crate) fn index(self) -> usize {
        match self {
            NewsKind::Raid => 0,
            NewsKind::Recruit => 1,
            NewsKind::Topic => 2,
            NewsKind::Recipe => 3,
            NewsKind::Tile => 4,
            NewsKind::Item => 5,
        }
    }

    pub(crate) fn from_index(i: usize) -> Option<NewsKind> {
        NewsKind::ALL.get(i).copied()
    }
}

/// Одна новость: что за пункт, открылся он или закрылся и на каком тике.
///
/// Тик едет наружу, потому что возраст новости считает **вид** — и считает его
/// в тиках, а не в секундах: на паузе мир стоит, значит стопка не тает, и игрок
/// разбирает её неспеша. Wall-clock означал бы, что пауза останавливает игру не
/// целиком, — тот же секундомер, которому отказали §12.40 и §12.86.
#[derive(Clone, Copy)]
pub(crate) struct Note {
    pub(crate) kind: NewsKind,
    /// Индекс записи в палитре своего вида.
    pub(crate) def: usize,
    /// `true` — открылось, `false` — закрылось.
    pub(crate) opened: bool,
    pub(crate) at: u64,
}

impl News {
    /// Пометить перемену. Лента ограничена, старое вытесняется — см. шапку типа.
    pub(crate) fn push(&mut self, kind: NewsKind, def: usize, opened: bool, at: u64) {
        self.feed.push(Note {
            kind,
            def,
            opened,
            at,
        });
        if self.feed.len() > NEWS_MAX {
            let cut = self.feed.len() - NEWS_MAX;
            self.feed.drain(..cut);
        }
    }

    /// Была ли запись открыта на прошлом тике. Неизвестная — закрыта: базовую
    /// линию снимает первый же тик, и разрастись список видов не может.
    pub(crate) fn was_open(&self, kind: NewsKind, def: usize) -> bool {
        self.open
            .get(kind.index())
            .and_then(|v| v.get(def))
            .copied()
            .unwrap_or(false)
    }

    pub(crate) fn set_open(&mut self, kind: NewsKind, def: usize, open: bool) {
        while self.open.len() < NewsKind::ALL.len() {
            self.open.push(Vec::new());
        }
        let row = &mut self.open[kind.index()];
        while row.len() <= def {
            row.push(false);
        }
        row[def] = open;
    }
}

/// Взятые цели, в порядке взятия. **Только растёт**: условие расходуемо, а
/// поступок нет, — потраченный лом не отнимает «Кладовую» (§12.58).
#[derive(Resource, Default)]
pub(crate) struct Goals(pub(crate) Vec<Taken>);

#[derive(Clone)]
pub(crate) struct Taken {
    /// Индекс записи в `goals:`.
    pub(crate) def: usize,
    /// Тик, на котором условие стало истинным: панель разворачивает его в «день 3».
    pub(crate) at: u64,
    /// С какого тика держалось каждое условие связки, в порядке `GoalRule::tests`
    /// (§12.159). **Замораживается в момент взятия**: дальше склад тратят, а
    /// репутация падает, и живая отметка к этому времени уже снята.
    pub(crate) parts: Vec<u64>,
}

impl Goals {
    pub(crate) fn taken(&self, def: usize) -> Option<&Taken> {
        self.0.iter().find(|t| t.def == def)
    }
}

/// С какого тика держится каждое условие каждой цели; `None` — не держится
/// сейчас (§12.159). Внешний индекс — цель, внутренний — условие в её связке.
///
/// **Отметка ставится, когда условие стало истинным, и снимается, когда
/// перестало.** Не «когда впервые сошлось»: лом тратят, репутация падает, и
/// «набрал ещё в день 12», сказанное про склад, который потом слили и набрали
/// заново, — это неправда о том самом, чем игрок гордится. Цель берётся, когда
/// держатся все разом, и дата у каждой части значит ровно это.
#[derive(Resource, Default)]
pub(crate) struct GoalHolds(pub(crate) Vec<Vec<Option<u64>>>);

/// Журнал: вылазки, завершённые успешно хоть раз, по индексу записи в `missions:`.
///
/// Пишется **ровно в одном месте** — `run_missions`, там же, где начисляется
/// известность: это единственный момент, когда вылазка засчитана. Только растёт.
#[derive(Resource, Default)]
pub(crate) struct Raids(pub(crate) Vec<usize>);

/// Журнал: рецепты, по которым сделана хоть одна штука, по индексу в `recipes:`.
///
/// Пишется **ровно в одном месте** — `work_craft`, там же, где готовое ложится
/// под ноги мастеру. Только растёт.
#[derive(Resource, Default)]
pub(crate) struct Crafted(pub(crate) Vec<usize>);

/// Журнал: сколько котоденег заработано продажей за всю партию.
///
/// Пишется **ровно в одном месте** — `work_hauls`, там же, где деньги капают
/// поштучно по факту сдачи (§12.44). Только растёт, тратой не уменьшается: это
/// и отличает его от `Money`.
#[derive(Resource, Default)]
pub(crate) struct Earned(pub(crate) i32);

/// Кандидаты на найм по индексу записи в рулсете. Пустой ресурс = нанимать
/// некого: так живут тесты чужих механик.
#[derive(Resource, Default)]
pub(crate) struct RecruitRules(pub(crate) Vec<RecruitRule>);

#[derive(Default, Clone)]
pub(crate) struct RecruitRule {
    /// Он же `UnitId` будущего кота: нанять дважды одного и того же нельзя,
    /// и проверяется это по самому коту, а не по отдельному списку нанятых.
    pub(crate) id: String,
    pub(crate) sprite: String,
    pub(crate) requires: i32,
    /// Чем платим — набор `(предмет, сколько)`, упорядоченный по имени
    /// предмета, как цена тайла и добыча (§12.21).
    pub(crate) cost: Vec<(usize, i32)>,
    /// Стартовый опыт: `(домен, очки)`.
    pub(crate) skills: Vec<(usize, i32)>,
    /// Врождённые параметры: `(параметр, сколько)` (§12.42). Опыт кандидат
    /// доберёт работой, а это — то, чего он не доберёт никогда, и ровно
    /// поэтому игрок на него смотрит.
    pub(crate) stats: Vec<(usize, i32)>,
    pub(crate) perks: Vec<String>,
    /// Пол доверия: `(фракция, сколько)`. Только ворота — найм репутацию не
    /// двигает, это покупка, а не поступок (§12.43).
    pub(crate) needs: Vec<(usize, i32)>,
}

/// Свойства кота, общие для всех и заданные рулсетом.
///
/// Ресурс, а не разовое чтение при старте: новичок с найма собирается по тем же
/// правилам, что и стартовая тройка, и второе место для этих чисел означало бы
/// кота, у которого лапы другого размера (§12.24).
#[derive(Resource, Default)]
pub(crate) struct UnitRules {
    /// Базовый объём лап; перк «Носильщик» удваивает. Ноль = предела нет.
    pub(crate) carry: i32,
}

/// Правила усталости из рулсета. `max = 0` — механика выключена целиком.
#[derive(Resource, Default)]
pub(crate) struct NeedRules {
    pub(crate) max: i32,
    /// Базовый расход бодрости за тик бодрствования (§12.70). Ступень
    /// «Выносливости» вычитается из него: кто дольше держится, тот чаще в поле.
    ///
    /// Ноль — расход не задан, и берётся единица, как было до §12.70: так живут
    /// синтетические схемы, где выносливость никого не различает.
    ///
    /// С §12.99 это ставка **работы** — самая дорогая из трёх, и потому именно
    /// она отвечает за сутки (`day = max / drain`, §12.46): сутки — это день
    /// кота, который весь день работал.
    pub(crate) drain: i32,
    /// Расход за тик ходьбы (§12.99). Ноль — как `drain`, то есть ставка одна
    /// на все состояния, как было до §12.99.
    pub(crate) walk: i32,
    /// Расход за тик простоя (§12.99): кот стоит, и дела у него нет. Ноль — как
    /// `drain`. Лежащий (спит или дремлет) не тратит вовсе, и своего числа у
    /// него поэтому нет: ноль — это не ставка, а отсутствие расхода.
    pub(crate) idle: i32,
    /// Порог, ниже которого свободный кот уходит спать сам.
    pub(crate) tired: i32,
    /// Порог, ниже которого кот бросает начатое и уходит спать. Ноль — второго
    /// порога нет, и кот работает до нуля бодрости, как было до §12.33.
    pub(crate) critical: i32,
    /// Восстановление вне лежанки: спать можно где угодно, просто дольше.
    pub(crate) floor: i32,
    /// Докуда высыпаются вне лежанки (§12.52). Ноль — до полной, как было до
    /// потолков. Ниже `tired` он значит «на полу можно только отлежаться, чтобы
    /// доползти до кровати», и это то, что делает зону отдыха обязательной, а
    /// не удобной.
    pub(crate) floor_wake: i32,
}

/// Правила голода из рулсета. `max = 0` — механика выключена целиком.
///
/// Отдельный ресурс, а не поля в `NeedRules`: у голода своя шкала, свой порог и
/// своя цена, а общего с усталостью у них ровно одно — то, что обе тикают
/// (§12.36). Слитые в одну структуру, они бы слиплись и в тестах: включить
/// усталость, не включив голод, стало бы невозможно.
#[derive(Resource, Default)]
pub(crate) struct FoodRules {
    pub(crate) max: i32,
    /// Порог, ниже которого свободный кот идёт есть сам. Второго порога нет
    /// намеренно: с работы голодного уводит бодрость, а не голод (§12.36).
    pub(crate) hungry: i32,
    /// Во сколько раз быстрее тратится бодрость на пустой желудок. Это вся цена
    /// голода: он стоит сил, а не жизни (§12.10). Ноль или единица — даром.
    pub(crate) starve: i32,
}

/// Правила здоровья из рулсета. `max = 0` — механика выключена целиком: коты не
/// ранятся, лечиться не ходят.
///
/// Отдельный ресурс, а не поля в `NeedRules`, по той же причине, что и у голода
/// (§12.36): своя шкала, свой порог и своя цена, а включаться они должны порознь.
#[derive(Resource, Default)]
pub(crate) struct HealthRules {
    pub(crate) max: i32,
    /// Порог, ниже которого кот выбывает: бросает начатое, ложится лечиться и
    /// не берётся в отряд. Порог **один** — второго нет намеренно (§12.37).
    pub(crate) hurt: i32,
    /// Заживление за тик вне лазарета: раны затягиваются сами, просто дольше.
    /// Тот же `floor`, что у сна, и с тем же смыслом — цена базы без лазарета.
    pub(crate) mend: i32,
}
